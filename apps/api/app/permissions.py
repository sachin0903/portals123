"""Canonical permission registry — the single source of truth for RBAC permissions.

Declare every permission ONCE here. From here it flows to:
  - the DB catalogue (`auth.permissions`) via ``sync_permissions()`` (idempotent upsert, run on
    app startup) — so there are no hand-written SQL seed/delta INSERTs to keep in step;
  - Python enforcement — ``auth.require_permission`` accepts these ``Permission`` constants;
  - the portals' typed TS constants — generated by ``scripts/generate_permissions_ts.py`` into
    ``@graphene/api-client`` (CI fails on drift, like the OpenAPI client).

Taxonomy: every resource gets ``read`` + ``write``; **``write`` implies ``read``** at check time
(see ``auth.require_permission`` / the TS ``can``). Bigger features add extra named actions via
``extra=`` (e.g. ``listings:export``). ``system`` is the global superuser — it bypasses every check.
Add a permission by adding a line here; nothing else needs editing to register it.
"""

from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession


@dataclass(frozen=True)
class Permission:
    slug: str
    name: str
    resource: str
    action: str
    portal: str  # 'client' | 'platform' | 'operations' — groups the RBAC UI
    description: str

    def __str__(self) -> str:  # so a constant can stand in for its slug in f-strings/queries
        return self.slug


_ALL: list[Permission] = []


def _reg(p: Permission) -> Permission:
    _ALL.append(p)
    return p


def _resource(
    resource: str,
    portal: str,
    label: str,
    *,
    read: str,
    write: str,
    extra: dict[str, tuple[str, str]] | None = None,
) -> dict[str, Permission]:
    """Register a resource's ``read`` + ``write`` (and any ``extra`` {action: (name, desc)}).
    Returns {action: Permission} so callers can pull the ones they need."""
    perms = {
        "read": _reg(
            Permission(f"{resource}:read", f"View {label}", resource, "read", portal, read)
        ),
        "write": _reg(
            Permission(f"{resource}:write", f"Manage {label}", resource, "write", portal, write)
        ),
    }
    for action, (name, desc) in (extra or {}).items():
        perms[action] = _reg(
            Permission(f"{resource}:{action}", name, resource, action, portal, desc)
        )
    return perms


