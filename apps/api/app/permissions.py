# Everything, in declaration order — what sync_permissions upserts and the TS generator emits.
ALL: tuple[Permission, ...] = tuple(_ALL)

# Operations-portal slugs, including ``system``. A Graphene role may carry these (the operations
# tenant is allowed to grant them) AND be attached to a platform membership; they must not leak
# into a firm-portal session or every ``can()`` / ``require_permission`` ignores the firm toggles.
OPERATIONS_SLUGS: frozenset[str] = frozenset(p.slug for p in ALL if p.portal == "operations")


def satisfies(held: set[str], required: str) -> bool:
    """Does a set of held permission slugs satisfy a required one? ``system`` satisfies anything;
    a ``:write`` satisfies the matching ``:read`` (write implies read). Mirrors the TS ``can``."""
    if "system" in held or required in held:
        return True
    if required.endswith(":read"):
        return required[: -len(":read")] + ":write" in held
    return False


def for_portal(slugs: list[str], portal: str | None) -> list[str]:
    """The slugs that apply on this portal.

    ``auth.member_permissions`` returns a role's whole grant set. Operations-only slugs
    (``system`` above all) belong on the operations portal; a platform-portal session that
    inherited them would bypass every firm gate, so turning ``contacts:create`` off would not
    hide New client.
    """
    if portal == "operations":
        return list(slugs)
    return [s for s in slugs if s not in OPERATIONS_SLUGS]


async def sync_permissions(session: AsyncSession) -> int:
    """Idempotently upsert the whole registry into ``auth.permissions`` (insert missing, refresh
    name/resource/action/portal/description). Never deletes — a removed permission is left in the
    catalogue (its grants would cascade) and should be pruned deliberately. Run as ``service_role``
    (FORCE RLS WITH CHECK). Returns the number of permissions in the registry."""
    for p in ALL:
        await session.execute(
            text(
                "INSERT INTO auth.permissions (slug, name, resource, action, portal, description) "
                "VALUES (:slug, :name, :resource, :action, :portal, :description) "
                "ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, "
                "  resource = EXCLUDED.resource, action = EXCLUDED.action, "
                "  portal = EXCLUDED.portal, description = EXCLUDED.description"
            ),
            {
                "slug": p.slug,
                "name": p.name,
                "resource": p.resource,
                "action": p.action,
                "portal": p.portal,
                "description": p.description,
            },
        )
    return len(ALL)
