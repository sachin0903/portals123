async def account_defaults(session: AsyncSession, provider: str, account_id: int) -> dict[str, str]:
    """What one account answers about itself, for the drawer to prefill. Keyed by field leaf.

    This is the half of "drive the vendor calls from data" that needed schema. Before 0119/0120 two
    of these fields had no source in the estate at all:

    * **`portfolioId`** is required by `createCurrencyReceipt`, `createcashdisbursement`,
      `currencytransfercreate` and every `PSM/model/assignment/*`, and the only home it ever had
      was a `platform.links` row — which permits exactly one, while 59 of 1,104 SEI accounts carry
      a Capital AND an Income portfolio. `platform.portfolios` is where it lives now, and the
      PRINCIPAL one is what a write defaults to.
    * **the BACS trio** is the destination a withdrawal is paid to. `crm.contacts.bank_account` has
      held validated details since 0002 and reached no vendor; `platform.accounts.bank_accounts`
      (0120) is the account-level half, and `app/bank_accounts.py` resolves account-then-client
      because the two custodians sit on opposite sides of that.

    RLS decides what is visible: the session is the caller's, so an account they cannot see yields
    `{}` — the same answer as an account with nothing configured, deliberately, because a
    distinguishable refusal would confirm the account exists.

    A resolved value is never a guess. Where the account has no portfolio, or no bank details
    anywhere, the field is simply absent and the drawer shows the empty required box the vendor's
    own 422 then names — which is the behaviour `defaults_for` already documents.
    """
    row = (
        (
            await session.execute(
                text(
                    "SELECT pl.external_id AS account_number, a.currency, "
                    "       pf.external_id AS portfolio_id "
                    "FROM platform.accounts a "
                    "LEFT JOIN platform.links pl "
                    "  ON pl.entity_type = 'account' AND pl.entity_id = a.id "
                    " AND pl.provider = :p AND pl.link_type = 'primary' "
                    # ITS PRINCIPAL PORTFOLIO — an account with two takes the Capital one, which
                    # is where a write goes when the caller names none. `is_principal` is the
                    # child's own flag and both providers publish it; this used to COALESCE an
                    # `accounts.default_portfolio_id` in front of it, a parent FK nothing ever
                    # wrote, so only this arm has ever fired.
                    "LEFT JOIN platform.portfolios pf "
                    "  ON pf.id = ("
                    "       SELECT p2.id FROM platform.portfolios p2"
                    "        WHERE p2.account_id = a.id AND p2.provider = :p"
                    "        ORDER BY p2.is_principal DESC, p2.external_id LIMIT 1) "
                    "WHERE a.id = :a"
                ),
                {"a": account_id, "p": provider},
            )
        )
        .mappings()
        .one_or_none()
    )
    if row is None:
        return {}

    out: dict[str, str] = {}
    number = row["account_number"]
    if number:
        for field in ("accountNumber", "debitAccountNumber", "externalAccountNumber"):
            out[field] = str(number)
    if row["portfolio_id"]:
        for field in ("portfolioId", "debitPortfolioId"):
            out[field] = str(row["portfolio_id"])
    if row["currency"]:
        out["currencyCode"] = str(row["currency"])
        out["accountBaseCurrency"] = str(row["currency"])

    # The destination for money OUT. `pay_to`, not any bank account the client has: SEI keeps
    # payer profiles on the same account, and paying a contribution's payer profile would send
    # money back to whoever it came from.
    entry, _source = await bank_accounts.resolve_for_account(
        session, account_id=account_id, direction="pay_to"
    )
    if entry:
        if entry.get("name"):
            out["bacsAccountName"] = str(entry["name"])
        if entry.get("sort_code"):
            # The vendor wants digits; the book stores the readable `12-34-56`.
            out["bacsDestinationSortCode"] = str(entry["sort_code"]).replace("-", "")
        if entry.get("account_number"):
            out["bacsPayToAccountNumber"] = str(entry["account_number"])
        # BACS is the default, SWIFT for an international entry — `sei_payment_method` states
        # that rule once rather than a third copy of it here.
        out["paymentMethod"] = bank_accounts.sei_payment_method(entry)
    return {name: value for name, value in out.items() if name in _ACCOUNT_FIELDS}


def _field_json(field: VendorField) -> dict[str, Any]:
    return {
        "name": field.name,
        "type": field.type,
        "required": field.required,
        "conditional": field.conditional,
        "required_note": field.required_note,
        "description": field.description,
        # The vendor's own words, first letter up: their page documents one set as `false`/`true`,
        # which the picker would otherwise print lowercase beside every capitalised option.
        "options": [
            {"label": o.label[:1].upper() + o.label[1:] if o.label else o.label, "value": o.value}
            for o in field.options
        ],
        "multiselect": field.multiselect,
        # Non-empty when this field is a REFERENCE to one of the firm's own records, so the drawer
        # offers a searchable picker instead of a box to paste a GUID into. The value is the
        # entity's label ("Contacts"), which is what the control says it is searching.
        "lookup": _LOOKUP_LABELS.get(field.name, ""),
    }


def _lookup_labels() -> dict[str, str]:
    """Vendor field -> the human name of the entity it references.

    Resolved lazily and defensively: `platform_entities` imports the lake adapter, and a field
    contract must still describe itself on a deployment where the warehouse is unreachable.
    """
    try:
        from app import platform_entities

        out: dict[str, str] = {}
        for name, key in platform_entities.lookup_fields("morgan-lloyd").items():
            entity = platform_entities.lookup_entity("morgan-lloyd", key)
            if entity is not None:
                out[name] = entity.label
        return out
    except Exception:  # noqa: BLE001 - a missing picker is a degraded form, not a failed one
        return {}


_LOOKUP_LABELS = _lookup_labels()


def contract(defined: ActionDef) -> Any | None:
    """The operation whose field list this action's form is built from.

    `fields_from` wins where it is set, because the vendor's own page delegates: the PATCH
    sections say "see Create X" instead of repeating the table.
    """
    from app.platform_contracts import resolve_contract

    reference = defined.fields_from or defined.contract_ref or defined.action
    # The METHOD disambiguates an entity set. `cam_nominationofbeneficiaries` names a GET-all, a
    # GET-by-id and this PATCH; without it the lookup returned the GET, which has no request
    # fields, and the action looked undocumented.
    method = "PATCH" if defined.method == "patch_entity" else "POST"
    return resolve_contract(defined.provider, reference, method)


def _defaults_for_action(found: Contract | None, configured: dict[str, str]) -> dict[str, str]:
    """Only the fields THIS action documents, keyed by their own full names.

    Two lookups per field and the order matters: the exact name first (Morgan Lloyd documents flat
    names and one of them, `provider`, would collide with a leaf if leaves were tried first), then
    the leaf. A leaf appearing twice in one action fills both — `createCashDisbursement` carries a
    `CurrencyDisbursement.accountNumber` and a `MemoDisbursement.accountNumber`, and they name the
    same account.
    """
    if found is None:
        return {}
    out: dict[str, str] = {}
    for field in found.fields:
        if field.name in configured:
            out[field.name] = configured[field.name]
        elif leaf(field.name) in configured:
            out[field.name] = configured[leaf(field.name)]
    return out


def describe(
    provider: str,
    source_config: dict[str, Any] | None = None,
    slice_config: dict[str, Any] | None = None,
    account: dict[str, str] | None = None,
) -> list[dict[str, Any]]:
    """Every action with its documented field contract, for the drawer to render.

    An action whose contract the manifest does not carry is REPORTED, not dropped: a form we
    cannot build is a gap worth seeing, and silently omitting it makes the console look complete.
    """
    out: list[dict[str, Any]] = []
    # Enablement config first, then the connection (which only Morgan Lloyd has and which is the
    # more specific answer), then the account — most specific last, so a resolved account number
    # beats anything configured for the firm.
    configured = {
        **tenant_defaults(provider, slice_config),
        **defaults_for(provider, source_config),
        **(account or {}),
    }
    for defined in actions_for(provider):
        found = contract(defined)
        out.append(
            {
                "key": defined.key,
                "label": defined.label,
                "action": defined.action,
                "group": defined.group,
                "method": defined.method,
                "prefill": defined.prefill,
                "note": defined.note,
                "danger": defined.danger,
                # What happens if this is sent twice. It classified how a delivery QUEUE could
                # retry the operation; the queue is gone (it never had a producer) and the
                # classification outlived it, because it is a fact about the VENDOR: Morgan Lloyd
                # has no delete, so a repeated create puts a second human in the CRM, and a
                # repeated contribution reclaims relief from HMRC twice. The operator submitting
                # the form is now the one who needs to know.
                "retry": defined.retry,
                "documented": found is not None and bool(found.fields),
                "fields_from": defined.fields_from,
                "fields": [_field_json(f) for f in (found.fields if found else ())],
                "lookups": list(found.lookups) if found else [],
                # The URL parameter a PATCH targets — the vendor's own description of the record
                # id, rather than the drawer inventing a label for its box.
                "parameters": [_field_json(f) for f in (found.parameters if found else ())],
                # Only the ones THIS action actually takes, so a drawer never shows a value that
                # is not part of its contract.
                # Matched on the field LEAF, so one resolved fact fills every path a vendor
                # spells it with — SEI names `accountNumber` in eleven services and no two agree
                # on the path. The key returned is the field's OWN full name, because that is what
                # the drawer posts back and what `validate()` checks.
                "defaults": _defaults_for_action(found, configured),
            }
        )
    return out


def validate(provider: str, defined: ActionDef, payload: dict[str, Any]) -> dict[str, Any]:
    """Check a payload against the vendor's documented contract, and return what to send.

    Three checks, in the order they save an operator time:

    * **unknown fields are refused**, not passed through. Dynamics ignores what it does not
      recognise, so a typo in a field name is otherwise a silent no-op that reads as success;
    * **missing required fields are named**, so the answer is a 422 saying which rather than the
      vendor's `0x80040224 Object reference not set to an instance of an object`;
    * **option-set values are checked against the documented set** and refused when unknown --
      never coerced to the nearest member, which is how a client ends up recorded with the wrong
      title or the wrong gender.

    Conditionally-required fields (`No*`, `No**`) are deliberately NOT enforced: the condition is
    stated in the vendor's prose, and guessing it wrong blocks legitimate calls. The drawer shows
    the note instead.
    """
    found = contract(defined)
    if found is None or not found.fields:
        # No contract to check against. Passed through rather than blocked: the action is real
        # and an operator may know its shape from elsewhere.
        logger.warning("no documented contract for %s; sending unvalidated", defined.action)
        return {k: v for k, v in payload.items() if v not in (None, "")}

    documented = {f.name: f for f in found.fields}
    supplied = {k: v for k, v in payload.items() if v not in (None, "")}

    unknown = sorted(set(supplied) - set(documented))
    if unknown:
        raise ActionRefused(
            f"{defined.action} does not document these field(s): {', '.join(unknown)}. "
            "Dynamics ignores fields it does not recognise, so sending them would look like a "
            "success and change nothing."
        )

    # Requiredness is a CREATE rule and does not carry over to a PATCH. An update sets the
    # fields it names and leaves the rest alone, so borrowing Create Contact's twelve required
    # fields (which is where an update's contract comes from -- see `fields_from`) would refuse
    # every legitimate partial update, e.g. correcting one postcode.
    if defined.method != "patch_entity" and defined.provider in _DOCUMENTS_REQUIREDNESS:
        missing = sorted(f.name for f in found.fields if f.required and f.name not in supplied)
        if missing:
            raise ActionRefused(f"{defined.action} requires: {', '.join(missing)}")
    elif not supplied:
        raise ActionRefused(f"{defined.label} needs at least one field to change.")

    for name, value in supplied.items():
        field = documented[name]
        if not field.options:
            continue
        allowed = {o.value for o in field.options}
        # A multiselect is sent as a comma-separated STRING of members (the vendor's own shape;
        # `morgan_lloyd.enums.multiselect` builds it), so each part is checked separately.
        parts = str(value).split(",") if isinstance(value, str) else [value]
        for part in parts:
            text = str(part).strip()
            if not text:
                continue
            try:
                numeric = int(text)
            except ValueError as exc:
                raise ActionRefused(f"{name} takes an option-set number, not {text!r}.") from exc
            if numeric not in allowed:
                readable = ", ".join(f"{o.label or o.value}={o.value}" for o in field.options[:12])
                raise ActionRefused(
                    f"{name} does not accept {numeric}. Documented values: {readable}"
                )
    return {
        _wire_name(defined, documented[name]): _typed(documented[name], value)
        for name, value in supplied.items()
    }


def _wire_name(defined: ActionDef, field: VendorField) -> str:
    """The name this field goes out under.

    **A lookup is spelled differently on a PATCH.** The vendor's own note on Update Contact:
    "any lookup field names must be suffixed with `@odata.bind`. For example,
    `cam_FinancialAdviserContact@odata.bind`". An ACTION takes the bare parameter name for the
    same field, so the borrowed Create Contact contract cannot be posted verbatim to the PATCH --
    it would send `cam_FinancialAdviserContact`, which the entity endpoint does not recognise.

    Only for `patch_entity`, and only for the two fields the manifest types `lookup`.
    """
    if defined.method != "patch_entity" or field.type.strip().lower() != "lookup":
        return field.name
    return f"{field.name}@odata.bind"


# The vendor's own type words, which are NOT consistently cased in the page: `int` and `Int`,
# `bool` and `Bool` both appear, on different operations. Matched lower-cased for that reason.
# Requiredness is ENFORCED only where the vendor states it, and only Morgan Lloyd does: their
# field tables carry a Required column.
#
# Seccl's schemas infer it -- `pkgs/seccl/README.md`: "present in every example of that shape",
# which it calls decent evidence and not a guarantee -- and SEI's sheet has no such column at all.
# Refusing on an inference blocks a legitimate call and can only be fixed by editing code;
# letting it through means the vendor answers, and the vendor's answer names itself. The marker
# is still SHOWN on those forms, because it is useful guidance even when it is not a rule.
_DOCUMENTS_REQUIREDNESS = frozenset({"morgan-lloyd"})

_TRUE = frozenset({"true", "1", "yes", "on"})
_FALSE = frozenset({"false", "0", "no", "off"})


def _typed(field: VendorField, value: Any) -> Any:
    """The value in the type the vendor documents for the field.

    A FORM POSTS STRINGS, AND DYNAMICS IS TYPED. `cam_title` is `Edm.Int32`, so `"809130000"`
    is not the same request as `809130000`, and the difference is invisible here: it surfaces as
    a vendor 400 on a live call. `contacts.build_contact` -- the path that has actually created
    contacts -- sends ints for the option sets, a real bool for the one boolean and a string for
    `cam_potentiallyvulnerable`, and this reproduces that shape from the manifest rather than
    from a second hand-written table.

    Coercion is keyed on the DOCUMENTED TYPE, never on what the value looks like: `"0"` is a
    valid string answer for `guidanceAppointmentAttendance` (documented `string`, options
    `No : 0`) and the integer 0 for `cam_previouslytakenflexiaccessbenefits` (documented `int`,
    same two labels). Guessing from the value would silently swap those two.

    A multiselect keeps its comma-separated STRING form whatever its members look like -- that is
    the shape the vendor documents and `enums.multiselect` builds.
    """
    if field.multiselect:
        # Re-emitted from the checked parts so stray whitespace does not travel: the vendor
        # parses this string itself and " 809130000 , 809130001" is not obviously safe.
        parts = [p.strip() for p in str(value).split(",")]
        return ",".join(p for p in parts if p)

    declared = field.type.strip().lower()
    text = str(value).strip()
    if declared == "int":
        try:
            return int(text)
        except ValueError as exc:
            raise ActionRefused(f"{field.name} takes a whole number, not {text!r}.") from exc
    if declared == "decimal":
        try:
            return float(text)
        except ValueError as exc:
            raise ActionRefused(f"{field.name} takes an amount, not {text!r}.") from exc
    if declared == "bool":
        lowered = text.lower()
        if lowered in _TRUE:
            return True
        if lowered in _FALSE:
            return False
        raise ActionRefused(f"{field.name} takes True or False, not {text!r}.")
    # string, lookup, Date, DateTime, Guid -- all sent as the text they were given. A date is
    # deliberately NOT parsed and re-rendered: the vendor's examples are already ISO, and a
    # reformat here would be this module inventing a shape.
    return value


async def run(
    provider: str,
    defined: ActionDef,
    payload: dict[str, Any],
    *,
    entity_id: str | None,
    tenant_id: int | None,
    user_id: str | None,
) -> dict[str, Any]:
    """Send it, and hand back what the vendor said.

    The recorder is built HERE, with the acting operator and the firm being acted on, rather
    than relying on the process default the lifespan installs. The default cannot know either:
    an operator acting on a firm's behalf is a proxied action, and the tenant that belongs on
    the audit row is the TARGET, not the operator's own — the same distinction the action-event
    stream draws for `?tenant=` requests.
    """
    if provider not in PROVIDER_ACTIONS:
        raise ActionRefused(f"{provider} has no write actions")

    from app import api_log

    audit = api_log.current()
    recorder = audit.recorder(tenant_id=tenant_id, user_id=user_id, source="app") if audit else None

    if provider == "seccl":
        return await _run_seccl(defined, payload, entity_id=entity_id, recorder=recorder)
    if provider == "sei":
        return await _run_sei(defined, payload, recorder=recorder)

    from app.integrations.morgan_lloyd import MorganLloydNotConfigured, configured

    if not configured():
        raise ActionRefused("Morgan Lloyd is unavailable for this firm. Contact support.")

    from morgan_lloyd import (
        MorganLloydActionError,
        MorganLloydApiError,
        MorganLloydAuthError,
        MorganLloydClient,
    )
    from morgan_lloyd.settings import MorganLloydSettings

    try:
        async with MorganLloydClient(settings=MorganLloydSettings(), recorder=recorder) as api:
            if defined.method == "patch_entity":
                if not entity_id:
                    raise ActionRefused(
                        f"{defined.label} updates an existing record, so it needs its id."
                    )
                await api.patch_entity(f"{defined.action}({entity_id})", payload)
                # A PATCH answers 204 with no body. Saying so beats returning an empty object,
                # which reads in the drawer as "the vendor told us nothing".
                return {"ok": True, "detail": "Updated.", "response": None}
            response = await api.call_action(defined.action, payload)
            return {"ok": True, "detail": "Sent.", "response": response}
    except MorganLloydActionError as exc:
        # A 200 whose envelope reported failure. The vendor's message is the useful part.
        raise ActionRefused(str(exc)) from exc
    except MorganLloydNotConfigured as exc:
        raise ActionRefused(str(exc)) from exc
    except MorganLloydAuthError as exc:
        # We never reached Morgan Lloyd -- Azure AD would not issue a token. A DIFFERENT answer
        # from "the vendor refused", and worth its own branch: the raw failure used to escape
        # every handler as an unhandled `httpx.HTTPStatusError`, so an operator got a 500 and a
        # stack trace where Azure had said, specifically, `AADSTS53003 Access has been blocked by
        # Conditional Access policies`. Nothing was sent, so nothing needs undoing.
        from app.platforms import PlatformUnavailable

        raise PlatformUnavailable(
            f"Could not authenticate to Morgan Lloyd, so nothing was sent. {exc}"
        ) from exc
    except MorganLloydApiError as exc:
        from app.platforms import PlatformUnavailable

        raise PlatformUnavailable(str(exc)) from exc


# --- Seccl ---------------------------------------------------------------------------------------


async def _run_seccl(
    defined: ActionDef,
    payload: dict[str, Any],
    *,
    entity_id: str | None,
    recorder: Any,
) -> dict[str, Any]:
    """Send one Seccl instruction through the sync's own client.

    `pkgs/seccl`'s client, not a second one: it carries Seccl's three auth types, the token
    refresh, the 429/5xx backoff and the page-boundary workarounds, all of which have production
    behind them.

    THROUGH `write()`, NOT `request_json()`. That method's own docstring names why: it "bypasses
    the retry loop AND the `audit.api_log` recorder, so a write made through it leaves no
    evidence. For a money instruction that is the one thing that must not happen" — and
    `create_transaction_group` is the money rail, since contributions, transfers and withdrawals
    are all lodged as a transaction group. The recorder was passed to the client and never
    reached, so the console's three outbound tabs, which read that log, showed none of these
    sends. `request_json` also ends in a bare `raise_for_status()`, so `httpx.HTTPStatusError`
    escaped the `except SecclApiError` below and an operator got a 500 rather than the vendor's
    own `fieldErrors` — which `_explain()` exists to render.

    AND A CREATE POSTS TO THE BARE COLLECTION. Seccl has two URL conventions and
    `pkgs/seccl/endpoints/_paths.py` exists because mixing them is silent: a create is
    `POST /client` with the firm named in the BODY as `firmId`, where a read or update puts the
    firm in the PATH. All four creates here were declared with the read shape, and that module
    names the exact symptom — "posting to `/client/{firm}` is a 404 that reads like a routing
    problem".
    """
    from app.integrations.seccl import configured
    from app.integrations.seccl.connection import seccl_settings, why_not_configured

    if not configured():
        raise ActionRefused(why_not_configured())

    from seccl.client import SecclApiError, SecclClient

    settings = seccl_settings()
    path = defined.action.replace("{firm}", settings.firm_id)
    if "{id}" in path:
        if not entity_id:
            raise ActionRefused(f"{defined.label} updates an existing record, so it needs its id.")
        path = path.replace("{id}", entity_id)

    method = "PATCH" if defined.method == "patch_entity" else "POST"
    body = dict(payload)
    if method == "POST":
        # The firm goes in the body on a create, and only if the caller has not stated one.
        body.setdefault("firmId", settings.firm_id)
    try:
        async with SecclClient(settings, recorder=recorder) as api:
            answer = await api.write(method, path, body)
    except SecclApiError as exc:
        from app.platforms import PlatformUnavailable

        raise PlatformUnavailable(str(exc)) from exc
    return {"ok": True, "detail": "Sent.", "response": answer}


# --- SEI -----------------------------------------------------------------------------------------
#
# SEI's bodies are a JSON:API-ish envelope and the contract's field names are DOTTED PATHS into
# it (`data.attributes.accountNumber`). The form collects leaves; the envelope is rebuilt from the
# paths here, mechanically, so there is no per-service mapping table to keep in step with a sheet
# the vendor reissues.


def _nest(flat: dict[str, Any]) -> dict[str, Any]:
    """`{"data.attributes.x": 1}` -> `{"data": {"attributes": {"x": 1}}}`.

    Arrays are not rebuilt: a path containing `[]` never reaches here, because the contract
    excludes repeating blocks and `validate` refuses anything the contract does not document.
    """
    out: dict[str, Any] = {}
    for path, value in flat.items():
        target = out
        parts = path.split(".")
        for part in parts[:-1]:
            nxt = target.get(part)
            if not isinstance(nxt, dict):
                nxt = {}
                target[part] = nxt
            target = nxt
        target[parts[-1]] = value
    return out


async def _run_sei(defined: ActionDef, payload: dict[str, Any], *, recorder: Any) -> dict[str, Any]:
    """Send one SEI instruction.

    mTLS plus OAuth plus an app-gateway key — three credentials that stack — so an unconfigured
    deployment is a refusal naming them rather than a connection error from inside httpx.
    """
    from app.integrations.sei import configured as sei_configured

    if not sei_configured():
        raise ActionRefused("SEI is unavailable for this firm. Contact support.")

    from sei import SeiClient, SeiError, SeiSettings

    body = _nest(payload)
    # A leading slash: `request` takes a path relative to the SWP root and the manifest stores
    # the service segment without one.
    path = defined.action if defined.action.startswith("/") else f"/{defined.action}"
    try:
        async with SeiClient(SeiSettings(), recorder=recorder) as api:
            answer = await api.request("POST", path, json=body)
    # `SeiError`, not `SeiApiError`. `SeiAuthError` and its subclass `SeiEntitlementError` are
    # SIBLINGS of `SeiApiError` under `SeiError`, and they are what `_from_status` returns for
    # every 401/403 — which includes the non-allowlisted-source-IP case that applies to the API's
    # own host, since SEI allowlists by IP. Catching only the sibling discarded the one message
    # written to explain it and answered with an unhandled 500 instead.
    except SeiError as exc:
        from app.platforms import PlatformUnavailable

        raise PlatformUnavailable(str(exc)) from exc
    return {"ok": True, "detail": "Sent.", "response": answer}
