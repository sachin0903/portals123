"""Firm-console write actions: a Graphene record in, a vendor payload out.

Admin > Platforms > {provider} > Firms > {uid} > an action drawer. The sixteen operations an
operator can perform against a custodian on a firm's behalf -- create a contact, a scheme, a
beneficiary, a transfer, a contribution, an investment, a valuation, a benefit application, set
up drawdown, submit an illustration or a document.

**The forms are DATA.** Each action's fields, types, requiredness and option sets come from the
vendor's own documentation (`morgan_lloyd.manifest`, generated by parsing their page), not from
a hand-written schema per action. Sixteen hand-written forms would drift from the vendor the day
they changed anything, and the drift is invisible until a live call fails.

**The mapping is explicit.** `PREFILLS` says which Graphene record supplies which vendor field.
It reuses the existing builders (`app.integrations.morgan_lloyd.contacts.build_contact` and its
`REQUIRED_FIELDS` posture) rather than re-deriving them, because those already encode the two
rules worth keeping: a missing field is a 422 naming it rather than a vendor 400, and an
option-set value is refused rather than coerced.

**Nothing here decides whether the operator may act.** The router gates on `platforms:write`.
"""

