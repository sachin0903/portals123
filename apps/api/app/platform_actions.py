def leaf(name: str) -> str:
    """The last segment of a vendor field path — see `_TENANT_CONFIG_DEFAULTS` for why."""
    return name.rsplit(".", 1)[-1]


def tenant_defaults(provider: str, slice_config: dict[str, Any] | None = None) -> dict[str, str]:
    """Firm-level values from `platform.tenant_platforms.config`, keyed by field leaf.

    Separate from `defaults_for` because they come from a different table: `defaults_for` reads the
    CONNECTION (`platform.providers.config`, which only Morgan Lloyd has) while these come from the
    firm's ENABLEMENT. Merged by the caller, enablement first, so a connection-level value for the
    same field still wins — the precedence `defaults_for` already documents.
    """
    mapping = _TENANT_CONFIG_DEFAULTS.get(provider)
    if not mapping:
        return {}
    config = slice_config or {}
    out: dict[str, str] = {}
    for field, key in mapping.items():
        value = config.get(key)
        if value not in (None, "") and not isinstance(value, (dict, list)):
            out[field] = str(value)
    return out


def defaults_for(provider: str, source_config: dict[str, Any] | None = None) -> dict[str, str]:
    """Configured values for the fields that have one, as strings for the form.

    THE SOURCE WINS OVER ENV, per field rather than per object. Env is per-deployment and this
    platform is multi-tenant with one Dynamics org per firm, so the connection's own row is the
    more specific answer wherever it has one -- but a half-filled row must not blank the fields it
    does not mention, or configuring `firm_id` would silently unset the scheme pairing.

    Empty where neither has a value, so a missing one shows as an empty required box that the 422
    then names -- never as a silently-omitted field, and never as a guess.
    """
    if provider != "morgan-lloyd":
        return {}
    from_source = source_config or {}
    settings: Any = None
    try:
        from morgan_lloyd.settings import MorganLloydSettings

        settings = MorganLloydSettings()
    except Exception:  # noqa: BLE001 - unconfigured is a state, not an error, in the read path
        settings = None

    out: dict[str, str] = {}
    for field, attribute in _MORGAN_LLOYD_DEFAULTS.items():
        key = _MORGAN_LLOYD_SOURCE_KEYS.get(field)
        value = from_source.get(key) if key else None
        if value in (None, "") and settings is not None:
            value = getattr(settings, attribute, None)
        if value not in (None, ""):
            out[field] = str(value)
    return out


