class ActionRefused(ValueError):
    """The payload cannot be sent as it stands. Carries a message naming the problem."""


@dataclass(frozen=True, slots=True)
class ActionDef:
    """One action the console offers, over the vendor's documented contract."""

    key: str
    label: str
    action: str
    """What the client actually calls.

    A Dataverse action for Morgan Lloyd (the CLIENT's spelling, which is the verified one where
    it differs from the documentation -- manifest.ACTION_ALIASES), an HTTP path for Seccl, a
    service path for SEI.
    """
    group: str
    provider: str = "morgan-lloyd"
    """Which custodian this action belongs to.

    On the ActionDef rather than passed alongside it, because everything that reads one -- the
    contract lookup, the payload typing, the send -- needs it, and threading it separately is how
    an action ends up validated against one vendor's contract and sent to another.
    """
    contract_ref: str = ""
    """How the vendor names this operation in ITS OWN contract source, when that differs from
    what the client calls. Seccl calls `POST /client/{firm}` and documents it as
    `client:ClientCreate`; ML's action name is both. Blank means `action` is the reference."""
    method: str = "call_action"
    """The `MorganLloydClient` coroutine. `call_action` is the generic door; a few operations
    have a typed wrapper worth using instead."""
    prefill: str = ""
    """Which Graphene record can populate the form: 'contact', 'account', or blank for none."""
    fields_from: str = ""
    """Borrow another operation's field contract.

    The vendor documents the entity-PATCH operations by REFERENCE -- "Update Contact" carries a
    URL-parameter table and the words "see Create Contact" rather than repeating 34 rows. Parsed
    faithfully that is an operation with no fields, which renders as an empty drawer: the action
    looks broken when in fact its contract is one section further up the page.

    Named explicitly rather than guessed from the label, because the pairing is the vendor's
    editorial choice and not a rule -- "Update Benefit Applications Illustration Template" has
    its own three fields and must not borrow anything.
    """
    note: str = ""
    danger: str = ""
    """Stated in the drawer before the operator submits. Non-empty where the vendor cannot
    undo the effect."""
    retry: str = "manual"
    """Whether this operation is safe to send twice — shown to the operator before they submit.

    It was written for a delivery queue (`platform.provider_instructions`, 0074) that never had a
    producer and has been removed. The classification stayed, because it is a property of the
    VENDOR OPERATION and not of the transport that happened to prompt it — which is also why it is
    declared here rather than at a call site:

    * ``safe``    -- idempotent by nature: a read, or a PATCH setting an absolute value. Sending
                     it twice leaves the same state, so a failed submit can simply be repeated.
    * ``guarded`` -- a create that mints an identifier we record on ``platform.links``, so the
                     question "did this already land?" is answerable. This is
                     ``integrations/morgan_lloyd/sync.py``'s check-then-create.
    * ``manual``  -- no such check exists and the effect is not reversible. If the answer is lost,
                     confirm at the vendor before sending again.

    **The default is ``manual`` deliberately.** An operation added without a decision here must
    not be presented as repeatable: Morgan Lloyd has no delete, so a resent `cam_createcontact`
    puts a second human being in the CRM, and a resent contribution reclaims relief from HMRC
    twice. Guessing wrong is only costly in one direction.
    """


