-- ============================================================================
-- 0041_platform_conformed -- the four canonical entities the conformed provider layers
-- materialise into, completing the model docs/platform-model.md describes.
--
-- 0002 landed contacts, accounts, products, models, fee_packages and transactions; 0003
-- landed the polymorphic bridge (platform.platform_links). What was missing is what every
-- custodian actually publishes and nothing canonical could hold:
--
--   platform.orgs        the provider org unit a tenant's slice is keyed on -- a Seccl
--                        node, an SEI firm/subfirm/DSR team, a Morgan Lloyd Microsoft
--                        tenant. Until now these existed only as opaque values inside
--                        integrations.tenant_providers.config, which is not something to
--                        hang authorisation on.
--   platform.instruments securities. Deferred by data-architecture Decision 1 ("a
--                        platform.instruments reference table is deferred"), which left
--                        transactions carrying a bare `isin` text column.
--   platform.valuations  account value per date. accounts.value holds only the latest, so
--                        there was nowhere for a series to live and every trend came from
--                        a lake read.
--   platform.model_platforms  the model<->platform join Decision 1 named but never built.
--
-- Expand phase throughout: new tables, new nullable columns, no rewrites. The
-- platform_identifier columns 0002 put on accounts/products/models are superseded by
-- platform_links and are left alone here for a later contract phase.
-- ============================================================================

CREATE TYPE platform.org_type AS ENUM ('firm', 'subfirm', 'team', 'node', 'tenant');

-- ============================================================================
-- platform.orgs -- provider org units.
--
-- `org_path` is the root->leaf ancestry, and it is the whole point: one containment test
-- (`org_key = ANY(...)` here, `list_has_any(org_path, [...])` in the lake) filters every
-- provider, replacing the per-provider predicate builder in app/fanout.py.
--
-- Scoped by tenant even though the upstream org exists independently of one: a tenant may
-- only see the org units its own enablement resolves to, and the same DSR team can be
-- granted to more than one tenant.
-- ============================================================================
CREATE TABLE platform.orgs (
  id          int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id   int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  provider    text NOT NULL,
  org_key     text NOT NULL,
  org_path    text[] NOT NULL DEFAULT '{}',
  org_type    platform.org_type NOT NULL,
  name        text,
  parent_key  text,
  -- Set when this org unit is what a tenant's provider enablement resolves to, so
  -- "which org am I?" is answerable without re-deriving the predicate.
  is_tenant_root boolean NOT NULL DEFAULT false,
  data        jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT orgs_unique UNIQUE (tenant_id, provider, org_key)
);
CREATE INDEX orgs_tenant_id_idx ON platform.orgs (tenant_id);
CREATE INDEX orgs_provider_key_idx ON platform.orgs (provider, org_key);
CREATE INDEX orgs_path_idx ON platform.orgs USING gin (org_path);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.orgs
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE platform.orgs ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.orgs FORCE ROW LEVEL SECURITY;
-- The firm's own staff can see their org units; writes are the materialiser's
-- (service_role) alone. No client-scoped branch: an org unit is firm structure, not
-- something a client has a relationship with.
CREATE POLICY orgs_read ON platform.orgs FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON platform.orgs TO authenticated;
GRANT ALL ON platform.orgs TO service_role;

-- ============================================================================
-- platform.instruments -- securities.
--
-- Deliberately NOT tenant-scoped: an ISIN is not owned by a firm, and scoping it would
-- store one row per (tenant, security) for data that is identical in every copy. This is
-- the OLTP counterpart of the conformed layer publishing an empty org_path for reference
-- data. No RLS, because there is no tenant column to filter on -- reads are granted to
-- `authenticated` outright, which is the same posture as a currency list.
--
-- IDENTITY. An ISIN is the natural key when present, but cash positions and some SEI
-- instruments have none, so it cannot be the only one: those rows are reached through
-- platform_links (entity_type='instrument') by provider id. Hence a partial unique index
-- rather than a UNIQUE constraint -- several ISIN-less instruments must coexist.
-- ============================================================================
CREATE TABLE platform.instruments (
  id            int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  isin          text,
  sedol         text,
  cusip         text,
  name          text NOT NULL,
  legal_name    text,
  asset_type    text,
  currency      text,
  exchange_code text,
  market_country text,
  issuer_country text,
  credit_rating text,
  interest_rate numeric(12, 6),
  issued_on     date,
  matures_on    date,
  data          jsonb,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX instruments_isin_key ON platform.instruments (isin) WHERE isin IS NOT NULL;
CREATE INDEX instruments_sedol_idx ON platform.instruments (sedol) WHERE sedol IS NOT NULL;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.instruments
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Global reference data still carries RLS with a permissive policy, which is the pattern
-- `platform.platforms` set in 0002 and what tests/test_schema_invariants.py enforces: a table
-- granted to `authenticated` must have a policy for it, so "readable by everyone" is stated
-- rather than implied by the absence of one. An instrument is not tenant data, so the policy is
-- `USING (true)` -- but it exists, and a future tenant column cannot quietly widen access.
ALTER TABLE platform.instruments ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.instruments FORCE ROW LEVEL SECURITY;
CREATE POLICY instruments_read ON platform.instruments FOR SELECT TO authenticated USING (true);
GRANT SELECT ON platform.instruments TO authenticated;
GRANT ALL ON platform.instruments TO service_role;

-- ============================================================================
-- platform.valuations -- account value per date.
--
-- One row per (account, date, source): small enough for OLTP at one row per account per
-- day, which is what buys the portals a trend without a lake read. Holdings stay in the
-- lake (docs/platform-model.md §2 Rule A) -- account x instrument x date is a different
-- order of volume and a pure snapshot.
--
-- `source_system` is in the key because two custodians can both value the same logical
-- account during a transfer, and averaging them or letting one overwrite the other would
-- both be wrong.
-- ============================================================================
CREATE TABLE platform.valuations (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id       int  NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  account_id      int  NOT NULL REFERENCES platform.accounts(id) ON DELETE CASCADE,
  as_of_date      date NOT NULL,
  source_system   text NOT NULL,
  market_value    numeric(20, 4) NOT NULL,
  cash_value      numeric(20, 4),
  book_cost       numeric(20, 4),
  unrealised_gain numeric(20, 4),
  opening_value   numeric(20, 4),
  currency        text NOT NULL DEFAULT 'GBP',
  data            jsonb,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT valuations_unique UNIQUE (account_id, as_of_date, source_system)
);
-- The tenant-containment invariant 0035 established and tests/test_schema_invariants.py
-- enforces: a single-column account_id FK lets a row point at ANOTHER firm's account, which the
-- client branch of a read policy (`account_id = ANY (auth.account_scope())`) would then expose,
-- and no WITH CHECK closes it because service_role is what actually writes here. Referential
-- integrity does, for every role, because RI checks bypass RLS.
ALTER TABLE platform.valuations ADD CONSTRAINT valuations_account_tenant_fkey
  FOREIGN KEY (tenant_id, account_id) REFERENCES platform.accounts (tenant_id, id)
  ON DELETE CASCADE;

CREATE INDEX valuations_tenant_id_idx ON platform.valuations (tenant_id);
CREATE INDEX valuations_account_date_idx ON platform.valuations (account_id, as_of_date DESC);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.valuations
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE platform.valuations ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.valuations FORCE ROW LEVEL SECURITY;
-- Mirrors platform.accounts' own two-layer scope: read-all staff see the firm, everyone
-- else sees only the accounts in their own scope. A valuation is as sensitive as the
-- account it values, so it must not be reachable more widely than the account is.
CREATE POLICY valuations_read ON platform.valuations FOR SELECT TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR account_id = ANY (auth.account_scope())
  );
GRANT SELECT ON platform.valuations TO authenticated;
GRANT ALL ON platform.valuations TO service_role;

-- ============================================================================
-- platform.model_platforms -- a model may exist on more than one platform.
-- (data-architecture Decision 1: "platform.model_platforms join (mirrors
-- product_providers)".)
-- ============================================================================
CREATE TABLE platform.model_platforms (
  id          int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id   int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  model_id    int NOT NULL REFERENCES platform.models(id) ON DELETE CASCADE,
  platform_id int NOT NULL REFERENCES platform.platforms(id),
  external_id text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT model_platforms_unique UNIQUE (model_id, platform_id)
);
CREATE INDEX model_platforms_tenant_id_idx ON platform.model_platforms (tenant_id);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.model_platforms
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE platform.model_platforms ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.model_platforms FORCE ROW LEVEL SECURITY;
CREATE POLICY model_platforms_read ON platform.model_platforms FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON platform.model_platforms TO authenticated;
GRANT ALL ON platform.model_platforms TO service_role;

-- ============================================================================
-- Wiring the new entities into the existing ones. All nullable: a row that predates the
-- sync, or a provider that publishes no org, simply has none.
-- ============================================================================
ALTER TABLE platform.accounts     ADD COLUMN org_id int REFERENCES platform.orgs(id);
ALTER TABLE crm.contacts          ADD COLUMN org_id int REFERENCES platform.orgs(id);
-- The canonical replacement for the bare `isin` text on a transaction. `isin` stays: it
-- is what the provider said, and it is still right when no instrument row resolves.
ALTER TABLE platform.transactions ADD COLUMN instrument_id int REFERENCES platform.instruments(id);
-- Discretionary management is a property of the wrapper at Seccl and of the strategy at
-- SEI; the canonical account needs it either way (the accounts listing derives
-- `discretionary` from `model_id IS NOT NULL` today, which is a proxy, not the fact).
ALTER TABLE platform.accounts     ADD COLUMN is_discretionary boolean;

CREATE INDEX accounts_org_id_idx ON platform.accounts (org_id) WHERE org_id IS NOT NULL;
CREATE INDEX contacts_org_id_idx ON crm.contacts (org_id) WHERE org_id IS NOT NULL;
CREATE INDEX transactions_instrument_id_idx ON platform.transactions (instrument_id)
  WHERE instrument_id IS NOT NULL;

