-- 0184_terms: legal terms as a first-class, versioned catalogue with durable acceptances.
--
-- Distinct from l10n.terms (UI vocabulary). Graphene-owned rows have tenant_id NULL; firm rows
-- are tenant-scoped. Published versions are insert-only. Acceptances pin a version, never the
-- header. crm.kyc_checks.kind = 'terms' remains the derived Compliance-card tick.

CREATE SCHEMA IF NOT EXISTS terms;
GRANT USAGE ON SCHEMA terms TO authenticated, service_role;

CREATE TYPE terms.owner AS ENUM ('graphene', 'tenant');
CREATE TYPE terms.status AS ENUM ('draft', 'published', 'archived');
CREATE TYPE terms.audience AS ENUM ('client', 'staff', 'all');
CREATE TYPE terms.body_kind AS ENUM ('html', 'pdf');
CREATE TYPE terms.channel AS ENUM ('portal', 'in_person');

CREATE TABLE terms.terms (
    id                           int              PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid                          text             NOT NULL UNIQUE,
    owner                        terms.owner      NOT NULL,
    tenant_id                    int              REFERENCES auth.tenants(id) ON DELETE CASCADE,
    code                         text             NOT NULL,
    title                        text             NOT NULL,
    audience                     terms.audience   NOT NULL DEFAULT 'client',
    required_at                  text[]           NOT NULL DEFAULT ARRAY['onboarding']::text[],
    applicability                jsonb            NOT NULL DEFAULT '{"always": true}'::jsonb,
    status                       terms.status     NOT NULL DEFAULT 'draft',
    body_kind                    terms.body_kind  NOT NULL DEFAULT 'html',
    body_md                      text,
    file_key                     text,
    file_content_type            text,
    file_size                    int,
    document_id                  uuid             REFERENCES documents.documents(id) ON DELETE SET NULL,
    current_published_version_id int,
    published_at                 timestamptz,
    sort_order                   int              NOT NULL DEFAULT 0,
    created_by                   uuid             REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at                   timestamptz      NOT NULL DEFAULT now(),
    updated_at                   timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT terms_owner_tenant CHECK (
        (owner = 'graphene' AND tenant_id IS NULL)
        OR (owner = 'tenant' AND tenant_id IS NOT NULL)
    ),
    CONSTRAINT terms_required_at_valid CHECK (
        required_at <@ ARRAY['onboarding', 'login']::text[]
        AND cardinality(required_at) > 0
    )
);
CREATE INDEX terms_tenant_status_idx ON terms.terms (tenant_id, status);
CREATE INDEX terms_owner_status_idx ON terms.terms (owner, status);
CREATE UNIQUE INDEX terms_tenant_code_uidx ON terms.terms (tenant_id, code)
    WHERE tenant_id IS NOT NULL;
CREATE UNIQUE INDEX terms_graphene_code_uidx ON terms.terms (code)
    WHERE owner = 'graphene';

CREATE TABLE terms.term_versions (
    id                int              PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid               text             NOT NULL UNIQUE,
    tenant_id         int              REFERENCES auth.tenants(id) ON DELETE CASCADE,
    term_id           int              NOT NULL REFERENCES terms.terms(id) ON DELETE CASCADE,
    version_number    int              NOT NULL,
    title             text             NOT NULL,
    body_kind         terms.body_kind  NOT NULL,
    body_html         text,
    file_key          text,
    file_content_type text,
    file_size         int,
    document_id       uuid             REFERENCES documents.documents(id) ON DELETE SET NULL,
    content_hash      text             NOT NULL,
    published_by      uuid             REFERENCES auth.users(id) ON DELETE SET NULL,
    published_at      timestamptz      NOT NULL DEFAULT now(),
    UNIQUE (term_id, version_number),
    CONSTRAINT term_versions_body CHECK (
        (
            body_kind = 'html'
            AND body_html IS NOT NULL
            AND length(btrim(body_html)) > 0
            AND file_key IS NULL
            AND document_id IS NULL
        )
        OR (
            body_kind = 'pdf'
            AND (file_key IS NOT NULL OR document_id IS NOT NULL)
        )
    )
);
CREATE INDEX term_versions_term_idx ON terms.term_versions (term_id);

ALTER TABLE terms.terms
    ADD CONSTRAINT fk_terms_current_published_version
    FOREIGN KEY (current_published_version_id)
    REFERENCES terms.term_versions(id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE OR REPLACE FUNCTION terms.reject_version_mutation() RETURNS trigger
    LANGUAGE plpgsql AS $fn$
BEGIN
    RAISE EXCEPTION 'term versions are immutable'
        USING ERRCODE = 'restrict_violation',
              HINT = 'Publish a new version instead of editing a snapshot.';
    RETURN NULL;
END;
$fn$;

SET LOCAL lock_timeout = '5s';
CREATE TRIGGER term_versions_immutable
    BEFORE UPDATE OR DELETE ON terms.term_versions
    FOR EACH ROW EXECUTE FUNCTION terms.reject_version_mutation();

CREATE TABLE terms.acceptances (
    id              bigint         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid             text           NOT NULL UNIQUE,
    tenant_id       int            REFERENCES auth.tenants(id) ON DELETE CASCADE,
    contact_id      int            REFERENCES crm.contacts(id) ON DELETE CASCADE,
    user_id         uuid           REFERENCES auth.users(id) ON DELETE CASCADE,
    term_id         int            NOT NULL REFERENCES terms.terms(id) ON DELETE CASCADE,
    term_version_id int            NOT NULL REFERENCES terms.term_versions(id) ON DELETE RESTRICT,
    application_id  int            REFERENCES crm.applications(id) ON DELETE SET NULL,
    accepted_by     uuid           REFERENCES auth.users(id) ON DELETE SET NULL,
    accepted_at     timestamptz    NOT NULL DEFAULT now(),
    channel         terms.channel  NOT NULL DEFAULT 'portal',
    attested_by     uuid           REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at      timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT acceptances_subject CHECK (contact_id IS NOT NULL OR user_id IS NOT NULL),
    CONSTRAINT acceptances_contact_tenant CHECK (
        contact_id IS NULL OR tenant_id IS NOT NULL
    )
);
CREATE INDEX acceptances_contact_idx ON terms.acceptances (contact_id)
    WHERE contact_id IS NOT NULL;
CREATE INDEX acceptances_user_idx ON terms.acceptances (user_id)
    WHERE contact_id IS NULL AND user_id IS NOT NULL;
CREATE INDEX acceptances_term_idx ON terms.acceptances (term_id);
CREATE UNIQUE INDEX acceptances_contact_version_uidx
    ON terms.acceptances (contact_id, term_version_id)
    WHERE contact_id IS NOT NULL;
CREATE UNIQUE INDEX acceptances_user_version_uidx
    ON terms.acceptances (user_id, term_version_id)
    WHERE contact_id IS NULL AND user_id IS NOT NULL;

