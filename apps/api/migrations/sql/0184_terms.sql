    USING (owner = 'graphene' AND status = 'published');
CREATE POLICY terms_graphene_system_read ON terms.terms FOR SELECT TO authenticated
    USING (owner = 'graphene' AND auth.is_system());
CREATE POLICY terms_tenant_staff_read ON terms.terms FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY terms_tenant_client_read ON terms.terms FOR SELECT TO authenticated
    USING (tenant_id = auth.tenant_id() AND status = 'published');
CREATE POLICY terms_tenant_write ON terms.terms FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()) AND owner = 'tenant');
GRANT SELECT, INSERT, UPDATE, DELETE ON terms.terms TO authenticated;
GRANT ALL ON terms.terms TO service_role;

