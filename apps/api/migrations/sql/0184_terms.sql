    USING (
        EXISTS (
            SELECT 1 FROM terms.terms t
            WHERE t.id = term_id AND t.owner = 'graphene' AND t.status = 'published'
        )
    );
CREATE POLICY term_versions_graphene_system_read ON terms.term_versions FOR SELECT TO authenticated
    USING (auth.is_system());
CREATE POLICY term_versions_tenant_staff_read ON terms.term_versions FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY term_versions_tenant_client_read ON terms.term_versions FOR SELECT TO authenticated
    USING (
        tenant_id = auth.tenant_id()
        AND EXISTS (
            SELECT 1 FROM terms.terms t
            WHERE t.id = term_id AND t.status = 'published' AND t.tenant_id = auth.tenant_id()
        )
    );
CREATE POLICY term_versions_tenant_write ON terms.term_versions FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON terms.term_versions TO authenticated;
GRANT ALL ON terms.term_versions TO service_role;

ALTER TABLE terms.acceptances ENABLE ROW LEVEL SECURITY;
ALTER TABLE terms.acceptances FORCE ROW LEVEL SECURITY;
CREATE POLICY acceptances_staff_read ON terms.acceptances FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY acceptances_own_user_read ON terms.acceptances FOR SELECT TO authenticated
    USING (contact_id IS NULL AND user_id = auth.uid());
CREATE POLICY acceptances_client_read ON terms.acceptances FOR SELECT TO authenticated
    USING (contact_id = ANY (auth.contact_scope()));
CREATE POLICY acceptances_staff_insert ON terms.acceptances FOR INSERT TO authenticated
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY acceptances_own_user_insert ON terms.acceptances FOR INSERT TO authenticated
    WITH CHECK (contact_id IS NULL AND user_id = auth.uid() AND tenant_id IS NULL);
CREATE POLICY acceptances_client_insert ON terms.acceptances FOR INSERT TO authenticated
    WITH CHECK (contact_id = ANY (auth.contact_scope()) AND tenant_id = auth.tenant_id());
GRANT SELECT, INSERT ON terms.acceptances TO authenticated;
GRANT ALL ON terms.acceptances TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA terms TO authenticated, service_role;

