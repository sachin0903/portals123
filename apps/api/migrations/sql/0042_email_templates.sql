-- 0042_email_templates: the email-template authoring store (the email system's authoring half).
--
-- A DEDICATED `email` schema mirroring 0012's documents.templates/template_versions (draft/publish,
-- versioned opaque `schema` jsonb) but with email-specific columns — `subject`/`preheader` on the
-- version — and its own `email_templates:*` perms so email editing gates INDEPENDENTLY of documents.
-- Every email (transactional + notification) is editable per-firm and seeded with a default; `code`
-- is the stable key the send path resolves (e.g. 'invite'), and `category` lets the app gate
-- transactional templates behind a stricter permission than firm comms. May merge into
-- documents.templates later — kept separate for now (cleaner perm gating).
--
-- Render reuses the documents Jinja-merge pipeline; only the OUTPUT differs (inline-CSS email HTML,
-- not PDF). STAFF-ONLY RLS (tenant lineage) — email templates are firm assets; clients never author.

CREATE SCHEMA IF NOT EXISTS email;
GRANT USAGE ON SCHEMA email TO authenticated, service_role;

CREATE TYPE email.template_status AS ENUM ('draft', 'published', 'archived');

-- ── templates ────────────────────────────────────────────────────────────────
CREATE TABLE email.templates (
    id                           int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid                          text        NOT NULL UNIQUE,
    tenant_id                    int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    code                         text        NOT NULL,   -- stable key the send path resolves (e.g. 'invite')
    name                         text        NOT NULL,
    category                     text        NOT NULL DEFAULT 'notification',  -- 'transactional' | 'notification' (perm gating)
    description                  text,
    current_published_version_id int,        -- deferred FK added below
    created_by                   uuid        NOT NULL REFERENCES auth.users(id),
    archived_at                  timestamptz,
    created_at                   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, code)
);
CREATE INDEX email_templates_tenant_category_idx ON email.templates(tenant_id, category);

-- ── template_versions ─────────────────────────────────────────────────────────
-- Immutable once status = 'published'. `schema` is the editor content (opaque jsonb: html/css/gjs).
-- `subject`/`preheader` carry Jinja tokens, merged at send time exactly like the body.
CREATE TABLE email.template_versions (
    id             int                   PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid            text                  NOT NULL UNIQUE,
    tenant_id      int                   NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    template_id    int                   NOT NULL REFERENCES email.templates(id) ON DELETE CASCADE,
    version_number integer               NOT NULL,
    status         email.template_status NOT NULL DEFAULT 'draft',
    subject        text                  NOT NULL DEFAULT '',
    preheader      text                  NOT NULL DEFAULT '',
    schema         jsonb                 NOT NULL DEFAULT '{}'::jsonb,
    metadata       jsonb,
    created_by     uuid                  NOT NULL REFERENCES auth.users(id),
    published_by   uuid                  REFERENCES auth.users(id),
    published_at   timestamptz,
    created_at     timestamptz           NOT NULL DEFAULT now(),
    UNIQUE (template_id, version_number)
);
CREATE INDEX email_template_versions_template_idx ON email.template_versions(template_id);

-- Deferred FK templates → template_versions (circular; both rows insert in one txn on first publish).
ALTER TABLE email.templates
    ADD CONSTRAINT fk_email_current_published_version
    FOREIGN KEY (current_published_version_id)
    REFERENCES email.template_versions(id)
    DEFERRABLE INITIALLY DEFERRED;

-- ── RLS + grants (claim-driven, per 0001) ─────────────────────────────────────
-- Staff-scoped; no client branch (clients don't author templates).
ALTER TABLE email.templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE email.templates FORCE ROW LEVEL SECURITY;
CREATE POLICY email_templates_read ON email.templates FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY email_templates_write ON email.templates FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON email.templates TO authenticated;
GRANT ALL ON email.templates TO service_role;

ALTER TABLE email.template_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE email.template_versions FORCE ROW LEVEL SECURITY;
CREATE POLICY email_template_versions_read ON email.template_versions FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY email_template_versions_write ON email.template_versions FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON email.template_versions TO authenticated;
GRANT ALL ON email.template_versions TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA email TO authenticated, service_role;

SELECT audit.attach(ARRAY['email.templates', 'email.template_versions']);
