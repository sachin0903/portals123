-- ============================================================================
-- 0263_client_groups — firm-owned tags a client can wear, such as a business
-- stream, so a portal design can follow the tag.
--
-- A book (0181) is one label, mostly derived, and it also decides whether the
-- client may move money. A group is assigned, a client may wear several, and
-- it does not grant a capability. Free-form contact tags (0044) stay the
-- automation labels: no catalogue, no slug, not readable by the client.
-- Design: docs/client-groups.md.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE TABLE crm.client_groups (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  name text NOT NULL
    CHECK (length(btrim(name)) BETWEEN 1 AND 40),
  slug text NOT NULL
    CHECK (slug ~ '^[a-z0-9-]{1,32}$'),
  description text NOT NULL DEFAULT ''
    CHECK (length(description) <= 160),
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, slug),
  -- The membership row's composite FK. A bare group_id would let a row point
  -- at another firm's group.
  UNIQUE (tenant_id, id)
);

CREATE INDEX client_groups_tenant_idx
  ON crm.client_groups(tenant_id, sort_order, id);

ALTER TABLE crm.client_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm.client_groups FORCE ROW LEVEL SECURITY;

-- Clients may READ the catalogue (auth.tenant_id() — the hook resolves a
-- design from the slugs). They cannot WRITE. Helpers are scalar subqueries
-- so the planner runs them once.
CREATE POLICY client_groups_read ON crm.client_groups
  FOR SELECT TO authenticated
  USING (
    tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[])
    OR tenant_id = (SELECT auth.tenant_id())
  );
CREATE POLICY client_groups_write ON crm.client_groups
  FOR ALL TO authenticated
  USING (tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[]))
  WITH CHECK (tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[]));

GRANT SELECT, INSERT, UPDATE, DELETE ON crm.client_groups TO authenticated;
GRANT ALL ON crm.client_groups TO service_role;
GRANT USAGE, SELECT ON SEQUENCE crm.client_groups_id_seq TO authenticated, service_role;

-- Who wears which group. A client reads only their own rows (contact_scope);
-- the catalogue of names is the table above. Deleting a group or a contact
-- drops the membership.
CREATE TABLE crm.contact_groups (
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  group_id int NOT NULL REFERENCES crm.client_groups(id) ON DELETE CASCADE,
  PRIMARY KEY (contact_id, group_id),
  CONSTRAINT contact_groups_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id)
    REFERENCES crm.contacts (tenant_id, id)
    ON DELETE CASCADE,
  CONSTRAINT contact_groups_group_tenant_fkey
    FOREIGN KEY (tenant_id, group_id)
    REFERENCES crm.client_groups (tenant_id, id)
    ON DELETE CASCADE
);

CREATE INDEX contact_groups_group_idx ON crm.contact_groups(tenant_id, group_id);

ALTER TABLE crm.contact_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm.contact_groups FORCE ROW LEVEL SECURITY;

CREATE POLICY contact_groups_read ON crm.contact_groups
  FOR SELECT TO authenticated
  USING (
    tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[])
    OR contact_id = ANY ((SELECT auth.contact_scope())::integer[])
  );
CREATE POLICY contact_groups_write ON crm.contact_groups
  FOR ALL TO authenticated
  USING (tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[]))
  WITH CHECK (tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[]));

GRANT SELECT, INSERT, UPDATE, DELETE ON crm.contact_groups TO authenticated;
GRANT ALL ON crm.contact_groups TO service_role;
