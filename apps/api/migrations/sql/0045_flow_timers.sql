-- ============================================================================
-- 0045_flow_timers.sql -- TIME, as a durable fact.
--
-- Flows v3 Phase B makes a flow a graph, and two of its control nodes are about
-- waiting:
--
--   * `wait`            -- pause the case for a duration, or until a date carried
--                          in case memory / a subject field, then resume at the
--                          node's successor.
--   * `wait_for_event`  -- park the case until one of the trigger registry's
--                          events happens FOR THIS CASE'S SUBJECT, with an
--                          optional deadline that takes a `timeout_branch`.
--
-- Both need state that outlives the process. A worker that is redeployed, OOM'd
-- or scaled to zero at 03:00 must not lose a client's seven-day chaser: "resume
-- this case at this instant" is a promise made to a firm, so it is a committed
-- row, not an asyncio task. That durability is the entire point of this file.
--
-- TWO tables, because they answer two different questions and only one of them
-- is always present:
--
--   * flows.timers         -- a pending WAKE-UP. One row per armed deadline.
--   * flows.case_listeners -- a case is LISTENING for a trigger on a subject.
--
-- They are not one table with a nullable column: `wait_for_event`'s
-- `timeout_days` is optional in the contract, so a listener frequently has no
-- timer at all, and folding the listener into the timer row would mean an
-- un-timed listener had nowhere to live (the automation consumer would find
-- nothing to match and the case would wait forever). Conversely a plain `wait`
-- has a timer and listens for nothing. Where a node has both, the listener
-- points at its timer so releasing one retires the other.
--
-- The cross-language source of truth for the node config
-- (`duration_days`/`duration_hours`/`until_date_field`, `trigger`/`conditions`/
-- `timeout_days`/`timeout_branch`) and for `caps.maxWaitDays` is
-- pkgs/ui/src/lib/components/book/journeys/flow-contract.json; the Python side
-- mirrors what it needs in app/flows/triggers.py, pinned by
-- tests/test_flow_contract.py.
--
-- Expand-only. Nothing here changes existing behaviour: with no rows in either
-- table the timer loop is a due-query that returns nothing and the automation
-- consumer's listener check is one indexed lookup that matches nothing.
-- ============================================================================

-- Policy/constraint changes below take short ACCESS EXCLUSIVE locks. Fail fast
-- rather than queue behind a long transaction (the 0024 convention).
SET LOCAL lock_timeout = '5s';

-- ---- flows.timers -- one pending wake-up -------------------------------------
CREATE TABLE flows.timers (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                       -- 'tmr_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

  -- The case whose control sits on `node_id`. ON DELETE CASCADE: a deleted case
  -- has no successor to resume at, so an orphaned timer is not a thing to keep.
  case_id int NOT NULL REFERENCES flows.cases(id) ON DELETE CASCADE,
  -- Denormalised from the case for the operator surfaces ("what is this run
  -- waiting on?") without a join. Nullable because a case need not belong to an
  -- execution in the v1 single-case shape.
  execution_id int REFERENCES flows.executions(id) ON DELETE CASCADE,

  -- The graph node the case is parked on -- NOT a flows.case_steps row: a
  -- control node is not work, so it has no step record. Resumption is
  -- "orchestrator, this node's wait is over", and the orchestrator reads the
  -- node out of the pinned definition to find the successor.
  node_id text NOT NULL,

  -- What firing this timer MEANS. The two are genuinely different transitions,
  -- and the loop must not have to re-derive which by inspecting the definition:
  --   'wait'                   -> resume at the node's normal successor.
  --   'wait_for_event_timeout' -> the deadline passed; take the timeout_branch.
  kind text NOT NULL CHECK (kind IN ('wait', 'wait_for_event_timeout')),

  fire_at timestamptz NOT NULL,

  -- Whatever the resuming transition needs that the node id alone does not carry
  -- (the resolved timeout branch, the authored config snapshot, the trigger the
  -- listener was armed on). Snapshotted rather than re-read, for the outbox's
  -- reason: by the time this fires the flow may have been re-published.
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,

  -- pending -> fired | cancelled | dead_letter.
  -- `dead_letter` is the fourth state the mission's three imply: a resume that
  -- keeps raising must stop being retried and start being a human's problem,
  -- exactly as flows.outbox does. Without it a poisonous timer is either retried
  -- for ever (wedging nothing, but never resolving) or silently marked 'fired'
  -- when it never resumed anything -- and a case that was told to wake up and
  -- did not is precisely the failure this whole table exists to prevent.
  state text NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending', 'fired', 'cancelled', 'dead_letter')),

  attempts int NOT NULL DEFAULT 0,
  max_attempts int NOT NULL DEFAULT 8,
  last_error text,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  fired_at timestamptz,
  cancelled_at timestamptz
);

-- THE due query: "pending timers whose moment has come, oldest first". Partial
-- on `state` because a fired/cancelled timer is never due again, and the include
-- order matches the loop's ORDER BY exactly, so claiming is an index range scan
-- of the head rather than a walk of every timer ever armed.
CREATE INDEX timers_due_idx ON flows.timers (fire_at, id) WHERE state = 'pending';

-- AT MOST ONE pending timer per (case, node). Re-entering a node whose wait is
-- already armed must RE-ARM it, not stack a second wake-up -- the engine's
-- resume path is at-least-once, so `schedule()` is written as an upsert against
-- this index and is therefore idempotent under replay. (Two pending timers on
-- one node would resume the same case twice, which for a `wait_for_event` node
-- means taking the timeout branch after the event already released it.)
CREATE UNIQUE INDEX timers_pending_node_idx
  ON flows.timers (case_id, node_id) WHERE state = 'pending';

-- ---- flows.case_listeners -- a case parked on `wait_for_event` ---------------
-- The mechanism by which the EXISTING automation consumer (app/flows/automation.py,
-- Phase A) notices that a running journey is waiting for the event it just read
-- off audit.actions. Deliberately a table rather than a query over the timers'
-- jsonb: an un-timed listener has no timer row to query, and the consumer's hot
-- path deserves a plain b-tree lookup rather than a jsonb expression index.
CREATE TABLE flows.case_listeners (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                       -- 'lsn_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  case_id int NOT NULL REFERENCES flows.cases(id) ON DELETE CASCADE,
  node_id text NOT NULL,

  -- The FRIENDLY registry key (e.g. 'client.document_uploaded'), never the raw
  -- event type -- the same indirection flows.automations.trigger_key uses, and
  -- for the same reason: a renamed route is re-pointed in the registry and every
  -- parked case keeps listening.
  trigger_key text NOT NULL,

  -- THE CORRECTNESS-CRITICAL PART. A document uploaded for client A must not
  -- release client B's waiting case, and an account event must not release a
  -- contact-scoped listener just because the two ids happen to collide (they are
  -- different id spaces -- account 7 is not contact 7). So the subject is stored
  -- as a KIND + an ID and BOTH are compared on release, and both are NOT NULL:
  -- an unscoped listener is not a weaker listener, it is a leak. A case whose
  -- subject cannot be resolved in the trigger's own subject space is refused a
  -- listener at arm time (app/flows/timers.py::arm_listener) and degrades to
  -- timeout-only, which is visible and safe rather than silent and wrong.
  subject_kind text NOT NULL,
  subject_id int NOT NULL,

  -- Optional extra conditions the author put on the node, evaluated by the ONE
  -- shared evaluator (app/flows/conditions.py) against the same flat dotted-path
  -- facts the entry conditions of an automation see. NULL = unconditional.
  conditions jsonb,

  -- The paired deadline, when the node authored one. ON DELETE SET NULL rather
  -- than CASCADE: retiring the timeout must not delete the record that a case
  -- was listening.
  timer_id bigint REFERENCES flows.timers(id) ON DELETE SET NULL,

  state text NOT NULL DEFAULT 'active'
    CHECK (state IN ('active', 'released', 'cancelled')),
  -- The audit.actions row that released it, for "why did this case move on?".
  released_event_id bigint,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  released_at timestamptz,
  cancelled_at timestamptz
);

-- THE consumer hot path: "is any live case in this firm listening for this
-- trigger, about this subject?". Partial on `state`, and ordered so the whole
-- match is one index probe -- the automation consumer runs this once per event
-- that is already on the curated trigger menu (a tiny slice of the stream), so
-- it must not cost a scan.
CREATE INDEX case_listeners_match_idx
  ON flows.case_listeners (tenant_id, trigger_key, subject_kind, subject_id)
  WHERE state = 'active';

-- One active listener per (case, node), for the same re-entry reason as timers.
CREATE UNIQUE INDEX case_listeners_node_idx
  ON flows.case_listeners (case_id, node_id) WHERE state = 'active';

-- Cancelling every listener of a case (it completed, or was cancelled) without
-- naming their nodes.
CREATE INDEX case_listeners_case_idx
  ON flows.case_listeners (case_id) WHERE state = 'active';

-- ============================================================================
-- ROW LEVEL SECURITY
-- ============================================================================
-- Both tables are ENGINE state, written only by the worker and the orchestrator
-- on a service_role session. service_role ONLY: no `authenticated` grant and no
-- policy at all -- withholding the privilege beats an always-false policy (the
-- flows.outbox / flows.automation_deliveries / aml.operator_secrets precedent).
--
-- A firm-facing "what is this journey waiting for, and until when?" surface
-- ships as a permission-gated endpoint reading on service_role, exactly the way
-- audit.actions is read by GET /admin/audit/actions -- NOT by opening these
-- tables to `authenticated`.
ALTER TABLE flows.timers ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.timers TO service_role;

ALTER TABLE flows.case_listeners ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.case_listeners TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA flows TO authenticated, service_role;

-- ============================================================================
-- updated_at triggers, audit attach, FORCE RLS (bind even the migrator owner).
-- ============================================================================
CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.timers
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.case_listeners
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Attached, unlike flows.automation_deliveries. The distinction 0043 drew is
-- volume against compliance value: deliveries are one row per candidate
-- CONSIDERED (the whole action stream, times every armed rule), whereas a timer
-- is one row per wait a journey actually enters -- the same order of magnitude as
-- flows.executions, which is attached. And the question these rows answer is a
-- compliance question: "this client's case sat still for nine days -- was that
-- authored, and did anything cancel it?"
SELECT audit.attach(ARRAY['flows.timers', 'flows.case_listeners']);

ALTER TABLE flows.timers FORCE ROW LEVEL SECURITY;
ALTER TABLE flows.case_listeners FORCE ROW LEVEL SECURITY;
