-- 0010_form_responses: persist completed forms + link a request item to its form.
--
-- FEATURE: a client can complete an adviser-requested form in-app and have the answers stored.
--  * request_items.form_uid  — the builder form a `complete_form` item points at (the form's stable
--    uid; forms still live in the app/mock layer, so this is plain text with no FK yet). Replaces the
--    earlier hack of carrying the form code in `category`.
--  * documents.form_responses — one submitted set of answers per fulfilled complete_form item, stored
--    as a jsonb blob keyed by fieldKey (exactly what DynamicForm.collect() produces). `answers`, not
--    `values` (a reserved word). Bound to auth.users for now (interim) — reconcile with crm.contacts
--    later, like the other collab tables. See docs/forms.md and docs/document-management.md.

ALTER TABLE documents.request_items ADD COLUMN form_uid text;

CREATE TABLE documents.form_responses (
    id               int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid              text        NOT NULL UNIQUE,
    tenant_id        int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,  -- denormalised for RLS
    request_item_id  int         NOT NULL REFERENCES documents.request_items(id) ON DELETE CASCADE,
    form_uid         text        NOT NULL,
    user_id          uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,  -- TEMP: -> crm.contacts
    answers          jsonb       NOT NULL DEFAULT '{}'::jsonb,  -- keyed by fieldKey (collect() output)
    submitted_by     uuid        REFERENCES auth.users(id),
    submitted_at     timestamptz NOT NULL DEFAULT now(),
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX form_responses_tenant_idx ON documents.form_responses(tenant_id);
CREATE INDEX form_responses_item_idx ON documents.form_responses(request_item_id);

-- Staff manage responses for their tenant; the submitting client may READ their own (via the
-- denormalised user_id — no subquery, so no RLS recursion). Clients never write directly (their
-- tenant lineage is empty) — they submit through the service_role endpoint — so writes are staff-only,
-- matching documents.request_items.
ALTER TABLE documents.form_responses ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents.form_responses FORCE ROW LEVEL SECURITY;
CREATE POLICY form_responses_read ON documents.form_responses FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()) OR user_id = auth.uid());
CREATE POLICY form_responses_write ON documents.form_responses FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON documents.form_responses TO authenticated;
GRANT ALL ON documents.form_responses TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA documents TO authenticated, service_role;

SELECT audit.attach(ARRAY['documents.form_responses']);
