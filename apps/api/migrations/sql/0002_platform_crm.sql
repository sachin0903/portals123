  tenant_id = ANY (auth.tenant_lineage())
  AND (
    auth.can_read_all()
    OR from_contact_id = ANY (auth.contact_scope())
    OR to_contact_id = ANY (auth.contact_scope())
  )
);
GRANT SELECT ON crm.relationships TO authenticated;
GRANT ALL ON crm.relationships TO service_role;

-- ---- crm.applications (STAFF-facing onboarding state; adviser sees own) ----
ALTER TABLE crm.applications ENABLE ROW LEVEL SECURITY;
CREATE POLICY applications_read ON crm.applications FOR SELECT TO authenticated USING (
  (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
  OR adviser_id = auth.uid()
