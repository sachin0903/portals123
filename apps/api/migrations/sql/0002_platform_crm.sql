-- ============================================================================
-- auth.resolve_claims() -- RE-DEFINED (0001 shipped it with empty contact/account
-- scope + a "filled in 0002" marker). CREATE OR REPLACE keeps the existing signature
-- and service_role ownership (migrator is a member of service_role -> allowed).
--
-- The scoped half of the two-layer RLS resolves through the contact_ids/account_ids
-- claims this mints -- the OWN scope of the login: the parties it may act for as a
-- client end-user (crm.contact_users) and/or the book it holds as staff
-- (crm.client_advisers), plus those parties' accounts. The "see the whole firm" bypass
-- is auth.can_read_all() (JWT permission 'contacts:read_all'), evaluated in the policy,
-- NOT here. Fail-closed: no links => empty scope (sees only via read_all, if granted).
-- SECURITY DEFINER owned by the BYPASSRLS service_role, so it reads crm/platform freely.
-- ============================================================================
CREATE OR REPLACE FUNCTION auth.resolve_claims(p_workos_user_id text, p_workos_org_id text)
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'auth' AS $fn$
DECLARE
  v_user_uuid  uuid;
  v_tenant_id  int;
  v_tenant_ids int[];
  v_contact_ids int[];
  v_account_ids int[];
BEGIN
  -- Project-per-tenant (§0): the tenant is a property of the LOGIN. Resolve the user and
  -- take its tenant; p_workos_org_id stays only as a transitional fallback for logins not
  -- yet backfilled with tenant_id (and psql sessions).
  SELECT id, tenant_id INTO v_user_uuid, v_tenant_id FROM auth.users
    WHERE workos_user_id = p_workos_user_id AND deleted_at IS NULL;

  IF v_tenant_id IS NULL THEN
    SELECT id INTO v_tenant_id FROM auth.tenants
      WHERE workos_organisation_id = p_workos_org_id;
  END IF;

  IF v_tenant_id IS NOT NULL THEN
    SELECT COALESCE(array_agg(id), '{}'::int[]) INTO v_tenant_ids
      FROM auth.tenants WHERE v_tenant_id = ANY(lineage);
  ELSE
    v_tenant_ids := '{}'::int[];
  END IF;

  -- OWN client scope: parties reachable as a client (contact_users) or assigned as staff
  -- (client_advisers). DISTINCT so a party held both ways appears once.
  IF v_user_uuid IS NOT NULL THEN
    SELECT COALESCE(array_agg(DISTINCT cid), '{}'::int[]) INTO v_contact_ids FROM (
      SELECT contact_id AS cid FROM crm.contact_users   WHERE user_id = v_user_uuid
      UNION
      SELECT contact_id AS cid FROM crm.client_advisers WHERE adviser_id = v_user_uuid
    ) s;
  ELSE
    v_contact_ids := '{}'::int[];
  END IF;

  -- The accounts of those parties -- both the owning account (accounts.contact_id) and
  -- any multi-party account the contact is on (account_contacts).
  IF array_length(v_contact_ids, 1) IS NOT NULL THEN
    SELECT COALESCE(array_agg(DISTINCT aid), '{}'::int[]) INTO v_account_ids FROM (
      SELECT id AS aid FROM platform.accounts WHERE contact_id = ANY(v_contact_ids)
      UNION
      SELECT account_id AS aid FROM crm.account_contacts
        WHERE contact_id = ANY(v_contact_ids) AND account_id IS NOT NULL
    ) s;
  ELSE
    v_account_ids := '{}'::int[];
  END IF;

  RETURN jsonb_build_object(
    'user_uuid',   v_user_uuid,
    'tenant_id',   v_tenant_id,
    'tenant_ids',  to_jsonb(v_tenant_ids),
    'contact_ids', to_jsonb(v_contact_ids),
    'account_ids', to_jsonb(v_account_ids)
  );
END;
$fn$;

GRANT EXECUTE ON FUNCTION auth.resolve_claims(text, text) TO authenticated, service_role;
-- Preserve the BYPASSRLS owner explicitly (CREATE OR REPLACE keeps it, but be plain).
ALTER FUNCTION auth.resolve_claims(text, text) OWNER TO service_role;

-- ============================================================================
-- ROW LEVEL SECURITY
--
-- Reference catalog (platforms/products): non-sensitive, read to authenticated USING
-- (true); writes service_role only. Firm-scoped catalog (models/fee_packages): read
-- within the caller's tenant lineage.
--
-- Client data (contacts/accounts/transactions + the join tables): the two-layer pattern
--   (auth.can_read_all() AND tenant_id = ANY(auth.tenant_lineage()))   -- read_all staff
--   OR <scope predicate>                                               -- scope-bound
-- A client has EMPTY lineage (auth.tenant_lineage()), so the staff layer never fires for
-- them -- they reach data ONLY through the scope predicate. Writes are service_role only
-- (provisioning/sync + firm_session run as service_role); no authenticated write policy
-- => authenticated writes are denied.
-- ============================================================================

-- ---- platform catalog ----
ALTER TABLE platform.platforms ENABLE ROW LEVEL SECURITY;
CREATE POLICY platforms_read ON platform.platforms FOR SELECT TO authenticated USING (true);
GRANT SELECT ON platform.platforms TO authenticated;
GRANT ALL ON platform.platforms TO service_role;

ALTER TABLE platform.products ENABLE ROW LEVEL SECURITY;
CREATE POLICY products_read ON platform.products FOR SELECT TO authenticated USING (true);
GRANT SELECT ON platform.products TO authenticated;
GRANT ALL ON platform.products TO service_role;

ALTER TABLE platform.models ENABLE ROW LEVEL SECURITY;
