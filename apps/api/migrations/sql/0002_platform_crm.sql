-- ============================================================================
-- 0002_platform_crm.sql -- the CRM/party + accounts + transactions domain, and the
-- client-scoped two-layer RLS it turns on. Client-core slice (docs/data-architecture.md
-- §8.2, Decision 8): the smallest forward step that makes clients + accounts real.
--
-- What this migration lands:
--   * enums for the platform catalog + crm party model;
--   * the platform catalog tables platform.accounts FK-needs (platforms, products,
--     models, fee_packages) -- reference data, read to authenticated;
--   * crm.contacts (THE CLIENT AS DATA -- Decision 8: the contact *is* the client, there
--     is no separate client entity) + the login<->party bridge (crm.contact_users) + the
--     staff-assignment book (crm.client_advisers) + notes/relationships/applications and
--     the application<->contact join (crm.account_contacts);
--   * platform.accounts (owned by a contact) + platform.transactions (the realised fact);
--   * the two-layer RLS -- (read_all staff within the firm lineage) OR (scope-bound
--     adviser/client) -- on contacts/accounts/transactions and the related tables;
--   * auth.resolve_claims re-defined to FILL contact_ids/account_ids (0001 left them empty
--     with a "filled in 0002" marker) from crm.contact_users + crm.client_advisers, so the
--     scoped layer of every policy above actually resolves per request;
--   * the DML audit triggers on the sensitive new tables.
--
-- Deferred to later phases (docs/data-architecture.md §8): the wider platform catalog
-- (platform_tenants, product_providers, countries/currencies, advisers, terms,
-- platform_links, domains), integrations (providers/connections/sync_jobs), the money
-- ledger + pensions domain (0003), natural income (0004), and the inbound provider sync.
-- ============================================================================

