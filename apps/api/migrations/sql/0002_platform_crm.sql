-- ============================================================================
-- updated_at + audit triggers, then FORCE RLS (bind even the migrator owner).
-- ============================================================================

-- Attach set_updated_at to every crm/platform table with an updated_at column
-- (contacts, applications, accounts, transactions).
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.table_schema, c.table_name
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.column_name = 'updated_at'
      AND t.table_type = 'BASE TABLE'
      AND c.table_schema IN ('crm', 'platform')
  LOOP
    EXECUTE format(
      'CREATE TRIGGER set_updated_at BEFORE UPDATE ON %I.%I '
      'FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()',
      r.table_schema, r.table_name);
  END LOOP;
END $$;

-- Sensitive domain tables: client PII, account holdings, money, and the party/staff
-- links (who can see whom) are all security-relevant (docs/data-architecture.md C2).
SELECT audit.attach(ARRAY[
  'crm.contacts', 'crm.contact_users', 'crm.client_advisers', 'crm.account_contacts',
  'crm.applications', 'platform.accounts', 'platform.transactions'
]);

-- FORCE RLS so even the table OWNER (the migrator) is subject to policies.
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT schemaname, tablename FROM pg_tables WHERE schemaname IN ('crm', 'platform')
  LOOP
    EXECUTE format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY', r.schemaname, r.tablename);
  END LOOP;
END $$;
