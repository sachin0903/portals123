GRANT ALL ON platform.fee_packages TO service_role;

-- ---- crm.contacts (the client) ----
ALTER TABLE crm.contacts ENABLE ROW LEVEL SECURITY;
CREATE POLICY contacts_read ON crm.contacts FOR SELECT TO authenticated USING (
  (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
  OR id = ANY (auth.contact_scope())
);
GRANT SELECT ON crm.contacts TO authenticated;
GRANT ALL ON crm.contacts TO service_role;

-- ---- crm.contact_users (login<->party bridge) ----
ALTER TABLE crm.contact_users ENABLE ROW LEVEL SECURITY;
CREATE POLICY contact_users_read ON crm.contact_users FOR SELECT TO authenticated USING (
  user_id = auth.uid()
  OR (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
  OR contact_id = ANY (auth.contact_scope())
);
GRANT SELECT ON crm.contact_users TO authenticated;
GRANT ALL ON crm.contact_users TO service_role;

-- ---- crm.client_advisers (the adviser's book) ----
ALTER TABLE crm.client_advisers ENABLE ROW LEVEL SECURITY;
CREATE POLICY client_advisers_read ON crm.client_advisers FOR SELECT TO authenticated USING (
  adviser_id = auth.uid()
  OR (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
  OR contact_id = ANY (auth.contact_scope())
);
GRANT SELECT ON crm.client_advisers TO authenticated;
GRANT ALL ON crm.client_advisers TO service_role;

-- ---- crm.contact_notes (STAFF-internal: a client never reads notes about themselves) ----
ALTER TABLE crm.contact_notes ENABLE ROW LEVEL SECURITY;
CREATE POLICY contact_notes_read ON crm.contact_notes FOR SELECT TO authenticated USING (
  tenant_id = ANY (auth.tenant_lineage())
  AND (auth.can_read_all() OR contact_id = ANY (auth.contact_scope()))
);
