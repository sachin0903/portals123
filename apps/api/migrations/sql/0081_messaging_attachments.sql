-- ============================================================================
-- 0081_messaging_attachments -- file attachments on the client<->adviser chat
-- (0080_messaging). Client and staff can attach one file per message (pdf,
-- word, excel, powerpoint, txt); the blob lives in the TENANT'S OWN bucket
-- (storage.tenants / app/tenant_storage.py), never the shared documents
-- bucket -- a chat attachment is exactly the per-tenant-sovereignty case that
-- bucket exists for. Stored under `attachments/{conversation_id}/{message_id}.
-- {ext}`, deliberately NOT under `files/tenant/` -- that prefix carries a
-- public-read bucket policy for branding assets, and an attachment is private.
--
-- messaging.attachments -- one row per message that carries a file (message_id
--   UNIQUE: at most one attachment per message, the "staged" UX this ships
--   with -- add a message-attachment join table only if that stops being
--   true). `tenant_id`/`contact_id` are denormalised from the parent message
--   for the same reason messages denormalises them from its conversation: the
--   read/insert policy is a plain column check, no subquery against another
--   RLS-protected table. Append-only, like messages itself.
--
-- messages.body becomes nullable: a message may now be attachment-only. "At
-- least one of body/attachment is present" is enforced in app/messaging.py,
-- not a CHECK here -- same call already made for sender_kind/sender_user_id
-- pairing on this table (a CHECK can't see a sibling table's row anyway,
-- since the attachment is a separate INSERT after the message's).
-- ============================================================================

SET LOCAL lock_timeout = '5s';

ALTER TABLE messaging.messages ALTER COLUMN body DROP NOT NULL;
ALTER TABLE messaging.messages DROP CONSTRAINT messages_body_check;
ALTER TABLE messaging.messages
  ADD CONSTRAINT messages_body_check CHECK (body IS NULL OR btrim(body) <> '');

CREATE TABLE messaging.attachments (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  contact_id int NOT NULL,
  CONSTRAINT attachments_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE,
  message_id bigint NOT NULL UNIQUE REFERENCES messaging.messages(id) ON DELETE CASCADE,
  bucket text NOT NULL,
  storage_key text NOT NULL,
  -- The uploader's original filename (display + download disposition) -- never used to build
  -- the storage key itself, which is derived server-side from the sniffed content-type's ext.
  filename text NOT NULL,
  content_type text NOT NULL,
  size_bytes bigint NOT NULL CHECK (size_bytes > 0),
  sha256 text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT attachments_bucket_key_key UNIQUE (bucket, storage_key)
);
CREATE INDEX attachments_tenant_id_idx ON messaging.attachments(tenant_id);
CREATE INDEX attachments_contact_id_idx ON messaging.attachments(contact_id);

ALTER TABLE messaging.attachments ENABLE ROW LEVEL SECURITY;
CREATE POLICY attachments_read ON messaging.attachments FOR SELECT TO authenticated USING (
  tenant_id = ANY (auth.tenant_lineage())
  OR contact_id = ANY (auth.contact_scope())
);
CREATE POLICY attachments_insert ON messaging.attachments FOR INSERT TO authenticated WITH CHECK (
  tenant_id = ANY (auth.tenant_lineage())
  OR contact_id = ANY (auth.contact_scope())
);
-- Append-only, same rationale as messaging.messages: no UPDATE/DELETE grant.
GRANT SELECT, INSERT ON messaging.attachments TO authenticated;
GRANT ALL ON messaging.attachments TO service_role;

-- Re-run for the new table's identity sequence -- the 0051 grant only covered sequences that
-- existed at the time it ran.
GRANT USAGE ON ALL SEQUENCES IN SCHEMA messaging TO authenticated, service_role;

SELECT audit.attach(ARRAY['messaging.attachments']);
ALTER TABLE messaging.attachments FORCE ROW LEVEL SECURITY;
