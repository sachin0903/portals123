-- ============================================================================
-- 0149_platform_illustrations.sql -- illustrations as their own record, linked to the PDF.
--
-- Filing a CTC illustration wrote a `documents.documents` row (`document_type = 'illustration'`)
-- and nothing else. That made the listing a filter over paperwork, and meant the assumptions the
-- PDF was built on lived only in `documents.inputs` — a jsonb dump the documents projection does
-- not expose. A generated illustration is a domain fact about a client (and optionally an account),
-- with a PDF as its artefact, so it belongs in `platform` beside contributions and transfers.
--
-- The document is kept: sharing, the client portal, and the viewer all already address it. This
-- table is the listing and the provenance; `document_id` is nullable so an illustration that was
-- produced but not stored (unconfigured object storage) can still be recorded later without
-- inventing a file.
-- ============================================================================

CREATE TABLE platform.illustrations (
  id          bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid         text          NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id   int           NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  contact_id  int           NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  account_id  int           REFERENCES platform.accounts(id) ON DELETE SET NULL,
  document_id uuid          REFERENCES documents.documents(id) ON DELETE SET NULL,

  name                   text,
  product_type           text,
  quotation_type         text,
  existing_fund_value    numeric(20,4),
  output_reference       text,
  placeholder            boolean      NOT NULL DEFAULT false,
  placeholder_reason     text,
  inputs                 jsonb        NOT NULL DEFAULT '{}'::jsonb,

  created_by  uuid          REFERENCES auth.users(id),
  created_at  timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX illustrations_tenant_contact_idx
  ON platform.illustrations (tenant_id, contact_id, created_at DESC);
CREATE INDEX illustrations_document_idx
  ON platform.illustrations (document_id) WHERE document_id IS NOT NULL;

COMMENT ON TABLE platform.illustrations IS
  'A CTC pension illustration produced for a client. The PDF is the linked documents.documents row; '
  'this row is the listing and the assumptions it was built on.';

-- Tenant containment on the client/account links (0035). A bare contact_id can point into another
-- firm, and the client branch of the read policy (`contact_id = ANY (auth.contact_scope())`) carries
-- no tenant conjunct — so a mis-tenanted row would be readable by the wrong firm's client.
ALTER TABLE platform.illustrations
  ADD CONSTRAINT illustrations_contact_tenant_fkey
  FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id)
  ON DELETE CASCADE;
ALTER TABLE platform.illustrations
  ADD CONSTRAINT illustrations_account_tenant_fkey
  FOREIGN KEY (tenant_id, account_id) REFERENCES platform.accounts (tenant_id, id)
  ON DELETE SET NULL (account_id);

ALTER TABLE platform.illustrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.illustrations FORCE ROW LEVEL SECURITY;

CREATE POLICY illustrations_read ON platform.illustrations
  FOR SELECT TO authenticated
  USING (
    tenant_id = ANY (auth.tenant_lineage())
    OR contact_id = ANY (auth.contact_scope())
  );
CREATE POLICY illustrations_write ON platform.illustrations
  FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

GRANT SELECT, INSERT, UPDATE, DELETE ON platform.illustrations TO authenticated;
GRANT ALL ON platform.illustrations TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA platform TO authenticated, service_role;

SELECT audit.attach(ARRAY['platform.illustrations']);

-- Existing illustration documents become rows. FORCE RLS means a backfill as the migrator sees
-- nothing and reports success; service_role is the role that can actually read the source.
SET LOCAL ROLE service_role;
INSERT INTO platform.illustrations (
  tenant_id, contact_id, document_id, name, product_type, quotation_type,
  existing_fund_value, output_reference, placeholder, placeholder_reason, inputs,
  created_by, created_at
)
SELECT DISTINCT ON (d.id)
  d.tenant_id,
  dc.contact_id,
  d.id,
  d.name,
  d.inputs->>'product_type',
  d.inputs->>'quotation_type',
  CASE
    WHEN jsonb_typeof(d.inputs->'existing_fund_value') = 'number'
      THEN (d.inputs->>'existing_fund_value')::numeric
  END,
  d.inputs->>'output_reference',
  COALESCE((d.inputs->>'placeholder')::boolean, false),
  d.inputs->>'placeholder_reason',
  COALESCE(d.inputs, '{}'::jsonb),
  d.generated_by,
  d.created_at
FROM documents.documents d
JOIN documents.document_contacts dc ON dc.document_id = d.id
WHERE d.document_type = 'illustration'
  AND d.status <> 'archived'
ORDER BY d.id, (dc.role = 'subject') DESC, dc.contact_id;
RESET ROLE;
