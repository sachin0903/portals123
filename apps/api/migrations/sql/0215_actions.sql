CREATE POLICY actions_policies_all ON actions.policies FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

CREATE POLICY actions_policy_roles_all ON actions.policy_roles FOR ALL TO authenticated
  USING (EXISTS (
    SELECT 1 FROM actions.policies p
    WHERE p.id = policy_id AND p.tenant_id = ANY (auth.tenant_lineage())
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM actions.policies p
    WHERE p.id = policy_id AND p.tenant_id = ANY (auth.tenant_lineage())
  ));

CREATE POLICY actions_runs_read ON actions.runs FOR SELECT TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR (
      tenant_id = ANY (auth.tenant_lineage())
      AND (
        requested_by = NULLIF(auth.jwt() ->> 'user_uuid', '')::uuid
        OR contact_id IS NULL
        OR contact_id = ANY (auth.contact_scope())
      )
    )
  );

CREATE POLICY actions_runs_write ON actions.runs FOR ALL TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR (
      tenant_id = ANY (auth.tenant_lineage())
      AND (
        requested_by = NULLIF(auth.jwt() ->> 'user_uuid', '')::uuid
        OR contact_id IS NULL
        OR contact_id = ANY (auth.contact_scope())
      )
    )
  )
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

CREATE POLICY actions_subjects_all ON actions.subjects FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

CREATE POLICY actions_steps_all ON actions.steps FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

-- Attempts are evidence. Reading is tenant-scoped. Writing must not fail because
-- the caller has no claims (the same rule as audit.api_log).
CREATE POLICY actions_http_read ON actions.http_requests FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR (tenant_id IS NULL AND auth.is_system()));
CREATE POLICY actions_http_append ON actions.http_requests FOR INSERT TO authenticated
  WITH CHECK (true);

CREATE POLICY actions_events_read ON actions.events FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR (tenant_id IS NULL AND auth.is_system()));
CREATE POLICY actions_events_append ON actions.events FOR INSERT TO authenticated
  WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON actions.policies TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON actions.policy_roles TO authenticated;
