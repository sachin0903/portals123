GRANT SELECT, INSERT, UPDATE ON actions.subjects TO authenticated;
GRANT SELECT, INSERT, UPDATE ON actions.steps TO authenticated;
GRANT SELECT, INSERT ON actions.http_requests TO authenticated;
GRANT SELECT, INSERT ON actions.events TO authenticated;

GRANT ALL ON actions.policies TO service_role;
