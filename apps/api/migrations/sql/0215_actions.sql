-- ============================================================================
-- 0215_actions.sql — the action registry (docs/actions.md).
--
-- A domain action (create an account, lodge a contribution) is code. A firm
-- enables it per provider on actions.policies. A run is the stateful job and,
-- when approval is on, the held command. Steps are the provider calls and the
-- queue. http_requests is one row per attempt. events is the thin "it happened"
-- stream.
--
-- Reviews, audit.actions, and audit.api_log keep their writers. These tables
-- are shaped so a later swap is a copy, not a redesign. Runs hold command
-- payloads (bank digits included) and are not audit.attach'd, same rule as
-- reviews.requests. http_requests and events are append-only.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE SCHEMA actions;
GRANT USAGE ON SCHEMA actions TO authenticated, service_role;

-- ---- policies ---------------------------------------------------------------

CREATE TABLE actions.policies (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  action_key text NOT NULL,
  -- Null for a book action (the peer-review catalogue). A provider action has
  -- one row per source, so Seccl and SEI can differ.
  provider text,
  enabled boolean NOT NULL DEFAULT false,
  approval_enabled boolean NOT NULL DEFAULT false,
  approval_role_id int REFERENCES auth.roles(id) ON DELETE SET NULL,
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE NULLS NOT DISTINCT (tenant_id, action_key, provider)
);

CREATE INDEX actions_policies_tenant_idx ON actions.policies(tenant_id);

CREATE TABLE actions.policy_roles (
  policy_id int NOT NULL REFERENCES actions.policies(id) ON DELETE CASCADE,
  role_id int NOT NULL REFERENCES auth.roles(id) ON DELETE CASCADE,
  PRIMARY KEY (policy_id, role_id)
);

-- ---- runs -------------------------------------------------------------------

CREATE TABLE actions.runs (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  action_key text NOT NULL,
  -- Snapshotted from the catalogue so a later rename does not rewrite history.
  event_type text NOT NULL,
  parent_run_id bigint REFERENCES actions.runs(id) ON DELETE CASCADE,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  before jsonb,
  requested_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  requested_at timestamptz NOT NULL DEFAULT now(),
  approval_role_id int REFERENCES auth.roles(id) ON DELETE SET NULL,
  decided_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  decided_at timestamptz,
  applied_at timestamptz,
  contact_id int REFERENCES crm.contacts(id) ON DELETE SET NULL,
  idempotency_key text NOT NULL,
  status text NOT NULL DEFAULT 'queued' CHECK (status IN (
    'awaiting_approval', 'rejected', 'cancelled', 'conflicted',
    'queued', 'running', 'succeeded', 'failed', 'needs_attention'
  )),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, idempotency_key)
);

CREATE INDEX actions_runs_tenant_status_idx ON actions.runs(tenant_id, status);
CREATE INDEX actions_runs_parent_idx ON actions.runs(parent_run_id) WHERE parent_run_id IS NOT NULL;
CREATE INDEX actions_runs_contact_idx ON actions.runs(contact_id) WHERE contact_id IS NOT NULL;

-- ---- subjects ---------------------------------------------------------------

CREATE TABLE actions.subjects (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  run_id bigint NOT NULL REFERENCES actions.runs(id) ON DELETE CASCADE,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  action_key text NOT NULL,
  entity_type text NOT NULL,
  entity_uid text NOT NULL,
  entity_id bigint,
  -- Maintained from the run status. The partial unique index is the one-open-hold
  -- rule reviews enforced on (action, subject).
  blocking boolean NOT NULL DEFAULT false
);

CREATE INDEX actions_subjects_run_idx ON actions.subjects(run_id);
CREATE UNIQUE INDEX actions_subjects_blocking_idx
  ON actions.subjects(tenant_id, action_key, entity_type, entity_uid)
  WHERE blocking;

-- ---- steps (the queue) ------------------------------------------------------

CREATE TABLE actions.steps (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  run_id bigint NOT NULL REFERENCES actions.runs(id) ON DELETE CASCADE,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  position int NOT NULL,
  provider text NOT NULL,
  operation_key text NOT NULL,
  status text NOT NULL DEFAULT 'queued' CHECK (status IN (
    'queued', 'running', 'succeeded', 'failed', 'skipped', 'needs_attention'
  )),
  retry_class text NOT NULL CHECK (retry_class IN ('safe', 'guarded', 'manual')),
  attempt_count int NOT NULL DEFAULT 0,
  idempotency_key text NOT NULL,
  last_error text,
  claimed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (run_id, position),
  UNIQUE (tenant_id, provider, operation_key, idempotency_key)
);

CREATE INDEX actions_steps_queued_idx ON actions.steps(id) WHERE status = 'queued';

-- ---- attempts ---------------------------------------------------------------

CREATE TABLE actions.http_requests (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  step_id bigint REFERENCES actions.steps(id) ON DELETE SET NULL,
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  provider text NOT NULL,
  service text,
  source text NOT NULL DEFAULT 'app' CHECK (source IN ('app', 'sync')),
  transport text NOT NULL DEFAULT 'http',
  method text,
  url text,
  operation text,
  request jsonb,
  response jsonb,
  status_code int,
  ok boolean NOT NULL,
  error text,
  duration_ms int,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX actions_http_requests_step_idx ON actions.http_requests(step_id, id);
CREATE INDEX actions_http_requests_tenant_idx ON actions.http_requests(tenant_id, created_at DESC);

-- ---- the thin stream --------------------------------------------------------

CREATE TABLE actions.events (
  id bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  event_type text NOT NULL,
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  target_tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_sub text,
  method text,
  route text,
  status int,
  path_params jsonb NOT NULL DEFAULT '{}'::jsonb,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  run_id bigint REFERENCES actions.runs(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX actions_events_tenant_cursor_idx ON actions.events(tenant_id, id) WHERE tenant_id IS NOT NULL;
CREATE INDEX actions_events_type_cursor_idx ON actions.events(event_type, id);
CREATE INDEX actions_events_run_idx ON actions.events(run_id) WHERE run_id IS NOT NULL;

-- ---- access -----------------------------------------------------------------

ALTER TABLE actions.policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE actions.policy_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE actions.runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE actions.subjects ENABLE ROW LEVEL SECURITY;
ALTER TABLE actions.steps ENABLE ROW LEVEL SECURITY;
