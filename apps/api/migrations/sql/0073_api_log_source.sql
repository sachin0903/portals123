-- Which half of the platform made an outgoing call, and the grant that lets the sync say so.
--
-- `audit.api_log` (0047) records what we said to a custodian. It could not say WHO SAID IT --
-- an adviser's action and a 3am cron pull landed as identical rows -- and that is the first
-- question anyone asks of the log, because both halves call the same operations. It cannot be
-- recovered after the fact from `operation` or `user_id`: a sync has no user, but neither does
-- a platform-wide token refresh on the request path.
--
-- Backfill is a no-op by luck rather than by design: the table is EMPTY. Every vendor client
-- accepted a recorder and no caller ever passed one, so the whole pipeline -- table, drain,
-- endpoints, admin page -- has been running with no producer since 0047. The default is 'app'
-- anyway, which is the right answer for anything a pre-existing row could have been.

ALTER TABLE audit.api_log
  ADD COLUMN source text NOT NULL DEFAULT 'app'
    CONSTRAINT api_log_source_check CHECK (source IN ('app', 'sync'));

COMMENT ON COLUMN audit.api_log.source IS
  'Which half of the platform made the call: app for a request path (an adviser created a '
  'client, an operator fired an action), sync for a provider daemon''s scheduled pull. A '
  'property of the PROCESS, stated once where persistence is configured -- see api_log.Source, '
  'which is kept in lockstep with this CHECK.';

-- Reading is "the sync''s failures last night" or "what did the app send today": source pairs
-- with recency the same way provider does.
CREATE INDEX api_log_source_idx ON audit.api_log (source, created_at DESC);

-- The sync services write their own rows now, as `book_writer` -- the narrow login from 0062
-- that reaches the merged relations and nothing else. They run in separate processes from the
-- API (an interlace daemon per provider), so they cannot use its queue-and-drain, and handing
-- them `service_role` to write an audit row would give a daemon the run of `auth.users`,
-- `documents.*` and `aml.*` to record that it called Seccl.
--
-- INSERT only, deliberately: the table is append-only, and 0047 makes that a fact about the
-- grants rather than a trigger. No UPDATE and no DELETE for the same reason `authenticated`
-- has none.
-- USAGE on the schema comes FIRST and is not optional: 0062 granted book_writer usage on
-- platform, crm and auth, and `audit` was not among them, so the table grant alone leaves every
-- INSERT failing with "permission denied for schema audit" -- swallowed by the drain's broad
-- handler into exactly the silent empty table 0047 already produced once. Caught by running the
-- INSERT as the role rather than by reading the grant.
GRANT USAGE ON SCHEMA audit TO book_writer;

-- No accompanying sequence grant: `id` is GENERATED BY DEFAULT AS IDENTITY, whose sequence
-- Postgres advances internally rather than through the caller's privileges. A `serial` would
-- have needed one, which is the trap this note exists to record -- and `test_api_log_source.py`
-- inserts as book_writer for real rather than trusting the reasoning.
GRANT INSERT ON audit.api_log TO book_writer;

-- No SELECT. A provider daemon writes evidence; it has no reason to read anyone else's, and
-- book_writer is BYPASSRLS, so a read grant here would be a cross-tenant read of every firm's
-- vendor traffic in exchange for nothing.
--
-- The consequence to know before writing a recorder: RETURNING needs SELECT on the columns it
-- names, so `INSERT ... RETURNING id` fails for this role. `book_sink.api_log` uses a plain
-- executemany, and a test pins the distinction.
