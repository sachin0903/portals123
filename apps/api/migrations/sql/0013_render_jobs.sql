-- 0013_render_jobs: the document render queue (docs/document-generation.md §8/§10).
--
-- A durable job table drained by the DocumentWorker with SELECT ... FOR UPDATE SKIP LOCKED — the
-- same claim / ack / retry / dead-letter contract PGMQ gives, without the extension. Deliberate
-- divergence from the spec's literal "PGMQ": it keeps the plain postgres:18 image (and its data
-- volume) and has no PG18 extension-availability risk. Swappable to PGMQ later behind the same
-- enqueue/claim interface. Not audit-attached — it's operational queue state, not a business entity.

CREATE TABLE documents.render_jobs (
    id           bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tenant_id    int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    document_id  uuid        NOT NULL REFERENCES documents.documents(id) ON DELETE CASCADE,
    status       text        NOT NULL DEFAULT 'queued'
                             CHECK (status IN ('queued', 'processing', 'done', 'failed')),
    attempts     int         NOT NULL DEFAULT 0,
    max_attempts int         NOT NULL DEFAULT 3,
    run_after    timestamptz NOT NULL DEFAULT now(),   -- visibility / retry backoff
    last_error   text,
    claimed_at   timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
-- The worker's hot path: the claimable set, oldest-ready first.
CREATE INDEX render_jobs_claim_idx ON documents.render_jobs (run_after) WHERE status = 'queued';
CREATE INDEX render_jobs_document_idx ON documents.render_jobs (document_id);

-- RLS: staff enqueue + read their own tenant's jobs; the worker runs as service_role (BYPASSRLS,
-- stamping tenant_id explicitly — the 0001 system pattern, §10).
ALTER TABLE documents.render_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents.render_jobs FORCE ROW LEVEL SECURITY;
CREATE POLICY render_jobs_read ON documents.render_jobs FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY render_jobs_insert ON documents.render_jobs FOR INSERT TO authenticated
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT ON documents.render_jobs TO authenticated;
GRANT ALL ON documents.render_jobs TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA documents TO authenticated, service_role;
