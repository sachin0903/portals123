-- ============================================================================
-- 0080_messaging -- a prototype client<->adviser chat (schema `messaging`).
--
-- Deliberately minimal for a first pass: ONE conversation per client, keyed to
-- whichever adviser `crm.client_advisers` currently names for that contact.
-- `adviser_user_id` is a MUTABLE pointer, re-synced whenever the client's own
-- session resolves the thread (see app/messaging.py) -- there is no reassignment
-- ledger yet (no `channel_adviser_history`). A firm's own audit trail already
-- carries "who reassigned this client's adviser, and when" via `audit.actions`
-- on whatever endpoint writes `crm.client_advisers`; add a dedicated ledger here
-- only if that stops being precise enough (exact handoff timestamp/actor,
-- queryable independent of chat activity).
--
-- messaging.conversations -- the channel: one row per (tenant, contact). No
--   message content, just identity + the two read-receipt watermarks the
--   unread badge is computed from (never a stored counter -- same "compute,
--   don't cache" rule the rest of the app follows for unread state).
-- messaging.messages -- append-only (no UPDATE/DELETE grant, like flows.ai_usage
--   and audit.actions): who sent it, when, to which conversation. `contact_id`/
--   `tenant_id` are denormalised from the parent conversation SO THAT the read
--   policy needs no subquery -- always written server-side (app/messaging.py),
--   never taken from caller input.
--
-- RLS is the mixed shape crm.client_advisers already uses: a client sees rows
-- for their own `contact_id` (auth.contact_scope()), staff see their tenant's
-- (auth.tenant_lineage()) -- no "read_all vs own book" split the way contacts
-- has, because requirement is "any tenant staff with the permission can search
-- the whole book's threads", not "only my assigned clients". Permission gating
-- (messages:read/write) is the API layer's job, same split of responsibility as
-- everywhere else: RLS proves tenant isolation, require_permission proves the
-- caller may use the feature.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE SCHEMA IF NOT EXISTS messaging;
GRANT USAGE ON SCHEMA messaging TO authenticated, service_role;

-- ---- messaging.conversations -------------------------------------------------
CREATE TABLE messaging.conversations (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  -- Composite link per 0035's invariant: a mis-tenanted contact_id would be
  -- readable through the contact_scope() branch below regardless of tenant_id.
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  CONSTRAINT conversations_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE,
  -- Mutable: re-synced from crm.client_advisers each time the client's own
  -- session resolves the thread. NULL means the firm hasn't assigned an
  -- adviser (the same state /crm/home's adviser block already handles).
  adviser_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  client_last_read_at timestamptz,
  staff_last_read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- One channel per client -- the business rule this whole feature rests on.
  CONSTRAINT conversations_tenant_contact_unique UNIQUE (tenant_id, contact_id)
);
CREATE INDEX conversations_tenant_id_idx ON messaging.conversations(tenant_id);
CREATE INDEX conversations_contact_id_idx ON messaging.conversations(contact_id);
CREATE INDEX conversations_adviser_id_idx ON messaging.conversations(adviser_user_id);

ALTER TABLE messaging.conversations ENABLE ROW LEVEL SECURITY;
CREATE POLICY conversations_read ON messaging.conversations FOR SELECT TO authenticated USING (
  tenant_id = ANY (auth.tenant_lineage())
  OR contact_id = ANY (auth.contact_scope())
);
-- ALL (not just INSERT/SELECT split) so the same policy covers the read-receipt
-- UPDATE (client_last_read_at/staff_last_read_at) from either side.
CREATE POLICY conversations_write ON messaging.conversations FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR contact_id = ANY (auth.contact_scope()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()) OR contact_id = ANY (auth.contact_scope()));
GRANT SELECT, INSERT, UPDATE ON messaging.conversations TO authenticated;
GRANT ALL ON messaging.conversations TO service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON messaging.conversations
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---- messaging.messages -------------------------------------------------------
CREATE TABLE messaging.messages (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  conversation_id bigint NOT NULL REFERENCES messaging.conversations(id) ON DELETE CASCADE,
  -- Denormalised from the parent conversation (never caller-supplied) so the
  -- read/insert policy is a plain column check, no subquery against another
  -- RLS-protected table.
  contact_id int NOT NULL,
  CONSTRAINT messages_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE,
  sender_kind text NOT NULL CHECK (sender_kind IN ('client', 'staff')),
  -- Exactly one of these is set, matching sender_kind; enforced in app/messaging.py
  -- (a CHECK could enforce it here too, left out for a prototype's first pass).
  sender_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  body text NOT NULL CHECK (btrim(body) <> ''),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX messages_conversation_id_created_at_idx
  ON messaging.messages(conversation_id, created_at);
CREATE INDEX messages_tenant_id_idx ON messaging.messages(tenant_id);
CREATE INDEX messages_contact_id_idx ON messaging.messages(contact_id);

ALTER TABLE messaging.messages ENABLE ROW LEVEL SECURITY;
CREATE POLICY messages_read ON messaging.messages FOR SELECT TO authenticated USING (
  tenant_id = ANY (auth.tenant_lineage())
  OR contact_id = ANY (auth.contact_scope())
);
CREATE POLICY messages_insert ON messaging.messages FOR INSERT TO authenticated WITH CHECK (
  tenant_id = ANY (auth.tenant_lineage())
  OR contact_id = ANY (auth.contact_scope())
);
-- Append-only: no UPDATE/DELETE grant, not even to service_role beyond ALL below
-- (kept consistent with flows.ai_usage/audit.actions -- a chat transcript is
-- exactly the kind of record that should not be quietly editable).
GRANT SELECT, INSERT ON messaging.messages TO authenticated;
GRANT ALL ON messaging.messages TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA messaging TO authenticated, service_role;

SELECT audit.attach(ARRAY['messaging.conversations', 'messaging.messages']);
ALTER TABLE messaging.conversations FORCE ROW LEVEL SECURITY;
ALTER TABLE messaging.messages FORCE ROW LEVEL SECURITY;
