-- ============================================================================
-- 0003_storage_credentials -- per-user object-storage credentials (docs/storage.md §4).
--
-- Platform-portal staff can hold S3-style credentials for their firm's bucket, minted
-- as literal per-user IAM users on the store (no policy variables upstream). The registry
-- here is the source of truth for what was issued: the store-side IAM user is disposable
-- and re-pushable from these rows.
--
--   * storage.user_credentials -- non-secret: who holds what, its scope summary and
--     status. One ACTIVE credential per (tenant, user); re-issue rotates.
--   * storage.user_credential_secrets -- the generated secret key, Fernet-encrypted
--     (app/crypto.py). Kept ONLY so a beta store's IAM state can be repaired/re-pushed;
--     the portal shows the secret once at issue and there is no reveal endpoint.
--     service_role-ONLY, like storage.tenant_secrets.
-- ============================================================================

CREATE TABLE storage.user_credentials (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  access_key_id text NOT NULL UNIQUE,
  -- Scope summary AT ISSUE TIME (the store-side policy is the authority; these are for
  -- display/audit): the granted read prefixes and whether files/shared/ is writable.
  read_prefixes text[] NOT NULL,
  shared boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- One live credential per person per firm; history stays queryable.
CREATE UNIQUE INDEX user_credentials_one_active_idx
  ON storage.user_credentials (tenant_id, user_id) WHERE status = 'active';
CREATE INDEX user_credentials_tenant_id_idx ON storage.user_credentials (tenant_id);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON storage.user_credentials
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- A firm can see its own credential rows (who holds access); a user always sees their
-- own. All writes are service_role only (issuance runs in the storage session).
ALTER TABLE storage.user_credentials ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage.user_credentials FORCE ROW LEVEL SECURITY;
CREATE POLICY storage_user_credentials_read ON storage.user_credentials FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR user_id = auth.uid());
GRANT SELECT ON storage.user_credentials TO authenticated;
GRANT ALL ON storage.user_credentials TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA storage TO service_role;

-- ============================================================================
-- storage.user_credential_secrets -- service_role ONLY (mirrors storage.tenant_secrets):
-- no authenticated grant or policy, so even the ciphertext is unreadable on the request
-- path. `secret_access_key_ct` is already in audit.record()'s redaction list.
-- ============================================================================
CREATE TABLE storage.user_credential_secrets (
  credential_id int PRIMARY KEY
    REFERENCES storage.user_credentials(id) ON DELETE CASCADE,
  secret_access_key_ct text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON storage.user_credential_secrets
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE storage.user_credential_secrets ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage.user_credential_secrets FORCE ROW LEVEL SECURITY;
GRANT ALL ON storage.user_credential_secrets TO service_role;

-- Issuance/rotation/revocation are part of the FCA-auditable trail.
SELECT audit.attach(ARRAY[
  'storage.user_credentials',
  'storage.user_credential_secrets'
]);
