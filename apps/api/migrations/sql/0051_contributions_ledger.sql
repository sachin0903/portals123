-- ============================================================================
-- 0051_contributions_ledger.sql — the money ledger + the two SIPP domain records.
--
-- Closes the gap Decision 2 (docs/data-architecture.md §4) named: platform.transactions is the
-- realised fact, but nothing held the FORECAST, so a contribution an adviser books had nowhere
-- to live between "we told the custodian to expect it" and "the credit landed".
--
--   expectation (forecast)  ->  transaction (realised)  ->  contribution/transfer (domain)
--   platform.transaction_expectations   platform.transactions   platform.{contributions,transfers}
--
-- SCHEMA PLACEMENT: Decision 7 originally routed the SIPP domain to a `pensions.*` schema. That
-- is superseded — contributions and transfers land in `platform` alongside the accounts and
-- transactions they reference, so one schema owns the whole money story and there is one fewer
-- grant/RLS surface. docs/data-architecture.md is amended to match.
--
-- The `platform.transactions.expectation_id` column has existed since 0002 carrying the comment
-- "FK -> integrations.transaction_expectations wired in 0003". 0003 became the links table and
-- the FK was never added. It is wired here, to platform.transaction_expectations.
-- ============================================================================

-- ============================================================================
-- platform.transaction_expectations — the forecast layer.
--
-- Deliberately NOT platform.transactions with a flag: the fact table is an immutable synced
-- mirror (idempotent on source_system+source_transaction_id), so a row we invented before the
-- provider ever saw the money has no business in it. Matching is expectation -> transaction via
-- transactions.expectation_id, which is an auditable join rather than a mutable state column.
-- ============================================================================
CREATE TABLE platform.transaction_expectations (
  id          bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid         text          NOT NULL UNIQUE,                    -- 'exp_...'
  tenant_id   int           NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  account_id  int           NOT NULL REFERENCES platform.accounts(id) ON DELETE CASCADE,
  contact_id  int           REFERENCES crm.contacts(id) ON DELETE SET NULL,

  kind        text          NOT NULL
                  CHECK (kind IN ('contribution', 'transfer_in', 'withdrawal', 'fee', 'income')),
  -- Signed direction is on the expectation, not the amount: a forecast is always a positive
  -- quantity of money, and which way it travels is a property of the kind.
  direction   text          NOT NULL DEFAULT 'in' CHECK (direction IN ('in', 'out')),
  amount      numeric(20,4) NOT NULL CHECK (amount > 0),
  currency    text          NOT NULL DEFAULT 'GBP',
  due_date    date,

  status      text          NOT NULL DEFAULT 'expected'
                  CHECK (status IN ('expected', 'instructed', 'matched',
                                    'reconciled', 'cancelled', 'failed')),

  -- Who we told, and what they said. request_payload/response_payload are kept because an
  -- anticipated-receipt call is a real instruction to a custodian: when it is queried months
  -- later, "what exactly did we send" must be answerable without replaying anything.
  provider           text   CHECK (provider IN ('sei', 'seccl', 'morgan_lloyd')),
  provider_reference text,                                      -- e.g. SEI's SWPActivityId
  request_payload    jsonb,
  response_payload   jsonb,
  error              text,                                      -- last failure, human-readable

  instructed_at timestamptz,
  matched_at    timestamptz,
  created_by    uuid        REFERENCES auth.users(id),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX transaction_expectations_tenant_status_idx
  ON platform.transaction_expectations(tenant_id, status);
CREATE INDEX transaction_expectations_account_idx
  ON platform.transaction_expectations(account_id);
CREATE INDEX transaction_expectations_contact_idx
  ON platform.transaction_expectations(contact_id) WHERE contact_id IS NOT NULL;
-- The matcher's hot path: open expectations for an account within a date window.
CREATE INDEX transaction_expectations_open_idx
  ON platform.transaction_expectations(account_id, due_date)
  WHERE status IN ('expected', 'instructed');

-- The FK 0002 promised. ON DELETE SET NULL: an expectation may be purged (cancelled, superseded)
-- without destroying the realised transaction that fulfilled it -- the fact outlives the forecast.
ALTER TABLE platform.transactions
  ADD CONSTRAINT transactions_expectation_id_fkey
  FOREIGN KEY (expectation_id) REFERENCES platform.transaction_expectations(id) ON DELETE SET NULL;
CREATE INDEX transactions_expectation_idx
  ON platform.transactions(expectation_id) WHERE expectation_id IS NOT NULL;

-- ============================================================================
-- platform.contributions — the SIPP domain record.
--
-- One row per contribution an adviser books or the feed detects. Carries the HMRC decision
-- (category + tax year), the relief-at-source arithmetic, and the contributor identity Morgan
-- Lloyd demands for anything that is not a personal contribution.
-- ============================================================================
CREATE TABLE platform.contributions (
  id          bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid         text          NOT NULL UNIQUE,                    -- 'con_...'
  tenant_id   int           NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  account_id  int           NOT NULL REFERENCES platform.accounts(id) ON DELETE CASCADE,
  contact_id  int           REFERENCES crm.contacts(id) ON DELETE SET NULL,

  -- The forecast it created, and the realised credit it was matched to. Both nullable: a
  -- contribution detected FROM a credit has a transaction but never had an expectation, and one
  -- booked ahead has an expectation long before any transaction exists.
  expectation_id bigint     REFERENCES platform.transaction_expectations(id) ON DELETE SET NULL,
  transaction_id bigint     REFERENCES platform.transactions(id) ON DELETE SET NULL,

  -- The HMRC decision. Mirrors the portal's five categories exactly (contributions/types.ts):
  -- only the first three are contributions in the tax sense; the last two exist so an adviser
  -- can dispose of a payment-in that landed in the queue by mistake.
  category    text          NOT NULL
                  CHECK (category IN ('personal_contribution', 'employer_contribution',
                                      'third_party_contribution', 'transfer_in',
                                      'not_a_contribution')),

  -- amount is what was actually paid: NET for personal/third-party (the scheme reclaims basic
  -- rate), GROSS for employer. gross_amount/relief_amount are the derived pair, stored rather
  -- than recomputed because the relief rate is a point-in-time fact -- recomputing a 2026/27
  -- contribution at a future year's rate would silently restate it.
  amount               numeric(20,4) NOT NULL CHECK (amount > 0),
  gross_amount         numeric(20,4),
  relief_amount        numeric(20,4),
  prefunded_ras_amount numeric(20,4),                   -- ML cam_prefundedrasamount
  currency             text          NOT NULL DEFAULT 'GBP',

  -- '2026/27'. Text, not a date range: it is the label HMRC and the custodian both key on, and
  -- SEI's treatmentCodeTaxYear wants it as a configured string.
  tax_year    text,
  -- Widened from the portal's binary one_off/regular: Morgan Lloyd's cam_frequency needs the
  -- actual period, so "regular" alone cannot be sent.
  frequency   text          NOT NULL DEFAULT 'single'
                  CHECK (frequency IN ('single', 'monthly', 'quarterly',
                                       'half_yearly', 'annually')),
  paid_by     text          NOT NULL DEFAULT 'client'
                  CHECK (paid_by IN ('client', 'third_party', 'employer')),
  contribution_date date,

  -- The contributor block. Required by cam_createcontribution whenever the contribution type is
  -- NOT personal (the docs' `*` rule), and held nowhere else -- the payer of an employer
  -- contribution is not the client, so crm.contacts cannot supply it.
  employer_name  text,
  address_line1  text,
  address_line2  text,
  address_line3  text,
  city           text,
  county         text,
  postcode       text,
  phone          text,
  email          text,

  status      text          NOT NULL DEFAULT 'identified'
                  CHECK (status IN ('identified', 'awaiting_confirmation', 'confirmed',
                                    'ml_recorded', 'ras_applied', 'ras_received',
                                    'tax_relief_received', 'reconciled', 'manual_intervention')),

  ml_contribution_id text,                              -- cam_contributionid GUID once recorded
  ml_recorded_at     timestamptz,
  note        text,
  data        jsonb,
  created_by  uuid          REFERENCES auth.users(id),
  created_at  timestamptz   NOT NULL DEFAULT now(),
  updated_at  timestamptz   NOT NULL DEFAULT now(),

  -- A non-personal contribution cannot reach Morgan Lloyd without a contributor name. Enforced
  -- at 'confirmed' and beyond rather than on insert, so the workbench can hold a half-classified
  -- row while an adviser goes and finds the employer's details.
  CONSTRAINT contributions_employer_named CHECK (
    category <> 'employer_contribution'
    OR status IN ('identified', 'awaiting_confirmation')
    OR employer_name IS NOT NULL
  )
);
CREATE INDEX contributions_tenant_status_idx ON platform.contributions(tenant_id, status);
CREATE INDEX contributions_account_idx ON platform.contributions(account_id);
CREATE INDEX contributions_contact_idx ON platform.contributions(contact_id) WHERE contact_id IS NOT NULL;
CREATE INDEX contributions_expectation_idx ON platform.contributions(expectation_id) WHERE expectation_id IS NOT NULL;
CREATE INDEX contributions_transaction_idx ON platform.contributions(transaction_id) WHERE transaction_id IS NOT NULL;
-- The workbench's default view: everything still needing a human.
CREATE INDEX contributions_open_idx ON platform.contributions(tenant_id, created_at DESC)
  WHERE status IN ('identified', 'awaiting_confirmation', 'manual_intervention');

-- ============================================================================
-- platform.transfers — a transfer in from a ceding scheme.
--
-- Column names track cam_createtransfer's required list so pushing to Morgan Lloyd is a mapping
-- rather than a translation. The vendor's triple-l "uncrystalllised" misspelling is NOT copied
-- here -- it is a wire-format quirk, corrected at the adapter boundary, not a domain concept.
-- ============================================================================
CREATE TABLE platform.transfers (
  id          bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid         text          NOT NULL UNIQUE,                    -- 'trf_...'
  tenant_id   int           NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  account_id  int           NOT NULL REFERENCES platform.accounts(id) ON DELETE CASCADE,
  contact_id  int           REFERENCES crm.contacts(id) ON DELETE SET NULL,

  expectation_id bigint     REFERENCES platform.transaction_expectations(id) ON DELETE SET NULL,
  transaction_id bigint     REFERENCES platform.transactions(id) ON DELETE SET NULL,

  ceding_provider text        NOT NULL,                 -- cam_providername
  policy_number   text,                                 -- cam_policyno
  transfer_type   text        NOT NULL DEFAULT 'pension'
                    CHECK (transfer_type IN ('pension', 'isa', 'gia', 'cash', 'in_specie')),

  -- Pensions split the value three ways and Morgan Lloyd wants all three; total_value is
  -- cam_nonprtv, which is the whole transfer, not the non-protected slice its name suggests.
  crystallised_value   numeric(20,4),
  uncrystallised_value numeric(20,4),
  total_value          numeric(20,4),
  currency             text   NOT NULL DEFAULT 'GBP',

  status      text          NOT NULL DEFAULT 'requested'
                  CHECK (status IN ('requested', 'submitted', 'in_progress', 'assets_received',
                                    'completed', 'cancelled', 'manual_intervention')),

  ml_transfer_id text,                                  -- cam_personalpolicyid GUID
  ml_recorded_at timestamptz,
  expected_date  date,
  completed_at   timestamptz,
  note        text,
  data        jsonb,
  created_by  uuid          REFERENCES auth.users(id),
  created_at  timestamptz   NOT NULL DEFAULT now(),
  updated_at  timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX transfers_tenant_status_idx ON platform.transfers(tenant_id, status);
CREATE INDEX transfers_account_idx ON platform.transfers(account_id);
CREATE INDEX transfers_contact_idx ON platform.transfers(contact_id) WHERE contact_id IS NOT NULL;
CREATE INDEX transfers_expectation_idx ON platform.transfers(expectation_id) WHERE expectation_id IS NOT NULL;

-- ============================================================================
-- crm.contacts — the two inputs the HMRC eligibility checks need and nobody held.
--
-- Without these, relief.ts silently falls back to the GBP 3,600 floor on every client and the
-- protection block never fires, so a contribution that would forfeit enhanced protection sails
-- through. Nullable: "not on file" is a real and common state, and the checks already degrade to
-- a warning rather than a pass when they are absent.
-- ============================================================================
ALTER TABLE crm.contacts
  ADD COLUMN relevant_uk_earnings numeric(20,2),
  ADD COLUMN relevant_uk_earnings_tax_year text,
  ADD COLUMN pension_protection text[];

COMMENT ON COLUMN crm.contacts.relevant_uk_earnings IS
  'Relevant UK earnings for the relievable-limit test (greater of GBP 3,600 / 100% of earnings). '
  'NULL means not on file -- the floor applies and the check degrades to a warning.';
COMMENT ON COLUMN crm.contacts.pension_protection IS
  'Lifetime-allowance protections held: enhanced | fixed | primary | individual. A contribution '
  'forfeits enhanced/fixed protection, so any value here blocks booking one.';

-- ============================================================================
-- Tenant containment on the client/account links (0035's invariant).
--
-- A plain `account_id`/`contact_id` can point into ANOTHER firm, and the client branch of these
-- tables' read policies (`account_id = ANY (auth.account_scope())`) carries no tenant conjunct —
-- so a mis-tenanted row would be readable by the wrong firm's client. Tightening WITH CHECK does
-- not close it: none of these policies binds service_role, which is what firm_session and the
-- worker actually write as. A composite (tenant_id, link) FK does, because referential integrity
-- is enforced for every role and bypasses RLS. `test_schema_invariants.py` derives this
-- requirement from the catalogue, so a new table with a bare contact_id fails the gate.
-- ============================================================================
ALTER TABLE platform.transaction_expectations
  ADD CONSTRAINT transaction_expectations_account_tenant_fkey
  FOREIGN KEY (tenant_id, account_id) REFERENCES platform.accounts (tenant_id, id)
  ON DELETE CASCADE;
-- Nullable link + ON DELETE SET NULL: the column list (Postgres 15+) is required because
-- tenant_id is NOT NULL and must not be nulled along with the link.
ALTER TABLE platform.transaction_expectations
  ADD CONSTRAINT transaction_expectations_contact_tenant_fkey
  FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id)
  ON DELETE SET NULL (contact_id);

ALTER TABLE platform.contributions
  ADD CONSTRAINT contributions_account_tenant_fkey
  FOREIGN KEY (tenant_id, account_id) REFERENCES platform.accounts (tenant_id, id)
  ON DELETE CASCADE;
ALTER TABLE platform.contributions
  ADD CONSTRAINT contributions_contact_tenant_fkey
  FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id)
  ON DELETE SET NULL (contact_id);

ALTER TABLE platform.transfers
  ADD CONSTRAINT transfers_account_tenant_fkey
  FOREIGN KEY (tenant_id, account_id) REFERENCES platform.accounts (tenant_id, id)
  ON DELETE CASCADE;
ALTER TABLE platform.transfers
  ADD CONSTRAINT transfers_contact_tenant_fkey
  FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id)
  ON DELETE SET NULL (contact_id);

-- ============================================================================
-- RLS -- the two-layer pattern from 0016_platform_instructions: staff see the firm (tenant
-- lineage), a client sees only their own accounts (account_scope). Writes are staff-only at the
-- DB; the platform portal's firm_session is service_role and bypasses this anyway, so the
-- authenticated write policy exists to keep a client login from ever inserting.
-- ============================================================================
ALTER TABLE platform.transaction_expectations ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.transaction_expectations FORCE ROW LEVEL SECURITY;
CREATE POLICY transaction_expectations_read ON platform.transaction_expectations
  FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR account_id = ANY (auth.account_scope()));
CREATE POLICY transaction_expectations_write ON platform.transaction_expectations
  FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

ALTER TABLE platform.contributions ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.contributions FORCE ROW LEVEL SECURITY;
CREATE POLICY contributions_read ON platform.contributions
  FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR account_id = ANY (auth.account_scope()));
CREATE POLICY contributions_write ON platform.contributions
  FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

ALTER TABLE platform.transfers ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.transfers FORCE ROW LEVEL SECURITY;
CREATE POLICY transfers_read ON platform.transfers
  FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR account_id = ANY (auth.account_scope()));
CREATE POLICY transfers_write ON platform.transfers
  FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

GRANT SELECT, INSERT, UPDATE, DELETE
  ON platform.transaction_expectations, platform.contributions, platform.transfers
  TO authenticated;
GRANT ALL
  ON platform.transaction_expectations, platform.contributions, platform.transfers
  TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA platform TO authenticated, service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.transaction_expectations
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.contributions
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.transfers
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Every write lands in audit.log (the 0001 spine). These rows instruct a custodian to move a
-- client's money and record an HMRC-reportable decision -- the full DML trail is not optional.
SELECT audit.attach(ARRAY[
  'platform.transaction_expectations',
  'platform.contributions',
  'platform.transfers'
]);
