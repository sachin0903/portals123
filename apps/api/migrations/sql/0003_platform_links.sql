-- ============================================================================
-- 0003_platform_links.sql -- the polymorphic external-id bridge.
--
-- Maps a canonical OLTP entity (a crm.contacts / platform.accounts row) to its id(s)
-- in each provider's system (Seccl, SEI, Morgan Lloyd, ...). This is what lets the
-- portals resolve "this client's accounts" -> the provider ids the analytical lake is
-- keyed by, WITHOUT the OLTP model or the portal ever depending on a provider's shape
-- (data-architecture.md Decision 1). One entity carries many provider ids at once
-- (UNIQUE per provider + entity + link_type).
--
-- (Numbering note: the data-arch §8 sketch pencilled this into 0002 and reserved 0003 for
-- the pensions ledger. Migrations are forward/append-only, so it lands here as 0003; the
-- ledger simply follows in a later revision.)
-- ============================================================================

CREATE TABLE platform.platform_links (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  entity_type text NOT NULL,                 -- 'contact' | 'account' | 'model' | ...
  entity_id bigint NOT NULL,                 -- the canonical OLTP id (crm/platform)
  provider text NOT NULL,                    -- 'seccl' | 'sei' | 'ml' | ...
  link_type text NOT NULL DEFAULT 'primary',
  external_id text NOT NULL,                 -- the id in the provider's system
  data jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT platform_links_unique_link UNIQUE (provider, entity_type, entity_id, link_type)
);
CREATE INDEX platform_links_entity_idx ON platform.platform_links(entity_type, entity_id);
CREATE INDEX platform_links_provider_external_idx ON platform.platform_links(provider, external_id);
CREATE INDEX platform_links_tenant_id_idx ON platform.platform_links(tenant_id);

-- Mapping metadata; writes are service_role only (the inbound sync / ingest owns it).
-- Read mirrors the two-layer scope of the entity it points at: read-all staff see the whole
-- firm's links; everyone else (a scoped adviser, or a client with empty lineage) sees only
-- the links for the account/contact in their OWN scope. That keeps the holdings read path's
-- account->Seccl-id resolution scoped exactly like the accounts themselves.
ALTER TABLE platform.platform_links ENABLE ROW LEVEL SECURITY;
CREATE POLICY platform_links_read ON platform.platform_links FOR SELECT TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR (entity_type = 'account' AND entity_id = ANY (auth.account_scope()))
    OR (entity_type = 'contact' AND entity_id = ANY (auth.contact_scope()))
  );
GRANT SELECT ON platform.platform_links TO authenticated;
GRANT ALL ON platform.platform_links TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA platform TO authenticated, service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.platform_links
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- The provider mapping is security-relevant (it authorises which lake rows a login reaches).
SELECT audit.attach(ARRAY['platform.platform_links']);

ALTER TABLE platform.platform_links FORCE ROW LEVEL SECURITY;
