-- Outgoing provider calls: what we sent a custodian, and what came back.
--
-- NAMING: `audit.api_log` and `audit.log` sit in the same schema and are NOT the same thing.
--   audit.log      -- what a USER did to OUR data (the DML spine from 0001)
--   audit.api_log  -- what WE said to a THIRD PARTY, and what it said back
-- One is inbound and about people; the other is outbound and about systems. They also differ
-- in volume (one sync run is thousands of rows here) and in who reads them, and folding these
-- into audit.log's `detail jsonb` would turn it into an untyped dumping ground holding request
-- bodies. The two table comments point at each other so the distinction survives the next
-- person who greps for "audit".
--
-- Design notes in docs/provider-routing.md §2.

CREATE TABLE audit.api_log (
  -- Primary Key
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- Foreign Keys. Both nullable: a nightly sync belongs to a tenant but to no user, and a
  -- platform-wide call (token refresh, reference-data pull) belongs to neither.
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,

  -- Who we called. `provider` is the counterparty a firm would name; `service` separates
  -- sub-systems reached through it -- CTC is recorded as provider 'morgan_lloyd', service
  -- 'ctc', because a firm thinks of it as Morgan Lloyd producing their illustration.
  provider text NOT NULL,
  service text,

  -- What we called. `operation` is the domain verb where the caller knows it ('create_transfer')
  -- so the log reads as a business trail, not only as HTTP.
  transport text NOT NULL DEFAULT 'http',
  method text,
  url text,
  operation text,

  -- What we sent and what came back. Bodies ARE stored: a redacted trail answers no questions.
  -- Credentials are stripped by the recorder before they get here, so a token cannot reach this
  -- table through a caller forgetting to redact.
  request jsonb,
  response jsonb,
  status_code int,

  -- Nullable status/response plus a populated `error` is the important case: a timeout that
  -- never reached the network is exactly what someone reconstructs an incident from.
  ok boolean NOT NULL,
  error text,
  duration_ms int,

  -- What it was about, when the caller knows. Deliberately loose (no FK): the entity may live
  -- in any schema, and evidence must not fail to write because a row was later deleted.
  entity_type text,
  entity_id bigint,

  -- Timestamps
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE audit.api_log IS
  'Append-only record of OUTGOING calls to custodians (Seccl, SEI, Morgan Lloyd/CTC) — what we '
  'sent a third party and what came back. Written from each client''s single HTTP choke point, '
  'so a new endpoint is audited the day it is written. NOT audit.log, which records what a USER '
  'did to our own data. See docs/provider-routing.md.';

-- The other half of the pair, so the distinction is discoverable from either side.
COMMENT ON TABLE audit.log IS
  'Append-only record of what a USER did to our own data (the DML spine, 0001). NOT '
  'audit.api_log, which records outgoing calls to custodians.';
COMMENT ON COLUMN audit.api_log.transport IS
  'http for a REST call, sftp for the inbound SEI reporting pull. All three custodians take '
  'outbound instructions over HTTP -- SEI''s SFTP drop is how we RECEIVE their reporting, not '
  'how we send.';
COMMENT ON COLUMN audit.api_log.ok IS
  'Whether the call achieved its purpose. NOT merely status < 400: Morgan Lloyd answers 200 '
  'with responseKey=1 on failure, and CTC answers 200 with an HTML error page.';

-- Reading is by provider and recency (the admin API log), or by the entity a support question
-- is about.
CREATE INDEX api_log_created_at_idx ON audit.api_log (created_at DESC);
CREATE INDEX api_log_provider_idx ON audit.api_log (provider, created_at DESC);
CREATE INDEX api_log_tenant_idx ON audit.api_log (tenant_id, created_at DESC)
  WHERE tenant_id IS NOT NULL;
CREATE INDEX api_log_entity_idx ON audit.api_log (entity_type, entity_id)
  WHERE entity_type IS NOT NULL;
-- Partial: failures are a small fraction of rows and the thing anyone actually scans for.
CREATE INDEX api_log_failures_idx ON audit.api_log (created_at DESC) WHERE NOT ok;

ALTER TABLE audit.api_log ENABLE ROW LEVEL SECURITY;

-- READ is tenant-scoped: a firm sees its own calls, and system sees the tenant-less ones too.
CREATE POLICY api_log_read ON audit.api_log FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR (tenant_id IS NULL AND auth.is_system()));

-- APPEND must NEVER be blocked by RLS. Same rule as audit.log: evidence-writing cannot fail
-- because of tenant scoping. A sync running outside a request has no claims at all, and the
-- call still has to be recorded.
CREATE POLICY api_log_append ON audit.api_log FOR INSERT TO authenticated WITH CHECK (true);

-- Append-only, enforced by the grant rather than by a trigger: no UPDATE, no DELETE.
GRANT SELECT, INSERT ON audit.api_log TO authenticated;
-- service_role writes these: the drain in app/api_log.py runs outside any request (a nightly
-- sync has no principal) and so writes as service_role, and the admin API log reads as
-- admin_session. Omitting this made every recorded call fail its INSERT and get swallowed by the
-- drain's error handler -- an audit trail that logged its own failure and stayed empty. Same
-- pairing as audit.log.
GRANT ALL ON audit.api_log TO service_role;
