-- ============================================================================
-- 0037_aml_creditsafe.sql — the local mirror of Creditsafe KYC Protect.
--
-- Creditsafe owns the screening; we own a read model of it. The sync engine pulls
-- profiles/searches/hits down on a schedule so the console, the flow engine's review
-- handler and the ops screens can query AML position with a join rather than an HTTP
-- round trip per client. Nothing in this schema is authored by a user: every table is
-- written ONLY by the sync engine as service_role, which is why `authenticated` gets
-- SELECT and nothing else.
--
--   aml.profiles   — a monitored subject in KYC Protect. Soft-linked to crm.contacts.
--   aml.searches   — a screening run against a profile (or a standalone ad-hoc search).
--   aml.hits       — the candidate matches a search returned, with our disposition.
--   aml.sync_state — Graphene-wide engine bookkeeping (not tenant data).
--
-- Creditsafe's own ids are mirrored as `cs_*` and are the natural keys the sync upserts
-- on; the surrogate int PK + 'amlp_'/'amls_'/'amlh_' uid are ours, for the API contract.
-- Creditsafe's created/modified stamps stay `text` on purpose — the vendor returns them
-- in more than one shape and a mirror must never lose a row to a parse failure; they are
-- provenance, not something we filter or sort on.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS aml;
GRANT USAGE ON SCHEMA aml TO anon, authenticated, service_role;

-- ============================================================================
-- aml.profiles — the mirrored KYC Protect profile.
--
-- contact_id is NULLABLE by design. Creditsafe profiles predate this platform and are
-- keyed by name, so a confident link to crm.contacts is often impossible. An unmatched
-- profile is surfaced in the ops console for a human to bind rather than guessed at: a
-- wrong link would attribute someone else's sanctions position to a client, which is
-- worse than no link at all.
-- ============================================================================
CREATE TABLE aml.profiles (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                          -- 'amlp_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  contact_id int REFERENCES crm.contacts(id) ON DELETE SET NULL,
  cs_profile_id text NOT NULL UNIQUE,                -- Creditsafe's profile id (upsert key)
  name text,
  type text,                                         -- individual | business (vendor vocabulary)
  status text,
  risk_rating text,
  -- Ongoing-monitoring configuration, mirrored verbatim. The emails/schedule ids arrive
  -- as vendor-delimited strings; we do not re-model them, we only display them.
  is_monitored boolean NOT NULL DEFAULT false,
  monitoring_emails text,
  monitoring_schedule_ids text,
  -- Denormalised counters straight off the vendor payload. They drive the console's
  -- triage columns, so recomputing them from aml.hits on every list would be wasteful
  -- (and wrong for hits we have not synced yet).
  search_count int NOT NULL DEFAULT 0,
  open_alert_count int NOT NULL DEFAULT 0,
  total_hit_count int NOT NULL DEFAULT 0,
  undecided_hit_count int NOT NULL DEFAULT 0,
  true_positive_hit_count int NOT NULL DEFAULT 0,
  archived_at timestamptz,                           -- archived upstream; kept for history
  cs_created_at text,
  cs_modified_at text,
  synced_at timestamptz NOT NULL DEFAULT now(),      -- when WE last saw this row upstream
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX profiles_tenant_id_idx ON aml.profiles(tenant_id);
CREATE INDEX profiles_contact_id_idx ON aml.profiles(contact_id);
-- The console's default listing excludes archived profiles.
CREATE INDEX profiles_active_idx ON aml.profiles(tenant_id) WHERE archived_at IS NULL;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON aml.profiles
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ============================================================================
-- aml.searches — one screening run. profile_id is nullable: an ad-hoc search can be run
-- before (or without) a profile existing, and the engine back-fills the link when the
-- vendor later attaches one.
-- ============================================================================
CREATE TABLE aml.searches (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                          -- 'amls_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  profile_id int REFERENCES aml.profiles(id) ON DELETE CASCADE,
  cs_search_id text NOT NULL UNIQUE,                 -- Creditsafe's search id (upsert key)
  type text,                                         -- individuals | businesses
  name text,
  status text,
  risk_rating text,
  total_hit_count int NOT NULL DEFAULT 0,
  undecided_hit_count int NOT NULL DEFAULT 0,
  true_positive_hit_count int NOT NULL DEFAULT 0,
  false_positive_hit_count int NOT NULL DEFAULT 0,
  schedule_id text,                                  -- the monitoring schedule that ran it
  is_monitored boolean NOT NULL DEFAULT false,
  hidden boolean NOT NULL DEFAULT false,             -- hidden upstream; mirrored, not deleted
  cs_created_at text,
  cs_modified_at text,
  synced_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX searches_profile_id_idx ON aml.searches(profile_id);
CREATE INDEX searches_tenant_id_idx ON aml.searches(tenant_id);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON aml.searches
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ============================================================================
-- aml.hits — the candidate matches. `decision` mirrors the vendor's disposition
-- vocabulary exactly (trueMatch/falsePositive/discarded) rather than inventing our own:
-- the decision is made in Creditsafe and syncs back, so a translation layer would only
-- create a chance to drift. decided_by/decided_at are OUR attribution for decisions
-- taken through this platform; both stay NULL for decisions made in the vendor UI.
-- ============================================================================
CREATE TABLE aml.hits (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                          -- 'amlh_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  search_id int NOT NULL REFERENCES aml.searches(id) ON DELETE CASCADE,
  profile_id int REFERENCES aml.profiles(id) ON DELETE CASCADE,
  cs_hit_id text NOT NULL UNIQUE,                    -- Creditsafe's hit id (upsert key)
  name text,
  hit_score int,
  decision text NOT NULL DEFAULT 'undecided'
    CHECK (decision IN ('undecided', 'trueMatch', 'falsePositive', 'discarded')),
  decision_reason text,
  note text,
  decided_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  decided_at timestamptz,
  datasets text[],                                   -- which lists matched: sanctions, PEP, …
  detail jsonb,                                      -- the vendor's full match payload
  synced_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX hits_search_id_idx ON aml.hits(search_id);
-- The review queue: undecided hits are the only ones anyone triages.
CREATE INDEX hits_undecided_idx ON aml.hits(profile_id) WHERE decision = 'undecided';
CREATE INDEX hits_tenant_id_idx ON aml.hits(tenant_id);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON aml.hits
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ============================================================================
-- RLS — staff-only, deliberately narrower than the rest of the domain.
--
-- ONE policy per table: SELECT for staff inside the tenant lineage. There is no INSERT/
-- UPDATE/DELETE policy and no DML grant to `authenticated`, because the sync engine is
-- the only writer and it runs as service_role (BYPASSRLS). A route handler cannot write
-- here even by mistake.
--
-- `auth.contact_scope()` is DELIBERATELY OMITTED. Contrast crm.kyc_checks, whose read
-- policy adds `OR contact_id = ANY (auth.contact_scope())` so a client may see their own
-- KYC outcome. That must NOT happen here: showing someone their own sanctions/PEP/
-- adverse-media hits — or even that a search exists against them — is tipping off, an
-- offence under POCA 2002 s.333A.
--
-- With contact_scope left out, the lineage predicate alone locks the client portal out:
-- auth.tenant_lineage() returns '{}' whenever portal/role is 'client' (0030), so
-- `tenant_id = ANY ('{}')` is false for every row and a client principal resolves NOTHING
-- here even though it is the subject of the search. This omission IS the control, and it
-- lives in the database rather than in a route handler so that no future endpoint, dataset
-- or ad-hoc query can route around it. If you are tempted to add contact_scope here, you
-- are adding a criminal-liability bug.
--
-- FORCE is set as well as ENABLE so the table owner (the migrator) is bound too — the
-- audit trigger crosses RLS via its service_role-owned SECURITY DEFINER function.
-- ============================================================================
ALTER TABLE aml.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE aml.profiles FORCE ROW LEVEL SECURITY;
CREATE POLICY profiles_read ON aml.profiles FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON aml.profiles TO authenticated;
GRANT ALL ON aml.profiles TO service_role;

ALTER TABLE aml.searches ENABLE ROW LEVEL SECURITY;
ALTER TABLE aml.searches FORCE ROW LEVEL SECURITY;
CREATE POLICY searches_read ON aml.searches FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON aml.searches TO authenticated;
GRANT ALL ON aml.searches TO service_role;

ALTER TABLE aml.hits ENABLE ROW LEVEL SECURITY;
ALTER TABLE aml.hits FORCE ROW LEVEL SECURITY;
CREATE POLICY hits_read ON aml.hits FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON aml.hits TO authenticated;
GRANT ALL ON aml.hits TO service_role;

-- ============================================================================
-- aml.sync_state — the engine's own bookkeeping: a single row, because there is one
-- Creditsafe account for the whole platform (the vendor tenancy is Graphene's, not the
-- firm's). It is therefore NOT tenant data and carries NO tenant_id, so there is no
-- sensible lineage predicate to write: it gets service_role only — no grant to
-- `authenticated` and no policy at all, exactly like storage.tenant_secrets. Firms see
-- their AML position through the tables above; whether the engine is mid-run is ops
-- information and would leak cross-tenant counts if exposed.
-- ============================================================================
CREATE TABLE aml.sync_state (
  id int PRIMARY KEY DEFAULT 1 CHECK (id = 1),       -- singleton guard
  last_sync_at timestamptz,
  last_full_sync_at timestamptz,
  status text NOT NULL DEFAULT 'idle'
    CHECK (status IN ('idle', 'running', 'done', 'error')),
  profile_count int NOT NULL DEFAULT 0,
  search_count int NOT NULL DEFAULT 0,
  error text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON aml.sync_state
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Seed the singleton so the engine only ever UPDATEs it (no upsert race between the
-- worker loop and a manually-triggered run). This INSERT must precede FORCE ROW LEVEL
-- SECURITY: FORCE binds the migrator too, and with no policy on the table the migrator
-- would be unable to insert its own seed row.
INSERT INTO aml.sync_state (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

ALTER TABLE aml.sync_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE aml.sync_state FORCE ROW LEVEL SECURITY;
GRANT ALL ON aml.sync_state TO service_role;

-- `authenticated` needs sequence USAGE for the identity columns only so that a future
-- service-context path sharing the request role behaves; it holds no INSERT privilege,
-- so this grants nothing on its own.
GRANT USAGE ON ALL SEQUENCES IN SCHEMA aml TO authenticated, service_role;

-- Screening data is regulated: every mirrored change and every hit disposition must be
-- reconstructable. sync_state is excluded — it is operational churn, not evidence.
SELECT audit.attach(ARRAY['aml.profiles', 'aml.searches', 'aml.hits']);
