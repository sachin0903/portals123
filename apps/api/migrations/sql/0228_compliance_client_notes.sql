-- ============================================================================
-- 0228_compliance_client_notes.sql — Graphene's internal notes on a client.
--
-- An operator writes free text on the AML console's client page: why something
-- was allowed, a call made, enhanced due diligence done
-- (POST /aml/clients/{key}/notes). A note sits on the client's contact when the
-- client has one, else on its compliance client; the page reads the notes of
-- both, so a note written before the compliance client existed still shows.
--
-- A note can say a client is suspected, which a firm must not learn from us
-- (tipping off, docs/aml.md §5). So, as compliance.client_risk (0227): RLS
-- forced, no policy, no grant to authenticated; operations read and write it on
-- service_role. The audit.log read policy already withholds compliance.* rows
-- from a firm (0221). Append-only: no route edits or deletes a note.
--
-- tenant_id is NOT NULL, unlike client_risk: a note is only ever written for a
-- client the console resolved, and every such client has a firm. The composite
-- foreign keys keep both links inside that firm (0035).
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE TABLE compliance.client_notes (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  contact_id int REFERENCES crm.contacts(id) ON DELETE CASCADE,
  client_id int REFERENCES compliance.clients(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 5000),
  author_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  -- The operator's name as written, so a note keeps its author after the user goes.
  author_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_client_notes_subject_check
    CHECK (contact_id IS NOT NULL OR client_id IS NOT NULL),
  CONSTRAINT compliance_client_notes_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE,
  CONSTRAINT compliance_client_notes_client_tenant_fkey
    FOREIGN KEY (tenant_id, client_id) REFERENCES compliance.clients (tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX compliance_client_notes_contact_idx ON compliance.client_notes (contact_id);
CREATE INDEX compliance_client_notes_client_idx ON compliance.client_notes (client_id);

ALTER TABLE compliance.client_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE compliance.client_notes FORCE ROW LEVEL SECURITY;
REVOKE ALL ON compliance.client_notes FROM PUBLIC, authenticated;
GRANT ALL ON compliance.client_notes TO service_role;

SELECT audit.attach(ARRAY['compliance.client_notes']);
