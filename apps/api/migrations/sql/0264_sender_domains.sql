-- ============================================================================
-- 0264_sender_domains — a firm's own Resend sending domain.
--
-- One row per firm. Graphene operations registers the domain on the shared
-- Resend account; the firm publishes the DNS records; mail uses the configured
-- address only once Resend has verified sending. Until then, and if verification
-- later fails, the platform EMAIL_FROM address stays the From.
--
-- No per-tenant API key. The row holds the domain, Resend's id, the DNS records
-- the operator copies out, and the mailbox operations chose on that domain.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE TABLE email.sender_domains (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,
  tenant_id int NOT NULL UNIQUE REFERENCES auth.tenants(id) ON DELETE CASCADE,
  domain text NOT NULL,
  resend_domain_id text NOT NULL,
  region text NOT NULL,
  provider_status text NOT NULL,
  sending_verified boolean NOT NULL DEFAULT false,
  records jsonb NOT NULL DEFAULT '[]'::jsonb,
  from_address text,
  verified_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sender_domains_domain_key UNIQUE (domain),
  CONSTRAINT sender_domains_resend_id_key UNIQUE (resend_domain_id),
  CONSTRAINT sender_domains_domain_shape CHECK (
    domain = lower(domain)
    AND length(domain) BETWEEN 4 AND 253
    AND domain LIKE '%.%'
  ),
  CONSTRAINT sender_domains_from_on_domain CHECK (
    from_address IS NULL
    OR (
      from_address = lower(from_address)
      AND split_part(from_address, '@', 2) = domain
      AND split_part(from_address, '@', 1) <> ''
    )
  )
);

CREATE INDEX sender_domains_active_idx
  ON email.sender_domains (tenant_id)
  WHERE sending_verified AND from_address IS NOT NULL;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON email.sender_domains
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE email.sender_domains ENABLE ROW LEVEL SECURITY;
ALTER TABLE email.sender_domains FORCE ROW LEVEL SECURITY;

-- Staff may READ their firm's domain (the send path resolves it under the
-- caller's role). Writes stay on the service-role operations routes: a firm
-- does not register or change its sending domain.
CREATE POLICY sender_domains_read ON email.sender_domains
  FOR SELECT TO authenticated
  USING (tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[]));

GRANT SELECT ON email.sender_domains TO authenticated;
GRANT ALL ON email.sender_domains TO service_role;
GRANT USAGE, SELECT ON SEQUENCE email.sender_domains_id_seq TO service_role;
