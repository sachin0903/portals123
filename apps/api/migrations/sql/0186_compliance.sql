-- ============================================================================
-- 0186_compliance.sql — screening subjects, checks, and the provider mirror.
--
-- The firm-facing API never names the provider. These tables are where that
-- mapping lives: one typed table per provider resource, `body` holding the
-- provider payload untouched, plus the columns we query. A client or check
-- that arrives before it matches `crm.contacts` is still stored: `tenant_id`
-- and `contact_id` null, full payload kept. Those rows are invisible to
-- `authenticated` (the policy requires a tenant). `service_role` can match
-- them later. `compliance.events` is the durable webhook inbox. pgmq is the
-- wake-up when the extension exists; the inbox row is enough for a SKIP
-- LOCKED consumer when it does not.
--
-- Reads for authenticated are the firm's staff via tenant lineage. A person
-- must not be able to select their own screening row, so the policy is
-- lineage only.
-- Writes are service_role only. The HTTP API strips `body` and `result`.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE SCHEMA IF NOT EXISTS compliance;
GRANT USAGE ON SCHEMA compliance TO authenticated, service_role;

CREATE TABLE compliance.clients (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  -- Null until the provider client matches a contact. The composite foreign
  -- key is not checked while either column is null (MATCH SIMPLE).
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  contact_id int REFERENCES crm.contacts(id) ON DELETE CASCADE,
  provider_client_id text,
  body jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_clients_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT compliance_clients_contact_key UNIQUE (tenant_id, contact_id),
  CONSTRAINT compliance_clients_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX compliance_clients_provider_id_key
  ON compliance.clients(provider_client_id) WHERE provider_client_id IS NOT NULL;
CREATE INDEX compliance_clients_tenant_idx ON compliance.clients(tenant_id);

CREATE TABLE compliance.addresses (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  client_id int NOT NULL REFERENCES compliance.clients(id) ON DELETE CASCADE,
  provider_address_id text,
  line text,
  city text,
  state text,
  postal_code text,
  country text,
  from_date date,
  body jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_addresses_client_key UNIQUE (client_id),
  CONSTRAINT compliance_addresses_client_tenant_fkey
    FOREIGN KEY (tenant_id, client_id) REFERENCES compliance.clients (tenant_id, id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX compliance_addresses_provider_id_key
  ON compliance.addresses(provider_address_id) WHERE provider_address_id IS NOT NULL;

CREATE TABLE compliance.documents (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  client_id int NOT NULL REFERENCES compliance.clients(id) ON DELETE CASCADE,
  provider_document_id text,
  issuing_country text,
  classification text,
  object_key text,
  body jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_documents_client_tenant_fkey
    FOREIGN KEY (tenant_id, client_id) REFERENCES compliance.clients (tenant_id, id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX compliance_documents_provider_id_key
  ON compliance.documents(provider_document_id) WHERE provider_document_id IS NOT NULL;
CREATE INDEX compliance_documents_client_idx ON compliance.documents(client_id);

CREATE TABLE compliance.live_photos (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  client_id int NOT NULL REFERENCES compliance.clients(id) ON DELETE CASCADE,
  provider_photo_id text,
  object_key text,
  body jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_live_photos_client_tenant_fkey
    FOREIGN KEY (tenant_id, client_id) REFERENCES compliance.clients (tenant_id, id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX compliance_live_photos_provider_id_key
  ON compliance.live_photos(provider_photo_id) WHERE provider_photo_id IS NOT NULL;

CREATE TABLE compliance.checks (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  client_id int NOT NULL REFERENCES compliance.clients(id) ON DELETE CASCADE,
  account_id int REFERENCES platform.accounts(id) ON DELETE SET NULL,
  document_id int REFERENCES compliance.documents(id) ON DELETE SET NULL,
  kind text NOT NULL CHECK (kind IN ('identity', 'aml')),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'clear', 'refer', 'rejected')),
  provider_check_id text,
  session_id text,
  redirect_url text,
  result jsonb NOT NULL DEFAULT '{}'::jsonb,
  body jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_checks_client_tenant_fkey
    FOREIGN KEY (tenant_id, client_id) REFERENCES compliance.clients (tenant_id, id) ON DELETE CASCADE,
  CONSTRAINT compliance_checks_account_tenant_fkey
    FOREIGN KEY (tenant_id, account_id) REFERENCES platform.accounts (tenant_id, id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX compliance_checks_provider_id_key
  ON compliance.checks(provider_check_id) WHERE provider_check_id IS NOT NULL;
CREATE INDEX compliance_checks_client_idx ON compliance.checks(client_id);
CREATE INDEX compliance_checks_tenant_status_idx ON compliance.checks(tenant_id, status);

CREATE TABLE compliance.events (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  provider_event_id text NOT NULL UNIQUE,
  event_type text NOT NULL,
  payload jsonb NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz
);

CREATE INDEX compliance_events_unprocessed_idx
  ON compliance.events(id) WHERE processed_at IS NULL;

-- One webhook endpoint per firm. The signing secret is Fernet ciphertext in
-- secret_ct. PUT returns the plaintext once. GET does not select it.
-- authenticated may read the url columns and not secret_ct. audit.record()
-- redacts secret_ct so a reader of the trail cannot sign check.updated.
CREATE TABLE compliance.webhooks (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  url text NOT NULL,
  secret_ct text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_webhooks_tenant_key UNIQUE (tenant_id)
);

-- Staff may read their own firm's rows. A client session has an empty lineage,
-- so the policy does not consult a per-person scope. Unmatched rows
-- (tenant_id NULL) stay invisible to authenticated until a tenant is attached.
-- webhooks.secret_ct is not in the authenticated column grant: a table-level
-- SELECT would include it, and column privileges do not.
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'clients', 'addresses', 'documents', 'live_photos', 'checks', 'events', 'webhooks'
  ]
  LOOP
    EXECUTE format('ALTER TABLE compliance.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE compliance.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format(
      'CREATE POLICY compliance_%I_read ON compliance.%I FOR SELECT TO authenticated '
      'USING (tenant_id IS NOT NULL AND tenant_id = ANY (auth.tenant_lineage()))',
      tbl, tbl
    );
    IF tbl = 'webhooks' THEN
      EXECUTE
        'GRANT SELECT (id, tenant_id, url, created_at, updated_at) '
        'ON compliance.webhooks TO authenticated';
    ELSE
      EXECUTE format('GRANT SELECT ON compliance.%I TO authenticated', tbl);
    END IF;
    EXECUTE format('GRANT ALL ON compliance.%I TO service_role', tbl);
  END LOOP;
END $$;

DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY['clients', 'addresses', 'documents', 'live_photos', 'checks', 'webhooks']
  LOOP
    EXECUTE format(
      'CREATE TRIGGER set_updated_at BEFORE UPDATE ON compliance.%I '
      'FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()',
      tbl
    );
  END LOOP;
END $$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA compliance TO service_role;

-- audit.record() is reissued with secret_ct added to the redact list, per the
-- 0038 convention. A reader of audit.log must not be able to sign check.updated.
CREATE OR REPLACE FUNCTION audit.record() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'audit', 'auth', 'pg_catalog' AS $fn$
DECLARE
  v_new     jsonb := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
  v_old     jsonb := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
  v_subject jsonb := COALESCE(v_new, v_old);
  -- never copy secrets / opaque pointers into the trail (key_hash is a hash, not the
  -- secret, but it stays out of logs on principle; credentials_ref points at a vault).
  v_redact  text[] := ARRAY['key_hash', 'credentials_ref', 'workos_api_key_ct', 'cookie_password_ct', 'secret_access_key_ct', 'password_ct', 'secret_ct'];
  v_entity  bigint;
  v_tenant  int;
  v_detail  jsonb;
  k         text;
BEGIN
  -- entity_id only when the PK is integer-shaped; uuid/composite PKs live in detail.
  BEGIN v_entity := (v_subject ->> 'id')::bigint; EXCEPTION WHEN others THEN v_entity := NULL; END;

  -- Stamp the AFFECTED row's tenant (correct for cross-tenant admin writes); fall back
  -- to the actor's tenant for tables that carry no tenant_id (e.g. auth.*), which now also
  -- covers an unattributed aml.* row whose tenant_id is NULL.
  BEGIN
    v_tenant := COALESCE(NULLIF(v_subject ->> 'tenant_id', '')::int, auth.tenant_id());
  EXCEPTION WHEN others THEN v_tenant := auth.tenant_id();
  END;

  v_new := v_new - v_redact;
  v_old := v_old - v_redact;

  IF TG_OP = 'UPDATE' THEN
    v_detail := '{}'::jsonb;   -- only the columns that actually changed (redacted ones excluded)
    FOR k IN SELECT jsonb_object_keys(v_new) LOOP
      IF v_new -> k IS DISTINCT FROM v_old -> k THEN
        v_detail := v_detail || jsonb_build_object(k, jsonb_build_object('old', v_old -> k, 'new', v_new -> k));
      END IF;
    END LOOP;
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'changed', v_detail);
  ELSIF TG_OP = 'INSERT' THEN
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'row', v_new);
  ELSE
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'row', v_old);
  END IF;

  INSERT INTO audit.log (tenant_id, user_id, action, entity_type, entity_id, detail)
  VALUES (
    v_tenant,
    auth.uid(),
    TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME || '.' || lower(TG_OP),
    TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME,
    v_entity,
    v_detail
  );
  RETURN NULL;  -- AFTER trigger: return value is ignored
END;
$fn$;

SELECT audit.attach(ARRAY[
  'compliance.clients',
  'compliance.addresses',
  'compliance.documents',
  'compliance.live_photos',
  'compliance.checks',
  'compliance.events',
  'compliance.webhooks'
]);
