-- ============================================================================
-- 0025_flows_orchestration.sql — the generic orchestration model (Phase 1 walking skeleton).
--
-- ADDITIVE + feature-flag-safe: the current single-case engine keeps using flows.cases as-is; the
-- new orchestrator (settings.flows_orchestrator_v2, default off) uses the new grouping + generic
-- columns. Nothing here changes existing behaviour.
--
--   * flows.executions   — the version-PINNED run identity + case group (onboarding: an application).
--                          Owns the orchestration status (generic states); crm.applications is a
--                          projection of it, never the source of truth.
--   * flows.cases        — gains execution_id + a polymorphic subject (subject_type/subject_id) +
--                          kind, so a case can be about a contact (KYC) or an account.
--   * flows.case_steps   — gains step_key (stable across versions), participant_subject_id (per-person
--                          fan-out), depends_on (step-key gating), scope; status widened with
--                          blocked/waiting/failed for the generic machine.
--   * flows.domain_events — immutable append-only fact log (replay/audit spine).
--   * flows.outbox        — delivery queue (attempts/next_retry/dead_letter) referencing an event.
-- ============================================================================

-- ---- flows.executions — version-pinned group / run identity ----
CREATE TABLE flows.executions (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                         -- 'fex_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  flow_id int NOT NULL REFERENCES flows.flows(id) ON DELETE CASCADE,
  flow_version_id int NOT NULL REFERENCES flows.flow_versions(id) ON DELETE RESTRICT,  -- PINNED
  -- Generic engine state (states.py): draft|active|blocked|waiting|completed|cancelled|failed.
  -- NOT onboarding vocabulary — that is derived for the UI + the crm.applications projection.
  status text NOT NULL DEFAULT 'draft',
  subject_type text,                                -- the group's own subject, if any
  subject_id int,
  crm_application_id int REFERENCES crm.applications(id) ON DELETE SET NULL,  -- domain projection
  data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  cancelled_at timestamptz
);
CREATE INDEX executions_tenant_id_idx ON flows.executions(tenant_id);
CREATE INDEX executions_flow_id_idx ON flows.executions(flow_id);
CREATE INDEX executions_flow_version_id_idx ON flows.executions(flow_version_id);
CREATE INDEX executions_crm_application_idx
  ON flows.executions(crm_application_id) WHERE crm_application_id IS NOT NULL;

-- ---- flows.cases — grouping + polymorphic subject (additive) ----
ALTER TABLE flows.cases
  ADD COLUMN execution_id int REFERENCES flows.executions(id) ON DELETE CASCADE,
  ADD COLUMN kind text,                             -- 'profile' | 'account' (config label)
  ADD COLUMN subject_type text,                     -- 'contact' | 'account' | 'group'
  ADD COLUMN subject_id int;
CREATE INDEX cases_execution_id_idx ON flows.cases(execution_id) WHERE execution_id IS NOT NULL;

-- ---- flows.case_steps — fan-out + dependencies + widened status (additive) ----
ALTER TABLE flows.case_steps
  ADD COLUMN step_key text,                         -- the definition step key (stable across versions)
  ADD COLUMN participant_subject_id int,            -- per-person fan-out instance (joint accounts)
  ADD COLUMN depends_on text[] NOT NULL DEFAULT '{}',  -- step KEYS this step waits on
  ADD COLUMN scope text;                            -- 'participant' | 'account' | 'application'
ALTER TABLE flows.case_steps DROP CONSTRAINT IF EXISTS case_steps_status_check;
ALTER TABLE flows.case_steps ADD CONSTRAINT case_steps_status_check
  CHECK (status IN ('pending', 'fulfilled', 'skipped', 'cancelled', 'blocked', 'waiting', 'failed'));
CREATE INDEX case_steps_participant_idx
  ON flows.case_steps(participant_subject_id) WHERE participant_subject_id IS NOT NULL;

-- ---- flows.domain_events — immutable append-only fact log ----
CREATE TABLE flows.domain_events (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  execution_id int REFERENCES flows.executions(id) ON DELETE CASCADE,
  case_id int REFERENCES flows.cases(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  idempotency_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT domain_events_idem_key UNIQUE (tenant_id, event_type, idempotency_key)
);
CREATE INDEX domain_events_execution_idx
  ON flows.domain_events(execution_id) WHERE execution_id IS NOT NULL;
CREATE INDEX domain_events_case_idx ON flows.domain_events(case_id) WHERE case_id IS NOT NULL;

-- ---- flows.outbox — external-notification delivery queue (delivery state ONLY) ----
CREATE TABLE flows.outbox (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  domain_event_id bigint REFERENCES flows.domain_events(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'delivered', 'dead_letter')),
  attempts int NOT NULL DEFAULT 0,
  max_attempts int NOT NULL DEFAULT 8,
  last_attempt timestamptz,
  next_retry timestamptz NOT NULL DEFAULT now(),
  last_error text,
  delivered_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX outbox_due_idx ON flows.outbox(next_retry) WHERE status = 'queued';

-- ============================================================================
-- RLS — executions readable by staff (tenant lineage); domain_events readable by staff (audit
-- spine, append-only); cases/case_steps policies already cover the new columns. Every write is
-- service_role (the engine). outbox is service_role-only.
-- ============================================================================
ALTER TABLE flows.executions ENABLE ROW LEVEL SECURITY;
CREATE POLICY executions_read ON flows.executions FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON flows.executions TO authenticated;
GRANT ALL ON flows.executions TO service_role;

ALTER TABLE flows.domain_events ENABLE ROW LEVEL SECURITY;
CREATE POLICY domain_events_read ON flows.domain_events FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON flows.domain_events TO authenticated;
GRANT SELECT, INSERT ON flows.domain_events TO service_role;  -- append-only: no UPDATE/DELETE

ALTER TABLE flows.outbox ENABLE ROW LEVEL SECURITY;                    -- deny-all for authenticated
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.outbox TO service_role;  -- deliverer runs elevated

GRANT USAGE ON ALL SEQUENCES IN SCHEMA flows TO authenticated, service_role;

-- updated_at trigger on the one new table that has the column; audit the new group record; FORCE
-- RLS on all three new tables (bind even the migrator owner). Done explicitly (not via 0021's broad
-- loop) so we don't re-CREATE triggers on the pre-existing tables.
CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.executions
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
SELECT audit.attach(ARRAY['flows.executions', 'flows.domain_events']);
ALTER TABLE flows.executions FORCE ROW LEVEL SECURITY;
ALTER TABLE flows.domain_events FORCE ROW LEVEL SECURITY;
ALTER TABLE flows.outbox FORCE ROW LEVEL SECURITY;
