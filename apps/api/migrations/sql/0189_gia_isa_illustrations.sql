  id            int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid           text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  effective_from date NOT NULL,
  equity_rate   numeric(12, 8) NOT NULL,
  gilts_rate    numeric(12, 8) NOT NULL,
  bonds_rate    numeric(12, 8) NOT NULL,
  other_rate    numeric(12, 8) NOT NULL,
  spread        numeric(12, 8) NOT NULL DEFAULT 0.03,
  gia_haircut   numeric(12, 8) NOT NULL DEFAULT 0.005,
  inflation     numeric(12, 8) NOT NULL DEFAULT 0.02,
