  ADD COLUMN legal_name text,
  ADD COLUMN registered_office text,
  ADD COLUMN illustration_warning text,
  ADD COLUMN gia_isa_illustrations boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN auth.tenants.gia_isa_illustrations IS
  'The firm chooses to issue GIA and ISA illustrations. Off until switched on.';
COMMENT ON COLUMN auth.tenants.legal_name IS
  'Legal entity named on a GIA or ISA illustration.';
COMMENT ON COLUMN auth.tenants.illustration_warning IS
  'Future-performance warning printed on the firm''s GIA and ISA illustrations.';

