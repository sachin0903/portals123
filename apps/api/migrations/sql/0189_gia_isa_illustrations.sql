-- GIA and ISA illustrations. The engine reads Graphene tables and copies them onto the
-- illustration. Custodian sync may fill a model beforehand; it is not read when the
-- document is produced.
--
-- Growth rates and the ISA allowance are Graphene-wide. Cash interest and the custodian
-- footer are per custodian. The fee schedule and the legal disclosure are per firm.
-- Fund costs are global, one row per ISIN and data date.

