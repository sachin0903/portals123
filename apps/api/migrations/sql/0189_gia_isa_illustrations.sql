  ADD COLUMN reference_snapshot jsonb,
  ADD COLUMN outputs jsonb;

COMMENT ON COLUMN platform.illustrations.reference_snapshot IS
  'Fee schedule, growth set, model, costs, cash rates and legal text this illustration used.';
COMMENT ON COLUMN platform.illustrations.outputs IS
  'Engine result for a GIA or ISA illustration. Null on a CTC pension illustration.';

