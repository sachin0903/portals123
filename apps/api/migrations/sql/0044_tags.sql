-- ============================================================================
-- 0044_tags — plain labels on contacts and cases, the substrate automations
-- compose through (Crisp's segments), plus two CHECK widenings the AML hand-off
-- path has needed since 0037.
--
-- WHY TAGS ARE DELIBERATELY DUMB. A tag is a label and nothing else: no value, no
-- type, no schema, no expiry. Structured detail belongs in real fields, where it
-- can be validated, audited as a domain change and read by the engine — the day a
-- tag carries `risk_rating:high` is the day the firm has an unvalidated,
-- unmigratable second data model with none of the guarantees the first one has.
-- What a tag IS for is composition: one automation applies `chaser-sent`, another
-- triggers on it, a third clears it. That is the whole feature, and keeping it
-- that small is what makes it safe to let firms create them freely.
--
-- TWO TABLES, NOT ONE POLYMORPHIC TABLE. `contact_id`/`case_id` are real foreign
-- keys with real ON DELETE CASCADE, so a deleted client cannot leave orphaned
-- labels behind and no application code has to remember to tidy up. A single
-- `(target_kind, target_id)` table would buy a little less SQL in app/tags.py at
-- the cost of referential integrity in the database, which is the wrong trade in
-- a schema whose whole tenancy story is enforced by the database.
--
-- THE READ RULE (do not "fix" for symmetry with crm.kyc_checks). The policies
-- scope by auth.tenant_lineage() and deliberately OMIT auth.contact_scope(): a
-- tag is STAFF shorthand about a client — `chaser-sent`, `slow-payer`,
-- `complaint-open` — and a client reading their own labels would be a disclosure
-- the firm never intended to make. auth.tenant_lineage() returns '{}' for a
-- client-portal principal, so the omission alone locks the client portal out.
-- This is the same reasoning as the AML tipping-off control in 0037, applied to a
-- much milder secret; contrast 0026, which DOES include contact_scope because a
-- client is entitled to see their own KYC state.
-- ============================================================================

-- ---- crm.contact_tags -------------------------------------------------------
CREATE TABLE crm.contact_tags (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  -- 0035's invariant: the link is COMPOSITE, not a bare contact_id. A tag row whose contact_id
  -- pointed into another firm would be readable by that firm (the `contact_id = ANY
  -- (auth.contact_scope())` branch of a dozen policies carries no tenant conjunct), and no WITH
  -- CHECK closes it because service_role — what the worker actually writes as — is not bound by
  -- RLS. Referential integrity is, for every role. `tests/test_schema_invariants.py` derives this
  -- requirement rather than enumerating it, and named this table when it was first written
  -- without it.
  -- Both FKs, matching every table 0035 touched: the plain one carries the cascade and the
  -- column's own integrity, the composite carries the tenant containment.
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  CONSTRAINT contact_tags_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE,

  -- Normalised at the service layer (app/tags.py::normalise): trimmed, inner
  -- whitespace collapsed, casefolded. Stored normalised rather than as-typed so
  -- that "VIP", "vip" and " Vip " are ONE tag — an idempotent apply has to mean
  -- something, and a label set that distinguishes them is a label set nobody can
  -- filter on. The CHECK is a backstop for any writer that bypasses the service.
  tag text NOT NULL CHECK (tag = lower(btrim(tag)) AND tag <> '' AND length(tag) <= 64),

  -- Provenance: who/what applied it. `applied_by` is NULL for an automation —
  -- there was no human — which is exactly what `source` then explains.
  source text NOT NULL DEFAULT 'manual'
    CHECK (source IN ('manual', 'automation', 'flow')),
  applied_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),

  -- THE idempotency key: applying a tag twice is a no-op, not a duplicate row.
  UNIQUE (contact_id, tag)
);
CREATE INDEX contact_tags_tenant_idx ON crm.contact_tags(tenant_id);
-- The condition hot path: "which tags does this contact carry?" (contact.tags),
-- read once per firing while the consumer builds its facts.
CREATE INDEX contact_tags_contact_idx ON crm.contact_tags(contact_id);
-- The reverse question the builder's picker and any future segment view asks:
-- "who carries this tag?"
CREATE INDEX contact_tags_tag_idx ON crm.contact_tags(tenant_id, tag);

ALTER TABLE crm.contact_tags ENABLE ROW LEVEL SECURITY;
CREATE POLICY contact_tags_read ON crm.contact_tags FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY contact_tags_write ON crm.contact_tags FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON crm.contact_tags TO authenticated;
GRANT ALL ON crm.contact_tags TO service_role;

-- ---- flows.case_tags --------------------------------------------------------
-- The same label on a unit of WORK rather than a person. A case tag answers "what
-- is going on with this journey" (`awaiting-probate`, `escalated`) and dies with
-- the case; a contact tag outlives every journey the client is ever on.
CREATE TABLE flows.case_tags (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  -- A plain FK here, NOT the composite one contact_tags carries, and the asymmetry is deliberate.
  -- 0035's invariant exists because a mis-tenanted contact/account link becomes readable through
  -- the `contact_id = ANY (auth.contact_scope())` branch that a dozen CLIENT-facing policies
  -- carry. case_tags has no such branch — its only read policy is tenant_lineage — so there is no
  -- client-portal path to widen, and the composite would additionally require a new
  -- UNIQUE (tenant_id, id) on flows.cases. Revisit if a client-scoped read of cases ever lands.
  case_id int NOT NULL REFERENCES flows.cases(id) ON DELETE CASCADE,
  tag text NOT NULL CHECK (tag = lower(btrim(tag)) AND tag <> '' AND length(tag) <= 64),
  source text NOT NULL DEFAULT 'manual'
    CHECK (source IN ('manual', 'automation', 'flow')),
  applied_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (case_id, tag)
);
CREATE INDEX case_tags_tenant_idx ON flows.case_tags(tenant_id);
CREATE INDEX case_tags_case_idx ON flows.case_tags(case_id);
CREATE INDEX case_tags_tag_idx ON flows.case_tags(tenant_id, tag);

ALTER TABLE flows.case_tags ENABLE ROW LEVEL SECURITY;
CREATE POLICY case_tags_read ON flows.case_tags FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY case_tags_write ON flows.case_tags FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.case_tags TO authenticated;
GRANT ALL ON flows.case_tags TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA crm TO authenticated, service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA flows TO authenticated, service_role;

-- Row-level audit from the 0001 spine. "Who tagged this client `complaint-open`,
-- and when did it come off again" is precisely the sort of question a compliance
-- reader asks months later, and a tag is cheap enough to churn that nobody would
-- remember without the trail.
SELECT audit.attach(ARRAY['crm.contact_tags', 'flows.case_tags']);
ALTER TABLE crm.contact_tags FORCE ROW LEVEL SECURITY;
ALTER TABLE flows.case_tags FORCE ROW LEVEL SECURITY;

-- ============================================================================
-- tasks.tasks — the AML hand-off has never been able to insert
-- ============================================================================
-- 0037 shipped app/aml/screening.py::_raise_screening_task with source_kind='aml'
-- and category='aml'. NEITHER value was ever legal:
--
--   * source_kind — 0027 declared ('manual','flow','document','system') and 0043
--     added 'automation'. 'aml' was never in the set, so the INSERT violates
--     tasks_source_kind_check.
--   * category — 0027 declared ('review','acknowledge','upload','follow_up',
--     'generic'), and app/tasks/service.py::CATEGORIES mirrors it. This one fails
--     EARLIER and more quietly: create_task validates the category in Python and
--     raises TaskError before the database is ever asked, so the constraint above
--     is not even reached.
--
-- The path is the one that asks a Graphene operator to adjudicate a possible
-- sanctions/PEP match raised by a firm's flow — i.e. it fails exactly when it
-- matters. Both values are widened here rather than rewritten to an existing
-- category, because provenance is the point: an operator filtering their inbox
-- needs to see an AML adjudication as an AML adjudication, not as a 'generic'
-- task from 'system'.
ALTER TABLE tasks.tasks DROP CONSTRAINT IF EXISTS tasks_source_kind_check;
ALTER TABLE tasks.tasks ADD CONSTRAINT tasks_source_kind_check
  CHECK (source_kind IN ('manual', 'flow', 'document', 'system', 'automation', 'aml'));

ALTER TABLE tasks.tasks DROP CONSTRAINT IF EXISTS tasks_category_check;
ALTER TABLE tasks.tasks ADD CONSTRAINT tasks_category_check
  CHECK (category IN ('review', 'acknowledge', 'upload', 'follow_up', 'generic', 'aml'));
