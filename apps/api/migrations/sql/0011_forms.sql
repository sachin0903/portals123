-- 0011_forms: staff-authored dynamic forms (questionnaires / fact-finds).
--
-- FEATURE: firm staff author typed, ordered, conditional forms in the platform builder; those
--  definitions were frontend/mock-only (docs/forms.md) — this lands the persistence they were
--  drawn to mirror ("a swap, not a rewrite"). Two tables:
--   * documents.forms       — the top-level form record (a named, ownable set of fields).
--   * documents.form_fields — the 1:N field list (one row per field, ordered by sort_order).
--  Home is documents.* (alongside the render pipeline they feed) per docs/forms.md open-question #2.
--
-- request_items.form_uid stays plain text (no FK): a request item may point at a form uid before
-- the row exists (and legacy/mock uids exist), so we keep the "dangling reference" tolerance from
-- 0007 rather than a hard constraint. Conditions/validation/options are opaque jsonb — the shapes
-- are the frontend FormField's (docs/forms.md §3); the API validates structure loosely and the
-- runtime (pkgs/ui) interprets them.
--
-- STAFF-ONLY RLS (tenant lineage), matching documents.documents. Clients don't read forms in this
-- slice (the client fill flow still resolves its definition from the bundled mock); a client-facing
-- render path is a documented follow-up. See docs/forms.md and docs/api.md.

-- forms -- the authorable form record. code is a human slug, unique per tenant.
CREATE TABLE documents.forms (
    id                          int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid                         text        NOT NULL UNIQUE,   -- public id ('frm_…'); API paths use this
    tenant_id                   int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    code                        text        NOT NULL,
    name                        text        NOT NULL,
    description                 text,
    status                      text        NOT NULL DEFAULT 'draft'
                                            CHECK (status IN ('draft', 'published', 'archived')),
    entity_type                 text        NOT NULL DEFAULT 'applicant'
                                            CHECK (entity_type IN ('applicant', 'account')),
    document_type               text,       -- optional doc-type affinity (a suggestion, not a lock)
    questionnaire_dataset_code  text,       -- FUTURE: the dataset this form feeds (docs/forms.md §9)
    created_by                  uuid        REFERENCES auth.users(id),
    created_at                  timestamptz NOT NULL DEFAULT now(),
    updated_at                  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT forms_tenant_code_key UNIQUE (tenant_id, code)
);
CREATE INDEX forms_tenant_idx ON documents.forms(tenant_id);

-- form_fields -- the ordered field list. tenant_id is denormalised for a simple RLS predicate (no
-- subquery, matching form_responses); it is always the parent form's tenant.
CREATE TABLE documents.form_fields (
    id           int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid          text        NOT NULL UNIQUE,   -- public id ('fld_…')
    tenant_id    int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,  -- denormalised for RLS
    form_id      int         NOT NULL REFERENCES documents.forms(id) ON DELETE CASCADE,
    field_key    text        NOT NULL,
    field_type   text        NOT NULL DEFAULT 'text',
    label        text        NOT NULL DEFAULT '',
    section      text,
    description  text,
    required     boolean     NOT NULL DEFAULT false,
    conditions   jsonb,      -- visibility (docs/forms.md FieldConditions); null = always visible
    validation   jsonb,      -- flat rules bag (FieldValidation)
    options      jsonb,      -- FieldOptions union
    sort_order   int         NOT NULL DEFAULT 0,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX form_fields_form_idx ON documents.form_fields(form_id, sort_order);
CREATE INDEX form_fields_tenant_idx ON documents.form_fields(tenant_id);

-- Standalone form responses: 0007 bound documents.form_responses to a request item (the client
-- fill flow). A form filled outside a request (docs/forms.md §9 "standalone mode") has no item, so
-- relax request_item_id to nullable and add a direct form_id link (present for standalone rows;
-- request-driven rows still carry request_item_id and resolve the form via it).
ALTER TABLE documents.form_responses ALTER COLUMN request_item_id DROP NOT NULL;
ALTER TABLE documents.form_responses ADD COLUMN form_id int REFERENCES documents.forms(id) ON DELETE SET NULL;
CREATE INDEX form_responses_form_idx ON documents.form_responses(form_id);

-- ===== RLS + grants =========================================================================
-- STAFF-ONLY (tenant lineage), matching documents.documents.

ALTER TABLE documents.forms ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents.forms FORCE ROW LEVEL SECURITY;
CREATE POLICY forms_read ON documents.forms FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY forms_write ON documents.forms FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON documents.forms TO authenticated;
GRANT ALL ON documents.forms TO service_role;

ALTER TABLE documents.form_fields ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents.form_fields FORCE ROW LEVEL SECURITY;
CREATE POLICY form_fields_read ON documents.form_fields FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY form_fields_write ON documents.form_fields FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON documents.form_fields TO authenticated;
GRANT ALL ON documents.form_fields TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA documents TO authenticated, service_role;

