-- 0235_identity_photos -- a portal client's identity photos, held encrypted only until their
-- identity check is finished.
--
-- The client's submit holds each photo here, sealed with the API's master key (`app.crypto`,
-- Fernet), and the worker sends them to ComplyCube from here, so a ComplyCube outage is a retry
-- rather than a lost send. A photo is deleted once nothing needs it: when its try reopens it, and
-- when the identity step finishes (passed, failed, cancelled, or handed to a person). The AML
-- console reads the images from ComplyCube, never from here.
--
-- Service_role only: no policy, and no grant to `authenticated`. Deliberately NOT under the audit
-- trigger: `audit.log` keeps whole rows for ever, which would keep every photo.

SET LOCAL lock_timeout = '5s';

CREATE TABLE compliance.identity_photos (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  case_id int NOT NULL REFERENCES flows.cases(id) ON DELETE CASCADE,
  step_key text NOT NULL,
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  -- The capture slot the photo fills (`app/idv/capture.py`): one photo per slot, replaced by a
  -- second send of the same slot.
  slot_uid text NOT NULL UNIQUE,
  item_key text NOT NULL
    CHECK (item_key IN ('idv_document_front', 'idv_document_back', 'idv_selfie')),
  content_type text NOT NULL
    CHECK (content_type IN ('image/jpeg', 'image/png', 'application/pdf')),
  -- The photo's bytes as a Fernet token: unreadable without the API's master key.
  sealed bytea NOT NULL,
  held_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT identity_photos_contact_tenant_fk
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX identity_photos_step_idx
  ON compliance.identity_photos (case_id, step_key, contact_id);

ALTER TABLE compliance.identity_photos ENABLE ROW LEVEL SECURITY;
ALTER TABLE compliance.identity_photos FORCE ROW LEVEL SECURITY;
REVOKE ALL ON compliance.identity_photos FROM PUBLIC;
REVOKE ALL ON compliance.identity_photos FROM authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON compliance.identity_photos TO service_role;
GRANT USAGE, SELECT ON SEQUENCE compliance.identity_photos_id_seq TO service_role;

COMMENT ON TABLE compliance.identity_photos IS
  'A portal client''s identity photos, sealed with the API master key, held only until ComplyCube '
  'has them and the identity step has finished. Service_role only; never audited.';
