-- ============================================================================
-- 0004_tenant_providers -- per-tenant platform/provider enablement (docs/storage.md §9,
-- docs/datalake.md). Creates the `integrations` schema (connectivity only --
-- data-architecture Decision 7; providers/connections/sync_jobs arrive with the
-- domain migration).
--
-- A tenant enables a provider with the filter that selects THEIR slice of the
-- whole-firm core data (the fan-out predicate):
--   morgan_lloyd: {"tenant_ids": ["<Microsoft tenant GUID>", ...]}
--   seccl:        {"node_ids": [...]}          (1-m nodes)
--   sei:          {"firm_id": ..., "subfirm_id": ..., "dsr_ids": [...]}
-- The core sync always lands ALL tenants' records; this registry drives which rows
-- fan out into each tenant's own bucket/catalogue.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS integrations;
GRANT USAGE ON SCHEMA integrations TO anon, authenticated, service_role;

CREATE TABLE integrations.tenant_providers (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  provider text NOT NULL CHECK (provider IN ('morgan_lloyd', 'seccl', 'sei')),
  -- Provider-shaped filter config (see header). Validated by the API per provider.
  config jsonb NOT NULL DEFAULT '{}',
  enabled boolean NOT NULL DEFAULT true,
  -- Fan-out bookkeeping: when this tenant's slice last projected successfully.
  last_fanout_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tenant_providers_tenant_provider_key UNIQUE (tenant_id, provider)
);
CREATE INDEX tenant_providers_tenant_id_idx ON integrations.tenant_providers (tenant_id);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON integrations.tenant_providers
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- A firm can see which providers it has enabled (and their filters); writes are
-- service_role only (operations manage enablement).
ALTER TABLE integrations.tenant_providers ENABLE ROW LEVEL SECURITY;
ALTER TABLE integrations.tenant_providers FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_providers_read ON integrations.tenant_providers FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON integrations.tenant_providers TO authenticated;
GRANT ALL ON integrations.tenant_providers TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA integrations TO service_role;

-- ============================================================================
-- integrations.provider_sources -- the KNOWN upstream sources per provider, with a
-- display name: e.g. each Morgan Lloyd Microsoft tenant (one Dynamics/Azure tenant per
-- firm). Drives the admin enablement dropdown. Operations-facing reference data --
-- service_role only (firms see their own enablement, not the cross-firm source list).
-- ============================================================================
CREATE TABLE integrations.provider_sources (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  provider text NOT NULL CHECK (provider IN ('morgan_lloyd', 'seccl', 'sei')),
  source_id text NOT NULL,   -- e.g. the Microsoft tenant GUID
  name text NOT NULL,        -- human label for dropdowns ("Clifton (dev)")
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT provider_sources_provider_source_key UNIQUE (provider, source_id)
);
CREATE TRIGGER set_updated_at BEFORE UPDATE ON integrations.provider_sources
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
ALTER TABLE integrations.provider_sources ENABLE ROW LEVEL SECURITY;
ALTER TABLE integrations.provider_sources FORCE ROW LEVEL SECURITY;
GRANT ALL ON integrations.provider_sources TO service_role;

-- Enablement changes (who can see which provider slice) are audit-relevant.
SELECT audit.attach(ARRAY[
  'integrations.tenant_providers',
  'integrations.provider_sources'
]);
