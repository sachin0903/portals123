-- ============================================================================
-- 0221_complycube_core.sql — ComplyCube as the one screening provider: the
-- portal's checks beside the firm API's, the matches a reviewer decides, and
-- the firm webhook outbox.
--
-- compliance.checks gains:
--   origin           'partner' (firm API) or 'portal' (a firm's onboarding flow)
--   kyc_check_id     the crm.kyc_checks row a portal check settles
--   attempt          the client's try number; a technical failure does not add one
--   decided_by/_at, decision_comment   an operations reviewer's verdict
--   stale_at         when the screened details stopped matching the client
--   monitoring       ongoing monitoring is on
-- and `failed` joins the status vocabulary: a check the provider could not run.
--
-- compliance.matches is one row per screening match, decided one by one.
-- compliance.webhook_deliveries is the outbox for a firm's `check.updated`.
--
-- TIPPING OFF (POCA 2002 s.333A). A firm's staff read compliance.checks through
-- the lineage policy, but only its status-level columns: `result`, `body`,
-- `outcome` and the reviewer's verdict are not granted. compliance.matches and
-- compliance.webhook_deliveries have no grant to `authenticated` at all, and the
-- inbox (compliance.events, which holds the provider's payload) loses its grant.
-- The audit.log read policy's firm branch excludes compliance.* as 0095 does
-- aml.*, so the DML trail cannot reopen what the grants withhold. Operations
-- reads all of it as service_role.
--
-- Every ADD COLUMN is nullable or carries a constant default, so none rewrites
-- the table. Alembic runs this revision inside a transaction, so the indexes
-- are not built concurrently; the tables are small.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

-- ---- compliance.checks -----------------------------------------------------

-- The target of the composite key below (0035's shape).
ALTER TABLE crm.kyc_checks ADD CONSTRAINT kyc_checks_tenant_id_key UNIQUE (tenant_id, id);

ALTER TABLE compliance.checks
  ADD COLUMN origin text NOT NULL DEFAULT 'partner',
  ADD COLUMN kyc_check_id int,
  ADD COLUMN attempt int NOT NULL DEFAULT 1,
  ADD COLUMN decided_by text,
  ADD COLUMN decided_at timestamptz,
  ADD COLUMN decision_comment text,
  ADD COLUMN stale_at timestamptz,
  ADD COLUMN monitoring boolean NOT NULL DEFAULT false;

ALTER TABLE compliance.checks
  ADD CONSTRAINT compliance_checks_origin_check CHECK (origin IN ('partner', 'portal')),
  ADD CONSTRAINT compliance_checks_attempt_check CHECK (attempt >= 1),
  ADD CONSTRAINT compliance_checks_tenant_id_key UNIQUE (tenant_id, id),
  -- Tenant-contained: a portal check can only settle its own firm's kyc row. Deleting the kyc
  -- row clears the link and keeps the check (and its tenant).
  ADD CONSTRAINT compliance_checks_kyc_check_fkey
    FOREIGN KEY (tenant_id, kyc_check_id) REFERENCES crm.kyc_checks (tenant_id, id)
    ON DELETE SET NULL (kyc_check_id);

ALTER TABLE compliance.checks DROP CONSTRAINT checks_status_check;
ALTER TABLE compliance.checks
  ADD CONSTRAINT checks_status_check
  CHECK (status IN ('pending', 'clear', 'refer', 'rejected', 'failed'));

CREATE INDEX compliance_checks_kyc_check_idx
  ON compliance.checks (kyc_check_id) WHERE kyc_check_id IS NOT NULL;

-- Column grants, replacing 0186's table-level SELECT. Column privileges are
-- additive to a table privilege, so the table grant has to go first.
REVOKE SELECT ON compliance.checks FROM authenticated;
-- decided_at is a date, not a result: it is what tells a firm's read that a refer is a decided
-- referral and not a review still in progress.
GRANT SELECT (
  id, uid, tenant_id, client_id, account_id, document_id, kind, status, origin,
  kyc_check_id, attempt, stale_at, decided_at, created_at, updated_at
) ON compliance.checks TO authenticated;

-- ---- compliance.events: the consumer's failure count -------------------------

ALTER TABLE compliance.events
  ADD COLUMN attempts int NOT NULL DEFAULT 0,
  ADD COLUMN last_error text;

REVOKE SELECT ON compliance.events FROM authenticated;

-- ---- compliance.matches -----------------------------------------------------

CREATE TABLE compliance.matches (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  -- Null while the check is unmatched, like the check itself.
  tenant_id int REFERENCES auth.tenants(id) ON DELETE CASCADE,
  check_id int NOT NULL REFERENCES compliance.checks(id) ON DELETE CASCADE,
  provider_match_id text NOT NULL,
  name text,
  match_types text[] NOT NULL DEFAULT '{}',
  score numeric,
  -- Text, not date: a listed date of birth is often a year or a year and month.
  dob text,
  countries text[] NOT NULL DEFAULT '{}',
  sources text[] NOT NULL DEFAULT '{}',
  raw jsonb NOT NULL DEFAULT '{}'::jsonb,
  decision text CHECK (decision IN ('confirmed', 'dismissed')),
  decided_by text,
  decided_at timestamptz,
  comment text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT compliance_matches_check_key UNIQUE (check_id, provider_match_id),
  CONSTRAINT compliance_matches_check_tenant_fkey
    FOREIGN KEY (tenant_id, check_id) REFERENCES compliance.checks (tenant_id, id)
    ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE INDEX compliance_matches_tenant_idx ON compliance.matches (tenant_id);

-- ---- compliance.webhook_deliveries -------------------------------------------

CREATE TABLE compliance.webhook_deliveries (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  webhook_id int NOT NULL REFERENCES compliance.webhooks(id) ON DELETE CASCADE,
  event text NOT NULL,
  payload jsonb NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
  attempts int NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX compliance_webhook_deliveries_due_idx
  ON compliance.webhook_deliveries (next_attempt_at) WHERE status = 'pending';
CREATE INDEX compliance_webhook_deliveries_tenant_idx
  ON compliance.webhook_deliveries (tenant_id);

-- No policy and no grant for `authenticated`: withholding the privilege is
-- stronger than a policy that evaluates to false. service_role (BYPASSRLS)
-- does every read and write.
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY['matches', 'webhook_deliveries']
  LOOP
    EXECUTE format('ALTER TABLE compliance.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE compliance.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('GRANT ALL ON compliance.%I TO service_role', tbl);
    EXECUTE format(
      'CREATE TRIGGER set_updated_at BEFORE UPDATE ON compliance.%I '
      'FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()',
      tbl
    );
  END LOOP;
END $$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA compliance TO service_role;

SELECT audit.attach(ARRAY['compliance.matches', 'compliance.webhook_deliveries']);

-- ---- the DML trail -------------------------------------------------------------
-- 0095's carve-out, extended: a firm principal never reads a compliance.* audit
-- row, because those rows carry the raw before/after of results and matches.

ALTER POLICY audit_log_read ON audit.log USING (
    (
      tenant_id = ANY (auth.tenant_lineage())
      AND entity_type NOT LIKE 'aml.%'
      AND entity_type NOT LIKE 'compliance.%'
    )
    OR (tenant_id IS NULL AND auth.is_system())
);
