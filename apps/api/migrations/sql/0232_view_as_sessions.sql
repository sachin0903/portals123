-- 0232_view_as_sessions -- a member of staff opening the client portal as one of their clients.
--
-- A member of staff opens the client portal to see exactly what a client sees. The session that
-- results is recorded here, one row per opening, and the row IS the credential: the client
-- portal holds an opaque token whose SHA-256 is `token_hash`, and every request it makes is
-- resolved back to this row. Keeping the credential in a table rather than in a self-contained
-- signed token is what makes the session revocable (`ended_at`) and answerable after the fact --
-- who looked, at whom, when, why, and for how long.
--
-- `handoff_hash` is the separate, near-immediate, single-use ticket that carries the session
-- from the staff portal to the client portal in a URL. Redeeming it is what MINTS the session
-- token, rather than handing over one already stored: the token is generated at redemption, its
-- hash written into `token_hash`, and the ticket destroyed in the same statement. So the row
-- holds no recoverable credential at any point in its life, only hashes -- and until the ticket
-- is redeemed there is no session token in existence at all, which is why `token_hash` is null
-- until then.
--
-- Tenant-scoped like every other row in this estate: the adviser and the client are both in the
-- same firm, and the session carries that firm so the firm's own trail can read it.

SET LOCAL lock_timeout = '5s';

CREATE TABLE auth.view_as_sessions (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  adviser_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  token_hash text UNIQUE,
  reason text NOT NULL,
  handoff_hash text,
  handoff_expires_at timestamptz,
  started_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  ended_at timestamptz,
  -- A reason is required of the person opening the session, and an empty one is not a reason.
  CONSTRAINT view_as_sessions_reason_present CHECK (btrim(reason) <> ''),
  -- 0035's invariant: a client link is tenant-contained by referential integrity, so a session
  -- can never name a contact in another firm whatever role wrote the row.
  CONSTRAINT view_as_sessions_contact_tenant_fk
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE
);

-- Resolving a live session on every request is the hot path: one partial index over the
-- sessions that can still answer.
CREATE INDEX view_as_sessions_live_idx ON auth.view_as_sessions (token_hash)
  WHERE ended_at IS NULL;

CREATE INDEX view_as_sessions_handoff_idx ON auth.view_as_sessions (handoff_hash)
  WHERE handoff_hash IS NOT NULL;

CREATE INDEX view_as_sessions_contact_idx
  ON auth.view_as_sessions (tenant_id, contact_id, started_at DESC);

COMMENT ON TABLE auth.view_as_sessions IS
  'One row per opening of the client portal by a member of staff acting as a client. The row is '
  'the credential (token_hash) and the record: adviser, client, reason, and the window it was '
  'open for. Revoked by setting ended_at.';
COMMENT ON COLUMN auth.view_as_sessions.token_hash IS
  'SHA-256 of the session token the client portal holds in an httpOnly cookie. Null until the '
  'handoff ticket is redeemed, which is the moment that token is first generated.';
COMMENT ON COLUMN auth.view_as_sessions.handoff_hash IS
  'SHA-256 of the single-use ticket that carries the session across to the client portal in a '
  'URL. Redeeming it mints the session token, so the token itself never travels in a query '
  'string and is never stored in a form anything can read back.';
COMMENT ON COLUMN auth.view_as_sessions.reason IS
  'Why the session was opened, given by the person opening it.';

ALTER TABLE auth.view_as_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth.view_as_sessions FORCE ROW LEVEL SECURITY;

-- Readable by the person who opened it (which is also how the session reads its own banner --
-- the view-as principal's user_uuid IS the adviser), and by whoever reads the firm's audit
-- trail. Minting and ending are service_role, so there is no write policy for `authenticated`:
-- a session cannot end or extend itself from under RLS.
CREATE POLICY view_as_sessions_read ON auth.view_as_sessions
  FOR SELECT TO authenticated
  USING (
    auth.is_system()
    OR (tenant_id = auth.tenant_id()
        AND (adviser_id = auth.uid() OR auth.has_permission('audit:read')))
  );

GRANT SELECT ON auth.view_as_sessions TO authenticated;
GRANT ALL ON auth.view_as_sessions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE auth.view_as_sessions_id_seq TO authenticated, service_role;

CREATE TRIGGER audit_row AFTER INSERT OR DELETE OR UPDATE ON auth.view_as_sessions
  FOR EACH ROW EXECUTE FUNCTION audit.record();


-- The claims a view-as session runs on.
--
-- This does not replace `auth.resolve_claims`; it calls it and narrows what comes back. That is
-- the safety argument in one place: the scope a member of staff holds is minted by exactly the
-- function every other staff request uses -- here classified as a PLATFORM session through the
-- tenant's registered platform application -- this asks whether the client they came to see is
-- inside it (their assigned book, or the whole firm via contacts:read_all / system), and the
-- session is then collapsed to that one client. No path through here ends in more access than
-- the login already had, and the existing minter is left as it is.
--
-- The portal comes back as 'client' because that is where the session is. `auth.tenant_lineage()`
-- is therefore '{}' (the client lever), `auth.can_read_all()` is false, and every policy answers
-- the way it does for the person whose portal is on screen. The staff roles this login holds do
-- not travel with it, for the same reason: `role_ids` is empty.
CREATE FUNCTION auth.resolve_view_as_claims(
  p_workos_user_id text,
  p_workos_org_id text,
  p_view_as_contact int
) RETURNS jsonb
  LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'auth' AS $fn$
DECLARE
  v_tenant_id   int;
  v_app         text;
  v_staff       jsonb;
  v_book        int[];
  v_role_ids    int[];
  v_perms       text[];
  v_account_ids int[];
BEGIN
  IF p_view_as_contact IS NULL THEN
    RAISE EXCEPTION 'auth.resolve_view_as_claims: no client to view as'
      USING ERRCODE = 'invalid_parameter_value';
  END IF;

  SELECT tenant_id INTO v_tenant_id FROM auth.users
    WHERE workos_user_id = p_workos_user_id AND deleted_at IS NULL;
  IF v_tenant_id IS NULL THEN
    RAISE EXCEPTION 'auth.resolve_view_as_claims: no identity to open a session for'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  -- The tenant's platform application: what classifies the staff resolution below as a
  -- platform-portal session (0107, app-only portal). A firm with none registered has no staff
  -- portal to have opened this from, and the resolution falls to no portal and no scope.
  SELECT platform_client_id INTO v_app FROM auth.tenant_environments
    WHERE tenant_id = v_tenant_id AND platform_client_id IS NOT NULL
    ORDER BY id LIMIT 1;

  -- The scope this login holds AS STAFF. Containment, portal validation and the book lineage
  -- are all that function's, unchanged and not duplicated here.
  v_staff := auth.resolve_claims(p_workos_user_id, p_workos_org_id, v_app);

  IF v_staff ->> 'user_uuid' IS NULL OR (v_staff ->> 'portal') IS DISTINCT FROM 'platform' THEN
    RAISE EXCEPTION 'auth.resolve_view_as_claims: no platform session to open a view-as from'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT COALESCE(array_agg(value::int), '{}'::int[]) INTO v_book
    FROM jsonb_array_elements_text(v_staff -> 'contact_ids');

  IF NOT (p_view_as_contact = ANY(v_book)) THEN
    -- Match the contacts read policy: firm-wide readers (and the system principal) may reach
    -- any live client even when that client is not in their assigned book.
    SELECT COALESCE(array_agg(value::int), '{}'::int[]) INTO v_role_ids
      FROM jsonb_array_elements_text(v_staff -> 'role_ids');
    v_perms := auth.member_permissions(v_role_ids);
    IF NOT ('contacts:read_all' = ANY(v_perms) OR 'system' = ANY(v_perms)) THEN
      RAISE EXCEPTION 'auth.resolve_view_as_claims: client % is not in this login''s book',
        p_view_as_contact
        USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;

  -- Live, and in the same firm. A deleted client has no portal to show, and a client of another
  -- firm is nobody this login can know exists.
  IF NOT EXISTS (
    SELECT 1 FROM crm.contacts
     WHERE id = p_view_as_contact AND tenant_id = v_tenant_id AND deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'auth.resolve_view_as_claims: client % is not a live client of this firm',
      p_view_as_contact
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT COALESCE(array_agg(DISTINCT aid), '{}'::int[]) INTO v_account_ids FROM (
    SELECT id AS aid FROM platform.accounts
      WHERE contact_id = p_view_as_contact AND tenant_id = v_tenant_id
    UNION
    SELECT account_id AS aid FROM crm.account_contacts
      WHERE contact_id = p_view_as_contact AND account_id IS NOT NULL AND tenant_id = v_tenant_id
  ) s;

  RETURN jsonb_build_object(
    'user_uuid',   v_staff -> 'user_uuid',
    'tenant_id',   v_staff -> 'tenant_id',
    'tenant_ids',  '[]'::jsonb,
    'portal',      'client',
    'contact_ids', to_jsonb(ARRAY[p_view_as_contact]),
    'account_ids', to_jsonb(v_account_ids),
    'role_ids',    '[]'::jsonb,
    'view_as',     to_jsonb(p_view_as_contact)
  );
END;
$fn$;

COMMENT ON FUNCTION auth.resolve_view_as_claims(text, text, int) IS
  'Claims for a staff login acting in the client portal as one of its clients. Delegates to '
  'auth.resolve_claims for the staff (platform) scope, refuses a client outside it unless the '
  'login holds contacts:read_all (or system), and answers with that one client under '
  'portal=client and no roles -- so it can only ever narrow.';

-- Same definer as the function it delegates to: `auth.users`, `crm.contacts` and
-- `crm.client_advisers` all carry row-level security, and a definer subject to them would
-- resolve every login to no identity at all.
ALTER FUNCTION auth.resolve_view_as_claims(text, text, int) OWNER TO service_role;
GRANT EXECUTE ON FUNCTION auth.resolve_view_as_claims(text, text, int)
  TO authenticated, service_role;


-- The client a session is acting as, or NULL for an ordinary session. Policies that collapse
-- on contact_scope() do not need it; the two below do, and a surface that has to say "you are
-- viewing as someone" reads it here rather than inferring it.
CREATE FUNCTION auth.view_as() RETURNS int LANGUAGE sql STABLE AS $$
  SELECT NULLIF(auth.jwt() ->> 'view_as', '')::int $$;

COMMENT ON FUNCTION auth.view_as() IS
  'The client this session is acting as, or NULL. Set only for a staff view-as session.';

GRANT EXECUTE ON FUNCTION auth.view_as() TO authenticated, service_role;


-- A view-as session keeps the STAFF user_uuid for audit, so the two policies that OR on the
-- caller's own uuid without a lineage guard would otherwise hand the whole of that adviser's
-- book -- every client_advisers row, every contact_users row -- to a screen captioned with one
-- client's name. Every other adviser-self branch in this estate is already behind
-- `tenant_id = ANY (auth.tenant_lineage())`, which is '{}' for a client-portal session.
DROP POLICY IF EXISTS contact_users_read ON crm.contact_users;
CREATE POLICY contact_users_read ON crm.contact_users FOR SELECT TO authenticated USING (
  (auth.view_as() IS NULL AND user_id = auth.uid())
  OR (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
  OR contact_id = ANY (auth.contact_scope())
);

DROP POLICY IF EXISTS client_advisers_read ON crm.client_advisers;
CREATE POLICY client_advisers_read ON crm.client_advisers FOR SELECT TO authenticated USING (
  (auth.view_as() IS NULL AND adviser_id = auth.uid())
  OR (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
  OR contact_id = ANY (auth.contact_scope())
);
