-- ============================================================================
-- 0179_reviews.sql — four-eye checks (peer review). Design: docs/reviews.md.
--
-- A firm can mark designated staff actions as requiring a second person before
-- they take effect. The hold is a fat, replayable command on reviews.requests;
-- audit.actions stays the thin "it happened" stream and is emitted only after
-- apply. Neither table is audit.attach'd: the request row holds redact-class
-- payloads (bank digits) and the DML trail must not store them.
--
-- Also grants the new reviews:* slugs to the model-tenant preset (0042 idiom)
-- and backfills existing owner / compliance roles so a firm that already exists
-- does not lose the capability until someone opens the role editor.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE SCHEMA reviews;
GRANT USAGE ON SCHEMA reviews TO authenticated, service_role;

CREATE TABLE reviews.policies (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  action_key text NOT NULL,
  mode text NOT NULL DEFAULT 'off' CHECK (mode IN ('off', 'four_eye')),
  reviewer_role_id int REFERENCES auth.roles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, action_key)
);

CREATE INDEX reviews_policies_tenant_idx ON reviews.policies(tenant_id);

CREATE TABLE reviews.requests (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

  action_key text NOT NULL,
  event_type text NOT NULL,

  subject_type text NOT NULL CHECK (subject_type IN ('contact', 'account', 'instruction')),
  subject_id text NOT NULL,
  contact_id int REFERENCES crm.contacts(id) ON DELETE CASCADE,

  payload jsonb NOT NULL,
  before jsonb,
  justification text NOT NULL,
  reviewer_role_id int REFERENCES auth.roles(id) ON DELETE SET NULL,

  proposed_by uuid NOT NULL REFERENCES auth.users(id),
  proposed_at timestamptz NOT NULL DEFAULT now(),

  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled', 'conflicted')),
  decided_by uuid REFERENCES auth.users(id),
  decided_at timestamptz,
  decision_note text,
  applied_at timestamptz,

  idempotency_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX reviews_requests_idempotency_key
  ON reviews.requests(tenant_id, idempotency_key);
CREATE UNIQUE INDEX reviews_requests_open_subject_key
  ON reviews.requests(tenant_id, action_key, subject_type, subject_id)
  WHERE status = 'pending';
CREATE INDEX reviews_requests_tenant_status_idx
  ON reviews.requests(tenant_id, status);
CREATE INDEX reviews_requests_proposed_by_idx
  ON reviews.requests(proposed_by);
CREATE INDEX reviews_requests_contact_idx
  ON reviews.requests(contact_id)
  WHERE contact_id IS NOT NULL;

-- RLS: full-book staff see the firm's queue; book-scoped staff see their book
-- plus their own proposals. Clients see nothing (lineage is empty; they are
-- never the proposer of a staff action). WITH CHECK stays tenant-wide —
-- targeting is validated in the service layer.
ALTER TABLE reviews.policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews.requests ENABLE ROW LEVEL SECURITY;

CREATE POLICY reviews_policies_read ON reviews.policies FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY reviews_policies_write ON reviews.policies FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

CREATE POLICY reviews_requests_read ON reviews.requests FOR SELECT TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR (
      tenant_id = ANY (auth.tenant_lineage())
      AND (
        proposed_by = NULLIF(auth.jwt() ->> 'user_uuid', '')::uuid
        OR contact_id IS NULL
        OR contact_id = ANY (auth.contact_scope())
      )
    )
  );
CREATE POLICY reviews_requests_write ON reviews.requests FOR ALL TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR (
      tenant_id = ANY (auth.tenant_lineage())
      AND (
        proposed_by = NULLIF(auth.jwt() ->> 'user_uuid', '')::uuid
        OR contact_id IS NULL
        OR contact_id = ANY (auth.contact_scope())
      )
    )
  )
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

GRANT SELECT, INSERT, UPDATE ON reviews.policies TO authenticated;
GRANT SELECT, INSERT, UPDATE ON reviews.requests TO authenticated;
GRANT ALL ON reviews.policies TO service_role;
GRANT ALL ON reviews.requests TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA reviews TO authenticated, service_role;

CREATE TRIGGER set_updated_at_reviews_policies BEFORE UPDATE ON reviews.policies
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER set_updated_at_reviews_requests BEFORE UPDATE ON reviews.requests
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE reviews.policies FORCE ROW LEVEL SECURITY;
ALTER TABLE reviews.requests FORCE ROW LEVEL SECURITY;

-- ---- permissions (0042 idiom) ------------------------------------------------
SET LOCAL ROLE service_role;

INSERT INTO auth.permissions (slug, name, resource, action, portal, description)
SELECT s.slug, s.slug, split_part(s.slug, ':', 1), split_part(s.slug, ':', 2), s.portal,
       'Bootstrap placeholder; app/permissions.py is the source of truth and refreshes this row.'
  FROM (VALUES
    ('reviews:read', 'platform'),
    ('reviews:write', 'platform'),
    ('reviews:approve', 'platform')
  ) AS s(slug, portal)
ON CONFLICT (slug) DO NOTHING;

-- Existing owner roles already configure the firm; give them the full set so
-- the settings page is reachable without a role-editor visit. Compliance is
-- the default checker. Adviser proposes via the action's own write permission
-- and does not get the queue grants.
INSERT INTO auth.role_permissions (role_id, permission_id)
SELECT r.id, p.id
  FROM (VALUES
    ('owner', 'reviews:read'),
    ('owner', 'reviews:write'),
    ('owner', 'reviews:approve'),
    ('compliance', 'reviews:read'),
    ('compliance', 'reviews:approve')
  ) AS g(role_slug, perm_slug)
  JOIN auth.tenants t ON t.is_model
  JOIN auth.roles r ON r.tenant_id = t.id AND r.slug = g.role_slug
  JOIN auth.permissions p ON p.slug = g.perm_slug
ON CONFLICT DO NOTHING;

-- Firms that already exist: every role holding roles:write (the people who
-- already configure access) gets reviews:write + read; every role holding
-- screening:read or the literal compliance slug gets read + approve. Narrowing
-- afterwards is a role-editor act, never this migration.
INSERT INTO auth.role_permissions (role_id, permission_id)
SELECT DISTINCT rp.role_id, child.id
  FROM auth.role_permissions rp
  JOIN auth.permissions parent ON parent.id = rp.permission_id
                              AND parent.slug = 'roles:write'
  JOIN auth.permissions child  ON child.slug IN ('reviews:read', 'reviews:write', 'reviews:approve')
ON CONFLICT DO NOTHING;

INSERT INTO auth.role_permissions (role_id, permission_id)
SELECT DISTINCT r.id, p.id
  FROM auth.roles r
  JOIN auth.permissions p ON p.slug IN ('reviews:read', 'reviews:approve')
  WHERE r.slug = 'compliance'
ON CONFLICT DO NOTHING;

RESET ROLE;

-- Peer-review built-ins address the reviewer role and the proposer. 0068's
-- audience CHECK did not know those names; without this, seeding the catalogue
-- fails the insert and no review notice ever lands. After RESET ROLE so the
-- migration owner can ALTER (service_role cannot).
ALTER TABLE notifications.rules DROP CONSTRAINT rules_audience_check;
ALTER TABLE notifications.rules ADD CONSTRAINT rules_audience_check
  CHECK (audience IN ('client', 'adviser', 'role', 'actor', 'assignee', 'reviewer', 'proposer'));
