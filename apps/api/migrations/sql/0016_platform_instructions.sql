-- 0016_platform_instructions: lightweight money-movement instructions for the transactions demo.
--
-- Adviser-initiated actions from the platform client detail: expected money in, cash withdrawal,
-- and model top-up / withdrawal. DEMO-GRADE — each is a real, audited row, but there is NO provider
-- integration, ledger posting or reconciliation behind it (that is the pensions-ledger work, §8 of
-- data-architecture.md). The row records intent + status only.
--
-- Client-readable for their own accounts (account_scope); staff by tenant lineage. Writes come from
-- the platform portal's firm_session (service_role), so the authenticated write policy is staff-only.

CREATE TABLE platform.instructions (
    id          int           PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid         text          NOT NULL UNIQUE,
    tenant_id   int           NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    account_id  int           NOT NULL REFERENCES platform.accounts(id) ON DELETE CASCADE,
    contact_id  int           REFERENCES crm.contacts(id) ON DELETE SET NULL,
    kind        text          NOT NULL
                    CHECK (kind IN ('expected_in', 'withdrawal', 'model_topup', 'model_withdrawal')),
    amount      numeric(18,2) NOT NULL CHECK (amount > 0),
    model_id    int           REFERENCES platform.models(id) ON DELETE SET NULL,
    due_date    date,
    note        text,
    status      text          NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'settled', 'cancelled')),
    created_by  uuid          REFERENCES auth.users(id),
    created_at  timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX instructions_tenant_idx ON platform.instructions(tenant_id, status);
CREATE INDEX instructions_account_idx ON platform.instructions(account_id);
CREATE INDEX instructions_contact_idx ON platform.instructions(contact_id, status);

ALTER TABLE platform.instructions ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.instructions FORCE ROW LEVEL SECURITY;

-- Read: staff see the firm's (tenant lineage); a client sees instructions on their own accounts.
CREATE POLICY instructions_read ON platform.instructions FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()) OR account_id = ANY (auth.account_scope()));
-- Write: staff-only at the DB (clients never create these; the platform firm_session is service_role).
CREATE POLICY instructions_write ON platform.instructions FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

GRANT SELECT, INSERT, UPDATE, DELETE ON platform.instructions TO authenticated;
GRANT ALL ON platform.instructions TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA platform TO authenticated, service_role;

-- Free DML audit trail (0001 spine) — every write lands in audit.log.
SELECT audit.attach(ARRAY['platform.instructions']);
