-- 0125_content: firm-published news, articles and PDF guides for the client portal.
--
-- Staff author in the platform CMS; clients never SELECT these tables (no contact_scope —
-- broadcast HTML must not leak via "my book", same posture as comms.messages / crm.contact_tags).
-- Client reads go through GET /crm/content, which filters published + eligible rows in the API.
-- eligibility jsonb is reserved for a later ConditionBuilder subset and MUST stay NULL in v1.

CREATE SCHEMA IF NOT EXISTS content;
GRANT USAGE ON SCHEMA content TO authenticated, service_role;

CREATE TYPE content.item_kind AS ENUM ('news', 'article', 'guide');
CREATE TYPE content.item_status AS ENUM ('draft', 'published', 'archived');
CREATE TYPE content.audience AS ENUM ('all', 'individual', 'organisation');

CREATE TABLE content.categories (
    id         int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid        text        NOT NULL UNIQUE DEFAULT public.nanoid(12),
    tenant_id  int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    name       text        NOT NULL,
    slug       text        NOT NULL,
    sort_order int         NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, slug)
);
CREATE INDEX content_categories_tenant_idx ON content.categories (tenant_id);

CREATE TABLE content.items (
    id                           int                  PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid                          text                 NOT NULL UNIQUE DEFAULT public.nanoid(12),
    tenant_id                    int                  NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    kind                         content.item_kind    NOT NULL,
    title                        text                 NOT NULL,
    slug                         text                 NOT NULL,
    summary                      text,
    category_id                  int                  REFERENCES content.categories(id) ON DELETE SET NULL,
    status                       content.item_status  NOT NULL DEFAULT 'draft',
    audience                     content.audience     NOT NULL DEFAULT 'all',
    service_types                text[]               NOT NULL DEFAULT '{}',
    sub_types                    text[]               NOT NULL DEFAULT '{}',
    eligibility                  jsonb,
    schema                       jsonb                NOT NULL DEFAULT '{}'::jsonb,
    body_html                    text,
    hero_url                     text,
    file_key                     text,
    file_content_type            text,
    file_size                    int,
    current_published_version_id int,
    published_at                 timestamptz,
    expires_at                   timestamptz,
    created_by                   uuid                 NOT NULL REFERENCES auth.users(id),
    created_at                   timestamptz          NOT NULL DEFAULT now(),
    updated_at                   timestamptz          NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, slug),
    CONSTRAINT content_items_eligibility_null CHECK (eligibility IS NULL),
    CONSTRAINT content_items_service_types_valid CHECK (
        service_types <@ ARRAY['advised', 'execution_only', 'discretionary']::text[]
    ),
    CONSTRAINT content_items_sub_types_valid CHECK (
        sub_types <@ ARRAY['trust', 'company', 'charity']::text[]
    )
);
CREATE INDEX content_items_tenant_status_idx ON content.items (tenant_id, status);
CREATE INDEX content_items_tenant_kind_idx ON content.items (tenant_id, kind);

CREATE TABLE content.item_versions (
    id             int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid            text        NOT NULL UNIQUE DEFAULT public.nanoid(12),
    tenant_id      int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    item_id        int         NOT NULL REFERENCES content.items(id) ON DELETE CASCADE,
    version_number int         NOT NULL,
    schema         jsonb       NOT NULL DEFAULT '{}'::jsonb,
    body_html      text        NOT NULL DEFAULT '',
    published_by   uuid        REFERENCES auth.users(id),
    published_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (item_id, version_number)
);
CREATE INDEX content_item_versions_item_idx ON content.item_versions (item_id);

ALTER TABLE content.items
    ADD CONSTRAINT fk_content_current_published_version
    FOREIGN KEY (current_published_version_id)
    REFERENCES content.item_versions(id)
    DEFERRABLE INITIALLY DEFERRED;

-- Published snapshots are insert-only. The live draft lives on content.items.schema.
CREATE OR REPLACE FUNCTION content.reject_version_mutation() RETURNS trigger
  LANGUAGE plpgsql AS $fn$
BEGIN
    RAISE EXCEPTION 'content versions are immutable'
        USING ERRCODE = 'restrict_violation',
              HINT = 'Publish a new version instead of editing a snapshot.';
    RETURN NULL;
END;
$fn$;

SET LOCAL lock_timeout = '5s';
CREATE TRIGGER content_item_versions_immutable
    BEFORE UPDATE OR DELETE ON content.item_versions
    FOR EACH ROW EXECUTE FUNCTION content.reject_version_mutation();

ALTER TABLE content.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE content.categories FORCE ROW LEVEL SECURITY;
CREATE POLICY content_categories_read ON content.categories FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()) OR tenant_id = auth.tenant_id());
CREATE POLICY content_categories_write ON content.categories FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON content.categories TO authenticated;
GRANT ALL ON content.categories TO service_role;

ALTER TABLE content.items ENABLE ROW LEVEL SECURITY;
ALTER TABLE content.items FORCE ROW LEVEL SECURITY;
CREATE POLICY content_items_read ON content.items FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
-- Clients have an empty lineage, so the staff policy above hides every row. They may SELECT
-- published items for their own tenant; eligibility (audience / service type) is enforced in the
-- API, not here. Writes stay lineage-only, so a client cannot draft or publish.
CREATE POLICY content_items_client_read ON content.items FOR SELECT TO authenticated
    USING (tenant_id = auth.tenant_id() AND status = 'published');
CREATE POLICY content_items_write ON content.items FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON content.items TO authenticated;
GRANT ALL ON content.items TO service_role;

ALTER TABLE content.item_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE content.item_versions FORCE ROW LEVEL SECURITY;
CREATE POLICY content_item_versions_read ON content.item_versions FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY content_item_versions_client_read ON content.item_versions FOR SELECT TO authenticated
    USING (
        tenant_id = auth.tenant_id()
        AND EXISTS (
            SELECT 1 FROM content.items i
            WHERE i.id = item_id AND i.status = 'published' AND i.tenant_id = auth.tenant_id()
        )
    );
CREATE POLICY content_item_versions_write ON content.item_versions FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON content.item_versions TO authenticated;
GRANT ALL ON content.item_versions TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA content TO authenticated, service_role;

SELECT audit.attach(ARRAY['content.categories', 'content.items', 'content.item_versions']);
