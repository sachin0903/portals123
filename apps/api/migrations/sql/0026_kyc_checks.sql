-- ============================================================================
-- 0026_kyc_checks.sql — the contact-scoped KYC store (Phase 3).
--
-- KYC is a property of the PERSON, not the account or application: a valid identity/AML result is
-- reused across every account and future application (no duplicate checks — the user's dedup
-- requirement). Stored per crm.contacts with a firm-configurable validity window; ongoing AML
-- monitoring alerts flag/reopen affected applications.
--
--   crm.kyc_checks — one row per (contact, kind) check attempt. The orchestrator's review handler
--   reads-or-triggers: a valid `passed` row short-circuits the step to completed; otherwise a new
--   check is kicked off and its external_ref stored. A monitoring alert updates the row and drives
--   the reopen path.
-- ============================================================================

CREATE TABLE crm.kyc_checks (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                          -- 'kyc_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('identity', 'aml')),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'passed', 'failed', 'referred', 'expired')),
  provider text NOT NULL DEFAULT 'manual',           -- 'manual' | 'idenfy' | 'creditsafe'
  external_ref text,                                 -- the provider's check/session id (async)
  monitoring_ref text,                               -- ongoing-monitoring schedule id (AML)
  verified_at timestamptz,
  valid_until timestamptz,                           -- firm-configurable re-screen horizon
  raw jsonb NOT NULL DEFAULT '{}'::jsonb,             -- provider payload (audit)
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX kyc_checks_tenant_id_idx ON crm.kyc_checks(tenant_id);
CREATE INDEX kyc_checks_contact_id_idx ON crm.kyc_checks(contact_id);
-- The dedup hot path: "does this contact hold a currently-valid check of this kind?"
CREATE INDEX kyc_checks_valid_idx
  ON crm.kyc_checks(contact_id, kind, valid_until) WHERE status = 'passed';
CREATE INDEX kyc_checks_external_ref_idx
  ON crm.kyc_checks(external_ref) WHERE external_ref IS NOT NULL;

-- RLS: staff read within the tenant lineage; the client reads their OWN checks (contact_scope);
-- writes are service_role only (the engine / provider webhook). Regulated data → audited + FORCE.
ALTER TABLE crm.kyc_checks ENABLE ROW LEVEL SECURITY;
CREATE POLICY kyc_checks_read ON crm.kyc_checks FOR SELECT TO authenticated
  USING (
    tenant_id = ANY (auth.tenant_lineage())
    OR contact_id = ANY (auth.contact_scope())
  );
GRANT SELECT ON crm.kyc_checks TO authenticated;
GRANT ALL ON crm.kyc_checks TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA crm TO authenticated, service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON crm.kyc_checks
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
SELECT audit.attach(ARRAY['crm.kyc_checks']);
ALTER TABLE crm.kyc_checks FORCE ROW LEVEL SECURITY;
