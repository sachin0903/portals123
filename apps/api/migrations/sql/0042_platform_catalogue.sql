  key            text PRIMARY KEY,
  category       text NOT NULL,
  default_label  text NOT NULL,
  default_plural text,
  description    text,
  sort_order     smallint NOT NULL DEFAULT 0
);
-- Global reference data, like a currency list: readable by everyone, no tenant column to
-- filter on, writes are ours (a new key ships with the code that reads it). RLS is still
-- enabled with a permissive policy -- the same statement-not-omission rule the invariant test
-- applies to platform.instruments and platform.platforms.
