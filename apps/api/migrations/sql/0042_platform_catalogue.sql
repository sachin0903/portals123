-- ============================================================================
-- 0042_platform_catalogue -- the firm-configured half of the platform model: products,
-- models (with allocation history and commentary), fee packages, the two provider
-- registries, and terminology overrides.
--
-- 0002 sketched products/models/fee_packages as platform-scoped configuration. Three things
-- were wrong for what the admin app needs:
--
--   1. `products` had no tenant_id at all and a `USING (true)` read policy, so a product was
--      global. A firm's product shelf is firm data: "the Graphene SIPP" is not the same
--      object as another firm's SIPP even when both are Seccl SIPPs.
--   2. `models` was one row per (model, platform) via a NOT NULL platform_id, which
--      contradicts data-architecture Decision 1 -- the same model can exist on Seccl and
--      SEI, which is what 0031's platform.model_platforms is for.
--   3. Neither carried the fields the providers actually publish, so a model's target
--      return lived in Seccl's `url` field and an allocation change left no record at all.
--
-- Expand phase: new tables, new nullable columns, and NOT NULL only dropped, never added.
-- No existing row is rewritten.
-- ============================================================================

-- ============================================================================
