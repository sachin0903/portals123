--
-- A wealth manager says "instruments" where a platform says "assets", and calling it the
-- wrong thing in their own portal is a papercut on every page. This is a per-tenant
-- override of ~30 nouns, NOT a multi-lingual message catalogue: there is one language, the
-- keys are stable, and the values are a word or two.
--
-- Its own schema because it is not platform data. `l10n.terms` is the catalogue of what may
-- be overridden -- global, seeded, and the only thing that decides which keys exist, so a
-- typo in the admin UI cannot invent a term the portals never read.
-- ============================================================================
CREATE SCHEMA IF NOT EXISTS l10n;
GRANT USAGE ON SCHEMA l10n TO authenticated, service_role;

