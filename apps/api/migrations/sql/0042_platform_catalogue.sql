-- platform_links holds the mapping for entities with an identity of their own. Transactions
-- and valuations do not get link rows -- their provider key is a column on the fact itself
-- (`source_system` + `source_transaction_id`, and (account, date, source) for a valuation),
-- which IS the mapping, denormalised. A link table beside a multi-million-row fact would
-- double the write for no new information. This view papers over that difference so a
-- reader asks one question.
-- ============================================================================
CREATE VIEW platform.entity_links AS
  SELECT tenant_id, entity_type, entity_id, provider, external_id, link_type, updated_at
  FROM platform.platform_links
  UNION ALL
  SELECT tenant_id, 'transaction', id, source_system, source_transaction_id, 'primary', updated_at
  FROM platform.transactions
  UNION ALL
  SELECT tenant_id, 'valuation', id, source_system,
         account_id || ':' || to_char(as_of_date, 'YYYY-MM-DD'), 'primary', updated_at
  FROM platform.valuations;

GRANT SELECT ON platform.entity_links TO authenticated, service_role;

SELECT audit.attach(ARRAY[
  'platform.products', 'platform.product_platforms', 'platform.models',
  'platform.model_versions', 'platform.model_allocations', 'platform.fee_packages',
  'platform.third_party_providers', 'platform.transfer_providers', 'l10n.overrides'
]);

GRANT USAGE ON ALL SEQUENCES IN SCHEMA platform TO authenticated, service_role;
