  published_by    uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT model_versions_unique UNIQUE (model_id, version)
);
CREATE INDEX model_versions_tenant_id_idx ON platform.model_versions (tenant_id);
CREATE INDEX model_versions_model_idx ON platform.model_versions (model_id, version DESC);

