-- The existing (model -> platform, platform_identifier) pairs move to the join 0031 added,
-- so nothing is lost when platform_id stops being the model's identity.
--
-- As service_role, for the reason 0023_flows_hardening spells out: the migrator is subject to
-- FORCE ROW LEVEL SECURITY and is NOT bypassrls, so with no request claims this SELECT sees
-- zero rows and the backfill silently copies nothing -- which is exactly what happened on the
-- first run of this migration. The migrator is a member of service_role (bootstrap/01-roles.sql),
-- so it can assume it; RESET ROLE hands the rest of the migration back to the owner.
SET LOCAL ROLE service_role;
INSERT INTO platform.model_platforms (tenant_id, model_id, platform_id, external_id)
SELECT m.tenant_id, m.id, m.platform_id, m.platform_identifier
FROM platform.models m
WHERE m.platform_id IS NOT NULL
ON CONFLICT (model_id, platform_id) DO NOTHING;
RESET ROLE;

-- ---------------------------------------------------------------------------
-- Allocation history. A model's allocations change together -- a rebalance is one event,
-- not n independent edits -- so a version is a snapshot with its own lines, and the
