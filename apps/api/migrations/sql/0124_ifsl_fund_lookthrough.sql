-- 0124_ifsl_fund_lookthrough: global, dated IFSL fund-composition snapshots.
--
-- The data is reference data, not a custodian feed and not tenant-owned. Tenancy enters only
-- when the API proves that the caller holds one of a fund's share-class ISINs.

CREATE SCHEMA IF NOT EXISTS lookthrough;
GRANT USAGE ON SCHEMA lookthrough TO authenticated, service_role;

CREATE TABLE lookthrough.funds (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  source text NOT NULL DEFAULT 'ifsl' CHECK (source = 'ifsl'),
  fund_code text NOT NULL,
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source, fund_code)
);

CREATE TABLE lookthrough.share_classes (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  fund_id bigint NOT NULL REFERENCES lookthrough.funds(id) ON DELETE CASCADE,
  class_code text NOT NULL,
  name text NOT NULL,
  isin text NOT NULL UNIQUE CHECK (isin = upper(isin)),
  sedol text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (fund_id, class_code)
);
CREATE INDEX lookthrough_share_classes_fund_idx ON lookthrough.share_classes (fund_id);

CREATE TABLE lookthrough.snapshots (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  fund_id bigint NOT NULL REFERENCES lookthrough.funds(id) ON DELETE CASCADE,
  as_of_date date NOT NULL,
  filename text NOT NULL,
  file_sha256 text NOT NULL UNIQUE CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
  imported_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  imported_at timestamptz NOT NULL DEFAULT now(),
  supersedes_id bigint REFERENCES lookthrough.snapshots(id) ON DELETE RESTRICT,
  position_count int NOT NULL CHECK (position_count > 0),
  share_class_count int NOT NULL CHECK (share_class_count > 0),
  coverage numeric(12,10) NOT NULL CHECK (coverage >= 0),
  UNIQUE (fund_id, as_of_date, file_sha256)
);
CREATE INDEX lookthrough_snapshots_fund_date_idx
  ON lookthrough.snapshots (fund_id, as_of_date DESC, imported_at DESC);

CREATE TABLE lookthrough.positions (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  snapshot_id bigint NOT NULL REFERENCES lookthrough.snapshots(id) ON DELETE CASCADE,
  ordinal int NOT NULL CHECK (ordinal > 0),
  isin text,
  sedol text,
  name text NOT NULL,
  long_name text,
  currency text,
  asset_group text,
  asset_class text NOT NULL,
  country_code text,
  country_name text,
  maturity_date date,
  quantity numeric(28,8),
  price numeric(28,8),
  book_cost numeric(28,4),
  market_value numeric(28,4) NOT NULL,
  weight numeric(14,12) NOT NULL,
  UNIQUE (snapshot_id, ordinal)
);
CREATE INDEX lookthrough_positions_snapshot_weight_idx
  ON lookthrough.positions (snapshot_id, weight DESC);
CREATE INDEX lookthrough_positions_isin_idx
  ON lookthrough.positions (isin) WHERE isin IS NOT NULL;

-- Global reference data is readable by logged-in principals. Mutations happen through the
-- operations-only API, whose admin session runs as service_role.
ALTER TABLE lookthrough.funds ENABLE ROW LEVEL SECURITY;
ALTER TABLE lookthrough.funds FORCE ROW LEVEL SECURITY;
CREATE POLICY lookthrough_funds_read ON lookthrough.funds FOR SELECT TO authenticated USING (true);

ALTER TABLE lookthrough.share_classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE lookthrough.share_classes FORCE ROW LEVEL SECURITY;
CREATE POLICY lookthrough_share_classes_read
  ON lookthrough.share_classes FOR SELECT TO authenticated USING (true);

ALTER TABLE lookthrough.snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE lookthrough.snapshots FORCE ROW LEVEL SECURITY;
CREATE POLICY lookthrough_snapshots_read
  ON lookthrough.snapshots FOR SELECT TO authenticated USING (true);

ALTER TABLE lookthrough.positions ENABLE ROW LEVEL SECURITY;
ALTER TABLE lookthrough.positions FORCE ROW LEVEL SECURITY;
CREATE POLICY lookthrough_positions_read
  ON lookthrough.positions FOR SELECT TO authenticated USING (true);

GRANT SELECT ON ALL TABLES IN SCHEMA lookthrough TO authenticated;
GRANT ALL ON ALL TABLES IN SCHEMA lookthrough TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA lookthrough TO service_role;

COMMENT ON SCHEMA lookthrough IS
  'Global dated fund-composition reference data; API access is gated by a visible held share-class ISIN.';
