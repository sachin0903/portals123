-- 0126_lookthrough_analytics: richer dated analytics from IFSL disclosure workbooks.

ALTER TABLE lookthrough.positions
  ADD COLUMN prior_price numeric(28,8),
  ADD COLUMN movement_percent numeric(18,12);

CREATE TABLE lookthrough.nav_history (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  snapshot_id bigint NOT NULL REFERENCES lookthrough.snapshots(id) ON DELETE CASCADE,
  date date NOT NULL,
  class_code text NOT NULL,
  class_name text,
  nav numeric(28,8) NOT NULL CHECK (nav > 0),
  units_outstanding numeric(28,8),
  fund_value numeric(28,4),
  UNIQUE (snapshot_id, date, class_code)
);
CREATE INDEX lookthrough_nav_history_snapshot_class_date_idx
  ON lookthrough.nav_history (snapshot_id, class_code, date);

CREATE TABLE lookthrough.cash_balances (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  snapshot_id bigint NOT NULL REFERENCES lookthrough.snapshots(id) ON DELETE CASCADE,
  ordinal int NOT NULL CHECK (ordinal > 0),
  currency text NOT NULL,
  name text NOT NULL,
  base_value numeric(28,4) NOT NULL,
  weight numeric(18,12) NOT NULL,
  UNIQUE (snapshot_id, ordinal)
);
CREATE INDEX lookthrough_cash_balances_snapshot_idx
  ON lookthrough.cash_balances (snapshot_id);

CREATE TABLE lookthrough.currency_contracts (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  snapshot_id bigint NOT NULL REFERENCES lookthrough.snapshots(id) ON DELETE CASCADE,
  ordinal int NOT NULL CHECK (ordinal > 0),
  share_class_code text,
  name text NOT NULL,
  currency text,
  delivery_date date,
  bought_sold text,
  amount numeric(28,4),
  current_value numeric(28,4),
  unrealised_gain_loss numeric(28,4),
  nav_impact numeric(18,12),
  long_short text,
  UNIQUE (snapshot_id, ordinal)
);
CREATE INDEX lookthrough_currency_contracts_snapshot_idx
  ON lookthrough.currency_contracts (snapshot_id);

ALTER TABLE lookthrough.nav_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE lookthrough.nav_history FORCE ROW LEVEL SECURITY;
CREATE POLICY lookthrough_nav_history_read
  ON lookthrough.nav_history FOR SELECT TO authenticated USING (true);

ALTER TABLE lookthrough.cash_balances ENABLE ROW LEVEL SECURITY;
ALTER TABLE lookthrough.cash_balances FORCE ROW LEVEL SECURITY;
CREATE POLICY lookthrough_cash_balances_read
  ON lookthrough.cash_balances FOR SELECT TO authenticated USING (true);

ALTER TABLE lookthrough.currency_contracts ENABLE ROW LEVEL SECURITY;
ALTER TABLE lookthrough.currency_contracts FORCE ROW LEVEL SECURITY;
CREATE POLICY lookthrough_currency_contracts_read
  ON lookthrough.currency_contracts FOR SELECT TO authenticated USING (true);

GRANT SELECT ON lookthrough.nav_history, lookthrough.cash_balances,
  lookthrough.currency_contracts TO authenticated;
GRANT ALL ON lookthrough.nav_history, lookthrough.cash_balances,
  lookthrough.currency_contracts TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA lookthrough TO service_role;
