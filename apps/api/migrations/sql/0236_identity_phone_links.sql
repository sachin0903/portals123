-- 0236_identity_phone_links -- a one-time link that lets the client take their identity
-- photos on a phone, without signing in there.
--
-- The desktop is where the client is signed in. The phone is where the camera is. The link
-- carries the photos and nothing else: one step, one try, and then it is finished.
--
-- `code_hash` is the short link. Opening it spends the code and mints `token_hash`, the
-- session the phone page keeps in a cookie. The row holds neither secret, only SHA-256s,
-- and asking for a new link (or withdrawing this one) nulls both and sets `spent_at`, so a
-- code that has been replaced cannot be opened and a session that has been replaced cannot
-- upload. The window is `expires_at`, set when the link is made.

SET LOCAL lock_timeout = '5s';

CREATE TABLE auth.identity_phone_links (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  case_id int NOT NULL REFERENCES flows.cases(id) ON DELETE CASCADE,
  step_key text NOT NULL,
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  -- The person who asked for the link, while they were signed in. A photo taken on the
  -- phone is still their act, so the trail names them and not the phone.
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  code_hash text UNIQUE,
  token_hash text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  redeemed_at timestamptz,
  spent_at timestamptz,
  CONSTRAINT identity_phone_links_contact_tenant_fk
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE,
  -- A live link holds exactly one credential: the code until it is opened, the session after.
  CONSTRAINT identity_phone_links_one_credential CHECK (
    spent_at IS NOT NULL
    OR (code_hash IS NOT NULL AND token_hash IS NULL)
    OR (code_hash IS NULL AND token_hash IS NOT NULL)
  )
);

CREATE INDEX identity_phone_links_code_idx ON auth.identity_phone_links (code_hash)
  WHERE code_hash IS NOT NULL AND spent_at IS NULL;

CREATE INDEX identity_phone_links_token_idx ON auth.identity_phone_links (token_hash)
  WHERE token_hash IS NOT NULL AND spent_at IS NULL;

CREATE INDEX identity_phone_links_step_idx
  ON auth.identity_phone_links (tenant_id, case_id, step_key, contact_id)
  WHERE spent_at IS NULL;

COMMENT ON TABLE auth.identity_phone_links IS
  'A one-time link for taking the identity photos on a phone. The code is spent by opening '
  'it; the session it mints can upload those photos until the photos are sent or the window '
  'ends. Hashes only — the code and the session token are never stored.';
COMMENT ON COLUMN auth.identity_phone_links.code_hash IS
  'SHA-256 of the short code in the link. Nulled when the link is opened, or when it is '
  'withdrawn, so the code cannot be used twice.';
COMMENT ON COLUMN auth.identity_phone_links.token_hash IS
  'SHA-256 of the session token minted when the code is opened. Nulled when the link is '
  'withdrawn. Null until then: opening the link is what creates the token.';

ALTER TABLE auth.identity_phone_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth.identity_phone_links FORCE ROW LEVEL SECURITY;

-- No policy for `authenticated`. The row is a credential, and the only reader is the API
-- acting as service_role, which bypasses RLS. A signed-in session has no business selecting
-- it: the desktop is given the link once, in the response that made it, and never again.
GRANT ALL ON auth.identity_phone_links TO service_role;
GRANT USAGE, SELECT ON SEQUENCE auth.identity_phone_links_id_seq TO service_role;

CREATE TRIGGER audit_row AFTER INSERT OR DELETE OR UPDATE ON auth.identity_phone_links
  FOR EACH ROW EXECUTE FUNCTION audit.record();

-- The row trigger copies the new row onto the activity trail. These two columns are hashes
-- of the link's secrets, and a hash of a secret stays off that trail on the same principle
-- as key_hash. The function is the one from 0211, with those two names added to the redact
-- list; nothing else about it changes.
CREATE OR REPLACE FUNCTION audit.record() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'audit', 'auth', 'pg_catalog' AS $fn$
DECLARE
  v_new     jsonb := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
  v_old     jsonb := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
  v_subject jsonb := COALESCE(v_new, v_old);
  -- never copy secrets / opaque pointers into the trail (key_hash is a hash, not the
  -- secret, but it stays out of logs on principle; credentials_ref points at a vault).
  v_redact  text[] := ARRAY['key_hash', 'credentials_ref', 'workos_api_key_ct', 'cookie_password_ct', 'secret_access_key_ct', 'password_ct', 'secret_ct',
    -- derived, not data: 0211's generated search text restates columns already in the row.
    '_search',
    -- hashes of the identity-photo link (0233). The code and the session token are never
    -- stored; their hashes are not a thing the activity trail needs either.
    'code_hash', 'token_hash'];
  v_entity  bigint;
  v_tenant  int;
  v_detail  jsonb;
  k         text;
BEGIN
  -- entity_id only when the PK is integer-shaped; uuid/composite PKs live in detail.
  BEGIN v_entity := (v_subject ->> 'id')::bigint; EXCEPTION WHEN others THEN v_entity := NULL; END;

  -- Stamp the AFFECTED row's tenant (correct for cross-tenant admin writes); fall back
  -- to the actor's tenant for tables that carry no tenant_id (e.g. auth.*), which now also
  -- covers an unattributed aml.* row whose tenant_id is NULL.
  BEGIN
    v_tenant := COALESCE(NULLIF(v_subject ->> 'tenant_id', '')::int, auth.tenant_id());
  EXCEPTION WHEN others THEN v_tenant := auth.tenant_id();
  END;

  v_new := v_new - v_redact;
  v_old := v_old - v_redact;

  IF TG_OP = 'UPDATE' THEN
    v_detail := '{}'::jsonb;   -- only the columns that actually changed (redacted ones excluded)
    FOR k IN SELECT jsonb_object_keys(v_new) LOOP
      IF v_new -> k IS DISTINCT FROM v_old -> k THEN
        v_detail := v_detail || jsonb_build_object(k, jsonb_build_object('old', v_old -> k, 'new', v_new -> k));
      END IF;
    END LOOP;
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'changed', v_detail);
  ELSIF TG_OP = 'INSERT' THEN
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'row', v_new);
  ELSE
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'row', v_old);
  END IF;

  INSERT INTO audit.log (tenant_id, user_id, action, entity_type, entity_id, detail)
  VALUES (
    v_tenant,
    auth.uid(),
    TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME || '.' || lower(TG_OP),
    TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME,
    v_entity,
    v_detail
  );
  RETURN NULL;  -- AFTER trigger: return value is ignored
END;
$fn$;

ALTER FUNCTION audit.record() OWNER TO service_role;
