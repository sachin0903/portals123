-- ============================================================================
-- 0050_flow_ai.sql -- THE TWO SWITCHES AND THE METER for the flow engine's AI
-- gates (`classify`, `draft_message`; app/flows/ai.py, app/flows/ai_usage.py).
--
-- The governing rule, which every column below follows from: AI ROUTES AND
-- DRAFTS. IT NEVER DECIDES AND IT NEVER SENDS. A classification lands in case
-- memory for a BRANCH to decide on; a draft lands on a TASK for a person to
-- send. Nothing here records a determination, because nothing here makes one.
--
-- TWO TABLES, TWO JOBS:
--
--   flows.ai_tenants -- the per-firm switch. `ANTHROPIC_API_KEY` being set says
--     the DEPLOYMENT can call out; this says a given firm MAY. Both must be
--     true. It is deliberately not a firm self-service setting: enabling a firm
--     to send its clients' text to a third-party model is Graphene's decision as
--     platform provider, the same posture as AML adjudication (docs/aml.md), so
--     writes are service_role and the admin surface gates on tenants:write.
--     A firm READS its own row (it is entitled to know it is enabled and what
--     its ceiling is) -- hence the lineage read policy, unlike flows.case_memory
--     which has no `authenticated` grant at all.
--
--   flows.ai_usage -- the meter, and the reason the cost bound is real rather
--     than aspirational. The programme already carries one honest gap here
--     (Creditsafe spend from a tenant flow is unmetered -- ReviewHandler.
--     preflight is the seam), and a second one would be a pattern rather than an
--     oversight. Every call appends a row; the cap is a SUM over the current
--     calendar month checked BEFORE the next call.
--
-- WHAT flows.ai_usage DOES NOT HOLD, and this is the point of the table's shape:
-- the prompt and the completion. Not truncated, not hashed, not "just the first
-- 200 characters" -- absent. The input is a client's own words (a free-text
-- answer, an inbound message) and the output is copy about them; a metering
-- table that accumulated either would be a second, unpoliced copy of the client
-- record living outside crm. What IS recorded is that a call happened, which
-- model, how many tokens, how long it took, and which memory key it wrote --
-- everything an operator needs to answer "what is this costing and is it
-- working", and nothing they need to be careful with. A test pins the column
-- list so a later "just add the prompt for debugging" fails the suite.
--
-- Expand-only. No existing flow references either table, and a tenant with no
-- ai_tenants row is simply not enabled -- absence is the safe default, which is
-- why enablement is a row's existence plus its `enabled` flag rather than a
-- column defaulting to true on auth.tenants.
-- ============================================================================

-- Short ACCESS EXCLUSIVE locks below (CREATE TABLE, policies, triggers). Fail
-- fast rather than queue behind a long transaction -- the 0024 convention.
SET LOCAL lock_timeout = '5s';

-- ============================================================================
-- flows.ai_tenants -- the per-firm switch and its ceiling
-- ============================================================================
CREATE TABLE flows.ai_tenants (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

  -- The switch. A row that exists but is disabled is NOT the same as no row: it
  -- is a firm that was enabled and has been turned off, which is worth being
  -- able to see (and to turn back on without re-entering a ceiling).
  enabled boolean NOT NULL DEFAULT false,

  -- The cost bound, in tokens (input + output), per calendar month, per tenant.
  --
  -- WHY TOKENS AND NOT MONEY. Money needs a price list, and a price list in a
  -- table is a number that goes stale silently the day pricing changes -- and
  -- then the cap a firm was given is no longer the cap it has. Tokens are what
  -- the provider actually reports back on every call (`usage.input_tokens` /
  -- `usage.output_tokens`), so the meter measures the thing it is metering.
  -- Converting to money is a reporting concern and belongs where the price list
  -- is maintained, not in the enforcement path.
  --
  -- WHY A MONTH. It matches how the spend is billed and reviewed, and it makes
  -- "we are two thirds through the month and 90% through the budget" a sentence
  -- an operator can act on. A rolling window would be defensible; a calendar
  -- month is the one a finance conversation is already about.
  monthly_token_cap bigint NOT NULL DEFAULT 1000000
    CHECK (monthly_token_cap > 0),

  -- Free-text for the operator who enabled it: which firm asked, what for, who
  -- approved. Not read by any code path.
  notes text,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ai_tenants_tenant_key UNIQUE (tenant_id)
);

CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.ai_tenants
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Attached: "who enabled AI for this firm, when, and what ceiling did they set"
-- is a governance question, and the audit spine's before-value is what makes a
-- ceiling being quietly raised reconstructible.
SELECT audit.attach(ARRAY['flows.ai_tenants']);

ALTER TABLE flows.ai_tenants ENABLE ROW LEVEL SECURITY;
ALTER TABLE flows.ai_tenants FORCE ROW LEVEL SECURITY;

-- A firm sees its own switch and ceiling -- publish preflight runs on the firm's
-- own session and has to be able to tell an author "your firm is not enabled for
-- this" rather than failing at 3am. Deliberately `tenant_lineage()` and NOT
-- `contact_scope()`: this is staff configuration, and a client portal principal
-- has no business reading it (tenant_lineage returns '{}' for one, so the
-- omission alone locks the client portal out -- the 0037 pattern).
CREATE POLICY ai_tenants_read ON flows.ai_tenants FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON flows.ai_tenants TO authenticated;
GRANT ALL ON flows.ai_tenants TO service_role;

-- ============================================================================
-- flows.ai_usage -- the meter
-- ============================================================================
CREATE TABLE flows.ai_usage (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

  occurred_at timestamptz NOT NULL DEFAULT now(),

  -- Which gate. Closed set: the two action types that can reach a model. A third
  -- one arriving means this CHECK, the contract and the executor change together
  -- (the three-way change the whole programme is built on).
  purpose text NOT NULL CHECK (purpose IN ('classify', 'draft_message')),

  -- The model as CONFIGURED AT THE TIME OF THE CALL, not as configured now.
  -- `settings.ai_model` moves without a deploy of code by design, so a stored
  -- model id is the only way to read a month's spend back and know what produced
  -- it -- and the only way to notice that a classification changed behaviour
  -- because the model under it changed.
  model text NOT NULL,

  -- What the provider reported. The cap sums these two.
  input_tokens int NOT NULL DEFAULT 0 CHECK (input_tokens >= 0),
  output_tokens int NOT NULL DEFAULT 0 CHECK (output_tokens >= 0),

  -- Wall-clock for the call, so a timeout that is about to start parking cases
  -- is visible as a latency trend before it becomes an incident.
  latency_ms int NOT NULL DEFAULT 0 CHECK (latency_ms >= 0),

  -- How it went. `unknown` is NOT a failure -- it is the model answering outside
  -- the declared set and the engine turning that into the reserved label. It is
  -- recorded separately because a classify node whose unknown rate is climbing
  -- is a labelling problem an author can fix, and averaging it into `ok` would
  -- hide exactly that.
  outcome text NOT NULL CHECK (outcome IN ('ok', 'unknown', 'refused')),

  -- WHERE it happened, in the vocabulary the run log already uses. `case_id` is
  -- SET NULL rather than CASCADE on purpose: a deleted case must not delete the
  -- record that its journey spent a firm's budget.
  case_id int REFERENCES flows.cases(id) ON DELETE SET NULL,
  node_id text,
  automation_uid text,

  -- Which memory key a classify wrote (NULL for a draft, and for a classify that
  -- wrote nothing). The author's own word for the fact, which is what makes the
  -- row legible -- and is safe, because a key name is authored, not client data.
  memory_key text,

  created_at timestamptz NOT NULL DEFAULT now()

  -- DELIBERATELY ABSENT: prompt, completion, input, output, response, any column
  -- that could hold the text either side of the call. See the file header. If a
  -- future change needs one, it needs a conversation about a second copy of the
  -- client record, not a migration.
);

-- THE read: the current period's SUM for one tenant, on the hot path before every
-- call. tenant first, then time descending.
CREATE INDEX ai_usage_tenant_period_idx ON flows.ai_usage (tenant_id, occurred_at DESC);

-- ENGINE state, like flows.timers / flows.case_memory (0045/0046): written only by
-- the worker and the orchestrator on a service_role session. No `authenticated`
-- grant and no policy -- withholding the privilege beats an always-false policy.
-- A firm-facing "what has this cost us" surface ships as a permission-gated
-- endpoint reading on service_role, not by opening the table.
ALTER TABLE flows.ai_usage ENABLE ROW LEVEL SECURITY;
ALTER TABLE flows.ai_usage FORCE ROW LEVEL SECURITY;
GRANT SELECT, INSERT ON flows.ai_usage TO service_role;

-- Append-only by grant: no UPDATE, no DELETE, not even for service_role. A meter
-- that can be edited is not a meter, and this one is the only evidence of what a
-- firm's flows spent.
--
-- NOT audit-attached, unlike ai_tenants: this table IS the log. Attaching would
-- write a second row into the audit spine for every model call to record that a
-- metering row was inserted, which is noise standing in for information.

GRANT USAGE ON ALL SEQUENCES IN SCHEMA flows TO service_role;
