-- ============================================================================
-- 0132_platform_portfolios.sql -- the container BELOW an account, which four SEI write paths need.
--
-- `portfolioId` is a required field on `createCurrencyReceipt`, `createcashdisbursement`,
-- `currencytransfercreate` and every `PSM/model/assignment/*`. We have never been able to supply
-- one, so the SEI money paths are unreachable — and `docs/contributions.md` records the SEI
-- contribution leg as blocked on "the account's SEI account-number/portfolio-id links". The
-- account-number half has been solved since `platform.links` started carrying it; this is the
-- other half.
--
-- WHY A CHILD TABLE AND NOT A LINK ROW. `docs/api-integrations.md` §1187 already settled it:
-- "Today it is a `platform.links` row with `link_type='portfolio'`, which permits exactly one.
-- The fix is a real child table." An account genuinely has more than one — measured over the
-- 2026-03-27 drop: 1,045 accounts carry a single portfolio and **59 carry two**, always a Capital
-- portfolio plus an Income portfolio joined by `LINKED_PORTFOLIO_ID`. `platform.links`' key is
-- `(provider, entity_type, entity_id, link_type)`, so the second one has nowhere to go.
--
-- SEI ONLY, DELIBERATELY. Seccl has no sub-account container at all: its hierarchy is
-- firm -> node -> client -> clientProduct -> account -> position, and the same Capital/Income
-- split is modelled there by opening a SECOND ACCOUNT. `clientProduct` and `portfolioGroup` are
-- both ABOVE the account, not below it. Forcing Seccl into this table would invent rows, which is
-- the conformed contract's own rule (docs/platform-model.md §3): a provider publishes what it has.
--
-- NOT AN AGGREGATION CONTAINER, which is the other thing this is not. SEI's
-- `ACCOUNT_SUB_TYPE` 7 "Portfolio Aggregation" and its `GROUP_ID` and
-- `PORTFOLIO_AGGREGATION_SERVICE_ACCOUNT` columns are **0% populated** across the corpus. A
-- portfolio is an allocation bucket inside one account, and nothing rolls several accounts up.
-- ============================================================================

CREATE TABLE platform.portfolios (
  id                  bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid                 text UNIQUE DEFAULT public.nanoid(12),
  tenant_id           int  NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  account_id          int  NOT NULL REFERENCES platform.accounts(id) ON DELETE CASCADE,
  provider            text NOT NULL,
  -- The custodian's own id — SEI's PORTFOLIO_ID. This is the value the vendor's API takes.
  external_id         text NOT NULL,
  name                text,
  -- Canonical, from SEI's PORTFOLIO_TYPE (189 Capital / 190 Income). Free text rather than an
  -- enum: a second custodian with a sub-account concept would bring its own vocabulary, and an
  -- unmapped word must degrade to "unrecognised" rather than fail the merge.
  portfolio_type      text,
  -- SEI's PORTFOLIO_PURPOSE (10 members: Client Directed, Advisor Guided, Managed Account…).
  purpose             text,
  -- The one a write goes to when the caller names none. Capital, in SEI's terms.
  is_principal        boolean NOT NULL DEFAULT true,
  -- SEI's LINKED_PORTFOLIO_ID: an Income portfolio names the Capital one it belongs with. Present
  -- on exactly the Income rows, and it always resolves within the same account (999 of 999 report
  -- rows checked).
  --
  -- The VENDOR'S id, not a book FK, and that is deliberate. A self-referencing bigint would be
  -- permanently NULL: the merge inserts a provider's whole slice in one statement, so the Income
  -- row cannot see the Capital row's freshly-minted id, and resolving it would need a second pass
  -- `book_sink` has no hook for. The external id carries the same fact, needs no resolution, and
  -- is what a caller naming a portfolio to SEI would use anyway — a reader that wants the sibling
  -- row joins on (tenant_id, provider, external_id), which is already unique.
  linked_external_id  text,
  data                jsonb,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT portfolios_provider_key UNIQUE (tenant_id, provider, external_id)
);

CREATE INDEX portfolios_tenant_id_idx ON platform.portfolios(tenant_id);
CREATE INDEX portfolios_account_id_idx ON platform.portfolios(account_id);

-- Tenant containment, the 0035 discipline: a portfolio's account must live in the portfolio's own
-- firm, or a money instruction could name another firm's account.
ALTER TABLE platform.portfolios
  ADD CONSTRAINT portfolios_account_tenant_fkey
  FOREIGN KEY (account_id, tenant_id) REFERENCES platform.accounts(id, tenant_id);

-- NO `accounts.default_portfolio_id`. It was added here, on the reasoning that "a write path
-- needs one to reach for without ordering rules of its own", and it is a SECOND ANSWER to a
-- question the child already answers: `portfolios.is_principal` is published by both providers,
-- where a parent FK pointing back the other way had no writer anywhere — NULL on every row — so
-- its only reader (`platform_actions._portfolio_for`) COALESCEd straight past it into the
-- principal-portfolio subquery on every call. A nullable duplicate of a fact the pipeline
-- maintains is the shape `0130` dropped eight columns for.
COMMENT ON TABLE platform.portfolios IS
  'The container BELOW an account — SEI''s Capital/Income portfolios. Required by four SEI write '
  'paths (cash receipt, disbursement, transfer, model assignment). SEI only: Seccl has no '
  'sub-account concept and models the same split as a second account.';
COMMENT ON COLUMN platform.portfolios.external_id IS
  'The custodian''s own id (SEI PORTFOLIO_ID) — the exact value its API takes.';

CREATE TRIGGER set_updated_at BEFORE UPDATE ON platform.portfolios
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---- RLS ----
--
-- Mirrors platform.accounts: read-all staff see the firm's, a scoped adviser and a client see only
-- the portfolios of accounts in their own scope. Writes are the pipeline's (service_role), like
-- every other provider-derived table.
ALTER TABLE platform.portfolios ENABLE ROW LEVEL SECURITY;

CREATE POLICY portfolios_read ON platform.portfolios FOR SELECT TO authenticated USING (
  (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
  OR account_id = ANY (auth.account_scope())
);

GRANT SELECT ON platform.portfolios TO authenticated;
GRANT ALL ON platform.portfolios TO service_role;

ALTER TABLE platform.portfolios FORCE ROW LEVEL SECURITY;

-- `book_writer` is the provider pipeline's own login (0062): it reaches the merged relations and
-- nothing else, so a new merge target has to be granted explicitly.
GRANT SELECT, INSERT, UPDATE ON platform.portfolios TO book_writer;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA platform TO book_writer;

-- A portfolio is an address money can be sent to, so a change to one is worth recording.
SELECT audit.attach(ARRAY['platform.portfolios']);
