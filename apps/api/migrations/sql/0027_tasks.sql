-- ============================================================================
-- 0027_tasks.sql — standalone tasks: first-class action items (design: docs/tasks.md).
--
-- A task is a tenant-scoped "somebody must do this": polymorphic assignee (staff user / staff
-- role / client contact), optional polymorphic subject (contact/account/execution/document),
-- provenance (source_kind/source_ref), and an open → done/cancelled lifecycle. Tasks stand
-- alone — they are not flow steps and not document requests — but flow-step transitions raise
-- them via the outbox (phase 2), and "action needed" anywhere is DERIVED from open tasks, never
-- a stored flag.
--
-- Also extends the claims contract: auth.resolve_claims now mints 'role_ids' (the login's
-- active membership roles for the resolved portal) + the auth.role_ids() reader, so the "mine"
-- filter for role-assigned tasks needs zero auth.* queries per row (the 0001 invariant).
--
-- NOTE on ordering: this file is 0027 but revision-chains from 0022_documents_activity_scope —
-- the filename sequence and the Alembic chain diverged after 0026 (two branches merged); the
-- down_revision chain is authoritative.
-- ============================================================================

CREATE SCHEMA tasks;
GRANT USAGE ON SCHEMA tasks TO authenticated, service_role;

CREATE TABLE tasks.tasks (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                            -- 'tsk_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

  -- What the task is about (optional): mirrors flows.cases' polymorphic subject. subject_id is
  -- text because subjects span namespaces (crm.contacts ints, flows.executions uids,
  -- documents.documents uuids); the service layer validates the pair — deliberately no FK.
  subject_type text CHECK (subject_type IN ('contact', 'account', 'execution', 'document')),
  subject_id text,
  CONSTRAINT tasks_subject_pair CHECK ((subject_type IS NULL) = (subject_id IS NULL)),

  -- What raised it (provenance + the idempotency handle for automated producers).
  source_kind text NOT NULL DEFAULT 'manual'
    CHECK (source_kind IN ('manual', 'flow', 'document', 'system')),
  source_ref text,                                     -- e.g. 'fex_abc:step_kyc:7:failed'

  -- Who must act. The CHECK forbids cross-kind contamination but allows the matching column to
  -- go NULL: the user/role FKs are ON DELETE SET NULL, so a deleted role orphans its tasks
  -- (visible in "All", absent from "Mine") instead of blocking the delete or losing the row.
  -- Creation-time NOT NULL is enforced by the service layer.
  assignee_kind text NOT NULL CHECK (assignee_kind IN ('user', 'role', 'contact')),
  assignee_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  assignee_role_id int REFERENCES auth.roles(id) ON DELETE SET NULL,
  assignee_contact_id int REFERENCES crm.contacts(id) ON DELETE CASCADE,
  CONSTRAINT tasks_one_assignee CHECK (
    (assignee_kind = 'user'    AND assignee_role_id IS NULL AND assignee_contact_id IS NULL) OR
    (assignee_kind = 'role'    AND assignee_user_id IS NULL AND assignee_contact_id IS NULL) OR
    (assignee_kind = 'contact' AND assignee_user_id IS NULL AND assignee_role_id  IS NULL)
  ),

  -- category is a label only — fulfilment is always "a human marks it done". Structured
  -- fulfilment (forms/uploads/signatures) is the document-requests engine's job, not a task's.
  category text NOT NULL DEFAULT 'generic'
    CHECK (category IN ('review', 'acknowledge', 'upload', 'follow_up', 'generic')),
  title text NOT NULL,
  description text,
  due_date date,
  priority text NOT NULL DEFAULT 'normal' CHECK (priority IN ('low', 'normal', 'high')),

  status text NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'in_progress', 'done', 'cancelled')),

  created_by uuid REFERENCES auth.users(id),           -- NULL = system/flow-raised
  completed_by uuid REFERENCES auth.users(id),
  completed_at timestamptz,
  completion_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX tasks_tenant_status_idx ON tasks.tasks(tenant_id, status);
CREATE INDEX tasks_assignee_user_idx ON tasks.tasks(assignee_user_id)
  WHERE assignee_user_id IS NOT NULL;
CREATE INDEX tasks_assignee_role_idx ON tasks.tasks(assignee_role_id)
  WHERE assignee_role_id IS NOT NULL;
CREATE INDEX tasks_assignee_contact_idx ON tasks.tasks(assignee_contact_id)
  WHERE assignee_contact_id IS NOT NULL;
CREATE INDEX tasks_subject_idx ON tasks.tasks(subject_type, subject_id)
  WHERE subject_type IS NOT NULL;

-- Idempotency: an automated source may only ever raise ONE task per source_ref. Retried outbox
-- deliveries / re-fired handlers collapse here (ON CONFLICT in the service), so the delivery
-- pipeline needs no dedupe of its own.
CREATE UNIQUE INDEX tasks_source_ref_key ON tasks.tasks(tenant_id, source_kind, source_ref)
  WHERE source_kind <> 'manual' AND source_ref IS NOT NULL;

-- RLS: staff read/write within the tenant lineage; a client sees + completes ONLY tasks
-- assigned to their own contact scope. service_role (the phase-2 dispatcher) bypasses.
ALTER TABLE tasks.tasks ENABLE ROW LEVEL SECURITY;
CREATE POLICY tasks_read ON tasks.tasks FOR SELECT TO authenticated
  USING (
    tenant_id = ANY (auth.tenant_lineage())
    OR assignee_contact_id = ANY (auth.contact_scope())
  );
CREATE POLICY tasks_write ON tasks.tasks FOR ALL TO authenticated
  USING (
    tenant_id = ANY (auth.tenant_lineage())
    OR assignee_contact_id = ANY (auth.contact_scope())
  )
  WITH CHECK (
    tenant_id = ANY (auth.tenant_lineage())
    OR assignee_contact_id = ANY (auth.contact_scope())
  );
GRANT SELECT, INSERT, UPDATE ON tasks.tasks TO authenticated;  -- no DELETE: cancel, don't erase
GRANT ALL ON tasks.tasks TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA tasks TO authenticated, service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON tasks.tasks
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
SELECT audit.attach(ARRAY['tasks.tasks']);
ALTER TABLE tasks.tasks FORCE ROW LEVEL SECURITY;

-- ============================================================================
-- Claims: 'role_ids' — the roles this login actively holds for the resolved portal.
-- Read by the "mine" filter for role-assigned tasks. Same pre-resolved-claims discipline as
-- contact_ids: policies and queries read the claim, never auth.* tables, per row.
-- ============================================================================

CREATE OR REPLACE FUNCTION auth.role_ids() RETURNS int[] LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN auth.jwt() ? 'role_ids'
    THEN ARRAY(SELECT jsonb_array_elements_text(auth.jwt() -> 'role_ids')::int)
    ELSE '{}'::int[] END $$;

-- The 0004_portal_scope body + v_role_ids. Everything else is unchanged.
CREATE OR REPLACE FUNCTION auth.resolve_claims(p_workos_user_id text, p_workos_org_id text)
  RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = 'auth' AS $fn$
DECLARE
  v_user_uuid   uuid;
  v_tenant_id   int;
  v_tenant_ids  int[];
  v_portal      text;
  v_contact_ids int[];
  v_account_ids int[];
  v_role_ids    int[];
BEGIN
  SELECT id, tenant_id INTO v_user_uuid, v_tenant_id FROM auth.users
    WHERE workos_user_id = p_workos_user_id AND deleted_at IS NULL;

  IF v_tenant_id IS NULL THEN
    SELECT id INTO v_tenant_id FROM auth.tenants
      WHERE workos_organisation_id = p_workos_org_id;
  END IF;

  IF v_tenant_id IS NOT NULL THEN
    SELECT COALESCE(array_agg(id), '{}'::int[]) INTO v_tenant_ids
      FROM auth.tenants WHERE v_tenant_id = ANY(lineage);
  ELSE
    v_tenant_ids := '{}'::int[];
  END IF;

  -- Classify the active org -> portal (project-per-tenant: org = portal). Unknown/unmatched
  -- defaults to 'platform' (a staff context); the client portal is matched explicitly so it
  -- can never be widened. Operations goes through the admin (service_role) path, not RLS.
  SELECT CASE
           WHEN p_workos_org_id = te.client_portal_org_id THEN 'client'
           WHEN p_workos_org_id = te.operations_org_id     THEN 'operations'
           ELSE 'platform'
         END
    INTO v_portal
    FROM auth.tenant_environments te
    WHERE te.tenant_id = v_tenant_id
    ORDER BY te.id
    LIMIT 1;
  v_portal := COALESCE(v_portal, 'platform');

  -- Client scope. In the client portal: ONLY the parties this login is linked to
  -- (crm.contact_users) -- never an adviser book. Elsewhere (staff): the login's own links
  -- PLUS its assigned book (crm.client_advisers).
  IF v_user_uuid IS NOT NULL THEN
    IF v_portal = 'client' THEN
      SELECT COALESCE(array_agg(DISTINCT contact_id), '{}'::int[]) INTO v_contact_ids
        FROM crm.contact_users WHERE user_id = v_user_uuid;
    ELSE
      SELECT COALESCE(array_agg(DISTINCT cid), '{}'::int[]) INTO v_contact_ids FROM (
        SELECT contact_id AS cid FROM crm.contact_users   WHERE user_id = v_user_uuid
        UNION
        SELECT contact_id AS cid FROM crm.client_advisers WHERE adviser_id = v_user_uuid
      ) s;
    END IF;
  ELSE
    v_contact_ids := '{}'::int[];
  END IF;

  IF array_length(v_contact_ids, 1) IS NOT NULL THEN
    SELECT COALESCE(array_agg(DISTINCT aid), '{}'::int[]) INTO v_account_ids FROM (
      SELECT id AS aid FROM platform.accounts WHERE contact_id = ANY(v_contact_ids)
      UNION
      SELECT account_id AS aid FROM crm.account_contacts
        WHERE contact_id = ANY(v_contact_ids) AND account_id IS NOT NULL
    ) s;
  ELSE
    v_account_ids := '{}'::int[];
  END IF;

  -- Roles this login actively holds for the resolved portal (drives role-assigned task
  -- filtering). Fail-closed empty; array-shaped even though today's memberships carry one
  -- role per (user, tenant, portal).
  IF v_user_uuid IS NOT NULL AND v_tenant_id IS NOT NULL THEN
    SELECT COALESCE(array_agg(DISTINCT role_id), '{}'::int[]) INTO v_role_ids
      FROM auth.organisation_memberships
      WHERE user_id = v_user_uuid AND tenant_id = v_tenant_id AND portal = v_portal
        AND status = 'active' AND role_id IS NOT NULL;
  ELSE
    v_role_ids := '{}'::int[];
  END IF;

  RETURN jsonb_build_object(
    'user_uuid',   v_user_uuid,
    'tenant_id',   v_tenant_id,
    'tenant_ids',  to_jsonb(v_tenant_ids),
    'portal',      v_portal,
    'contact_ids', to_jsonb(v_contact_ids),
    'account_ids', to_jsonb(v_account_ids),
    'role_ids',    to_jsonb(v_role_ids)
  );
END;
$fn$;

GRANT EXECUTE ON FUNCTION auth.resolve_claims(text, text) TO authenticated, service_role;
ALTER FUNCTION auth.resolve_claims(text, text) OWNER TO service_role;
GRANT EXECUTE ON FUNCTION auth.role_ids() TO authenticated, service_role;
