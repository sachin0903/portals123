-- 0250_staff_notes -- a member of staff's own checklist, kept beside the book on the dashboard.
--
-- The notes an adviser keeps for themselves: "chase the SIPP transfer", "call Joan". They are
-- PERSONAL -- one person's, readable and writable by that person alone -- and they are the
-- firm's data in the sense every other row here is: tenant-scoped, so a firm's departure takes
-- its people's notes with it, and never visible across the boundary. They were a browser-local
-- list first; a list that does not follow its owner to the next machine was the defect.
--
-- Not a task (tasks.tasks): a task has an assignee, a subject and a lifecycle other people can
-- see. A note is a line of text with a tick, and nobody else is ever meant to read it. Keeping
-- the two apart is what lets a note be as cheap to write as a thought.

SET LOCAL lock_timeout = '5s';

CREATE TABLE platform.staff_notes (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE DEFAULT public.nanoid(12),
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  body text NOT NULL,
  done boolean NOT NULL DEFAULT false,
  -- The order the owner keeps them in. New notes go to the end (max + 1 at insert).
  position int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT staff_notes_body_present CHECK (btrim(body) <> '')
);

CREATE INDEX staff_notes_owner_idx ON platform.staff_notes (tenant_id, user_id, position, id);

COMMENT ON TABLE platform.staff_notes IS
  'A member of staff''s own checklist, shown on their dashboard. Readable and writable by the '
  'owner alone; tenant-scoped like every other row.';
COMMENT ON COLUMN platform.staff_notes.position IS
  'The owner''s order. Appended at max + 1; not required to be dense.';

ALTER TABLE platform.staff_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.staff_notes FORCE ROW LEVEL SECURITY;

-- The owner, and nobody else -- not the firm's administrators, not the auditor. There is no
-- firm-wide read of a colleague's private list, so no permission branch here.
CREATE POLICY staff_notes_own ON platform.staff_notes
  FOR ALL TO authenticated
  USING (tenant_id = auth.tenant_id() AND user_id = auth.uid())
  WITH CHECK (tenant_id = auth.tenant_id() AND user_id = auth.uid());

GRANT SELECT, INSERT, UPDATE, DELETE ON platform.staff_notes TO authenticated;
GRANT ALL ON platform.staff_notes TO service_role;
GRANT USAGE, SELECT ON SEQUENCE platform.staff_notes_id_seq TO authenticated, service_role;
