-- ============================================================================
-- 0043_automations.sql -- the automation plane: armed triggers, the durable
-- consumer position, delivery idempotency, and the per-tenant kill switch.
--
-- Flows v3 gives the engine EVENT TRIGGERS. An "automation" is one armed rule:
-- when <trigger> happens and <conditions> hold, either START A FLOW or PERFORM
-- ONE ACTION. Those are the same shape and -- crucially -- share ONE precedence
-- order per tenant, because the consumer's contract is Crisp's
-- first-satisfiable-wins: exactly one automation fires per (event, tenant). Two
-- tables would mean two orders and no coherent answer to "which one won", so
-- there is ONE table with a nullable `flow_id` and a nullable `action`, and a
-- CHECK that exactly one is set.
--
-- The cross-language source of truth for trigger keys, condition operators,
-- caps and safety defaults is
-- pkgs/ui/src/lib/components/book/journeys/flow-contract.json. The API container
-- ships without pkgs/ui, so app/flows/triggers.py mirrors what Python needs and
-- tests/test_flow_contract.py pins the mirror to the JSON (the
-- app/branding.py::default_pages precedent).
--
-- Consumer shape (app/flows/automation.py, driven by the worker's automations
-- loop): tail audit.actions by `id > cursor` -- 0041 was designed for exactly
-- this consumer -- resolve candidate automations, evaluate entry conditions,
-- apply the safety guards, dispatch. At-least-once delivery is made safe by
-- flows.automation_deliveries' unique (automation_id, event_key).
--
-- Expand-only. Nothing here changes existing behaviour: with no rows in
-- flows.automations the loop is a cursor advancing over a stream nobody is
-- listening to.
-- ============================================================================

-- Policy/constraint changes below take short ACCESS EXCLUSIVE locks. Fail fast
-- rather than queue behind a long transaction (the 0024 convention).
SET LOCAL lock_timeout = '5s';

-- ---- flows.automations -- ONE armed automation (flow-start OR action) --------
CREATE TABLE flows.automations (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                       -- 'aut_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  name text NOT NULL,

  -- The FRIENDLY key from the contract's trigger registry (e.g.
  -- 'client.document_uploaded'), never the raw event type: authors see a curated
  -- menu, not the audit.actions firehose, and the key -> event mapping can be
  -- re-pointed when a route is renamed without rewriting every firm's rows.
  -- Deliberately NOT a CHECK constraint or an enum: the registry lives in the
  -- contract JSON and is pinned by tests, and a DB enum would need a migration
  -- per trigger added. Unknown keys are refused at write time by the API and
  -- skipped (loudly) by the consumer.
  trigger_key text NOT NULL,

  -- Entry conditions, evaluated by app/flows/conditions.py. NULL means
  -- unconditional. Authored shape is the contract's condition grammar.
  conditions jsonb,

  -- EXACTLY ONE of these two is set (see automations_target_check):
  --  * flow_id -- start a case of this flow (this wave; the existing engine).
  --  * action  -- { "type": <contract actionType>, "config": {...} }, run by the
  --               rule-tier executor registered as the 'action' dispatch target.
  flow_id int REFERENCES flows.flows(id) ON DELETE CASCADE,
  action jsonb,

  -- Target-specific parameters that are not the action itself. For a flow start:
  -- platform_id (which platform the synthesised application belongs to), and any
  -- `data` seeded onto the execution.
  config jsonb NOT NULL DEFAULT '{}'::jsonb,

  -- The total order. Lower fires first; (priority, id) is the tiebreak, so the
  -- order is total even when two rows share a priority -- deliberately NOT a
  -- UNIQUE (tenant_id, priority): a unique priority turns every drag-reorder in
  -- the builder into a renumbering transaction, and determinism is what the
  -- first-satisfiable-wins rule actually needs, not distinctness.
  priority int NOT NULL DEFAULT 100,

  enabled boolean NOT NULL DEFAULT true,

  -- Re-arm window: the same automation does not re-fire for the same SUBJECT
  -- inside this many minutes. NULL means the contract default
  -- (safety.defaultRearmMinutes).
  rearm_minutes int CHECK (rearm_minutes IS NULL OR rearm_minutes >= 0),

  -- For trigger_key entries whose source is 'schedule':
  --   { "cron": "0 9 * * 1-5", "timezone": "Europe/London" }
  -- The expression is the SAME 5-field subset app/cron.py already parses for the
  -- interlace model schedules (*, n, lists, a-b, */n, a-b/n) -- reused rather than
  -- inventing a second dialect for the builder's picker. Evaluated by the worker's
  -- schedule pass against the firm's LOCAL wall clock
  -- (flows.automation_settings.timezone unless overridden here).
  schedule jsonb,

  -- THE self-trigger opt-in. Our action stream emits an event for everything an
  -- automation does, so automations feeding themselves is the DEFAULT failure
  -- mode, not an edge case (contract: safety.automationEventsTriggerByDefault =
  -- false). An automation-sourced event never fires this automation unless this
  -- is explicitly true -- and even then the chain-depth cap still applies.
  allow_automation_source boolean NOT NULL DEFAULT false,

  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT automations_target_check CHECK ((flow_id IS NULL) <> (action IS NULL)),
  CONSTRAINT automations_action_shape_check
    CHECK (action IS NULL OR jsonb_typeof(action) = 'object'),
  CONSTRAINT automations_tenant_name_key UNIQUE (tenant_id, name)
);

-- THE consumer hot path: "enabled automations for tenant X on trigger key K, in
-- priority order". Partial on `enabled` because a disabled automation is never a
-- candidate, and the include-order (priority, id) matches the ORDER BY exactly so
-- the match is an index-only range scan per event.
CREATE INDEX automations_hot_idx
  ON flows.automations (tenant_id, trigger_key, priority, id) WHERE enabled;
-- The schedule pass sweeps every armed schedule across all tenants once a minute;
-- this keeps that from being a seq scan of the whole table.
CREATE INDEX automations_scheduled_idx
  ON flows.automations (tenant_id, priority, id) WHERE enabled AND schedule IS NOT NULL;
CREATE INDEX automations_flow_id_idx ON flows.automations (flow_id) WHERE flow_id IS NOT NULL;

-- ---- flows.automation_cursor -- the durable consumer position(s) -------------
-- One row per consumer (today: 'action_stream'). Keyed by name rather than a
-- singleton so a second consumer -- a replay, a shadow reader during a rollout --
-- can hold its own position without fighting the live one.
CREATE TABLE flows.automation_cursor (
  consumer text PRIMARY KEY,
  -- The highest audit.actions.id consumed. No FK: audit.actions is a stream that
  -- may be pruned, and a cursor pointing past a pruned row must stay valid.
  position bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ---- flows.automation_deliveries -- idempotency + observability -------------
-- What makes at-least-once redelivery SAFE: (automation_id, event_key) is unique,
-- so replaying the same event cannot start a second case. It is also the answer
-- to "why didn't my automation fire?" -- every considered candidate lands a row
-- with its outcome, not just the ones that ran.
CREATE TABLE flows.automation_deliveries (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  automation_id int NOT NULL REFERENCES flows.automations(id) ON DELETE CASCADE,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

  -- The originating audit.actions row, for tracing. Nullable (a scheduled firing
  -- has no event) and deliberately un-FK'd, same reason as the cursor.
  event_id bigint,
  -- THE idempotency key. 'action:<audit.actions.id>' or 'schedule:<iso slot>' --
  -- one column rather than a nullable event_id in the unique constraint, because
  -- in Postgres NULLs are distinct and a nullable key would dedupe nothing on the
  -- scheduled path.
  event_key text NOT NULL,

  -- What the firing was ABOUT, for the re-arm window ("don't re-fire for the same
  -- client inside 24h") and for the console.
  subject_kind text,
  subject_id text,
  -- The case whose lifetime the per-case trigger budget is counted over.
  case_uid text,

  outcome text NOT NULL CHECK (outcome IN (
    'dispatched',          -- it ran
    'deferred',            -- rate/concurrency overflow: it WILL run (see retry_after)
    'skipped_conditions',  -- entry conditions did not hold
    'skipped_rearm',       -- inside the re-arm window for this subject
    'skipped_paused',      -- tenant (or the global switch) is paused
    'skipped_automation',  -- automation-sourced event, no allow_automation_source
    'budget_exhausted',    -- per-case trigger budget spent (ops task raised)
    'depth_exceeded',      -- chain depth cap hit (ops task raised)
    'failed'               -- the target raised; dead-lettered here
  )),
  detail text,
  error text,

  -- How deep in an automation->event->automation chain this firing sits. 0 for a
  -- human-sourced event; capped at safety.maxChainDepth.
  chain_depth int NOT NULL DEFAULT 0,

  -- Deferral bookkeeping. Overflow is DEFERRED, NEVER DROPPED (contract
  -- safety.$comment_rates), so a deferred row is a durable retry record: the
  -- evaluated context is snapshotted so the retry needs nothing from the original
  -- event, which may by then be behind the cursor.
  attempts int NOT NULL DEFAULT 0,
  retry_after timestamptz,
  context jsonb NOT NULL DEFAULT '{}'::jsonb,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT automation_deliveries_once UNIQUE (automation_id, event_key)
);

-- The deferral queue: tiny, and swept every pass.
CREATE INDEX automation_deliveries_deferred_idx
  ON flows.automation_deliveries (retry_after) WHERE outcome = 'deferred';
-- The re-arm lookup: "has THIS automation already fired for THIS subject
-- recently?" -- one index-only backwards scan per candidate.
CREATE INDEX automation_deliveries_rearm_idx
  ON flows.automation_deliveries (automation_id, subject_kind, subject_id, created_at DESC)
  WHERE outcome = 'dispatched';
-- The per-tenant rate window and the per-case budget count.
CREATE INDEX automation_deliveries_rate_idx
  ON flows.automation_deliveries (tenant_id, created_at DESC) WHERE outcome = 'dispatched';
CREATE INDEX automation_deliveries_case_idx
  ON flows.automation_deliveries (case_uid) WHERE case_uid IS NOT NULL;

-- ---- flows.automation_settings -- per-tenant kill switch + overrides ---------
CREATE TABLE flows.automation_settings (
  tenant_id int PRIMARY KEY REFERENCES auth.tenants(id) ON DELETE CASCADE,

  -- THE kill switch. A firm admin pauses their own firm (automations:pause);
  -- Graphene operations pauses globally (automations:global_pause, an
  -- operations-portal slug so rbac.OPERATIONS_ONLY keeps it off every firm role).
  -- Checked before every dispatch. Pausing is itself an audited action: this
  -- table is on audit.attach below, so the change lands in audit.log with its
  -- before/after, and the API endpoint that sets it emits its own action event.
  paused boolean NOT NULL DEFAULT false,
  paused_reason text,

  -- The firm's timezone, for scheduled triggers. THIS is the tenant timezone
  -- source: auth.tenants has no timezone column and nothing else in the estate
  -- carries one, so rather than invent a column on the identity table for a
  -- feature that is the only consumer, it lives with the other automation
  -- settings. Default Europe/London -- a UK financial-services platform, and a
  -- scheduled annual-review chaser must not fire at 01:00 local because the
  -- server thinks in UTC. Validated against pg_timezone_names on write.
  timezone text NOT NULL DEFAULT 'Europe/London',

  -- Per-tenant overrides of the contract's safety defaults. NULL means "use the
  -- contract default" (app/flows/triggers.py::SAFETY); every override is clamped
  -- to a hard ceiling in Python so a settings row can never disarm a guard.
  executions_per_minute int CHECK (executions_per_minute IS NULL OR executions_per_minute > 0),
  flow_concurrency int CHECK (flow_concurrency IS NULL OR flow_concurrency > 0),
  case_trigger_budget int CHECK (case_trigger_budget IS NULL OR case_trigger_budget > 0),
  max_chain_depth int CHECK (max_chain_depth IS NULL OR max_chain_depth >= 0),
  default_rearm_minutes int CHECK (default_rearm_minutes IS NULL OR default_rearm_minutes >= 0),

  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ---- tasks.tasks.source_kind -- automations raise tasks of their own ---------
-- Expand-only CHECK widening (0027 declared manual|flow|document|system). A
-- safety-cap escalation is not a flow task and not a manual one: it is raised BY
-- the automation plane, in Graphene's operations tenant, and an operator filtering
-- their inbox by provenance should see it as exactly that.
ALTER TABLE tasks.tasks DROP CONSTRAINT IF EXISTS tasks_source_kind_check;
ALTER TABLE tasks.tasks ADD CONSTRAINT tasks_source_kind_check
  CHECK (source_kind IN ('manual', 'flow', 'document', 'system', 'automation'));

-- ---- flows.cases.initiation -- an automation-started journey says so ---------
-- Expand-only CHECK widening. Nothing switches on the value (the TS side types it
-- `string | null`), but "who started this journey" is exactly the question a
-- compliance reader asks of a case that no human opened.
ALTER TABLE flows.cases DROP CONSTRAINT IF EXISTS cases_initiation_check;
ALTER TABLE flows.cases ADD CONSTRAINT cases_initiation_check
  CHECK (initiation IN ('adviser', 'client', 'automation'));

-- ============================================================================
-- ROW LEVEL SECURITY
-- ============================================================================
-- automations: staff-authored CONFIG, exactly like flow definitions -- authenticated
-- read + write within the tenant lineage. The permission gate (automations:read /
-- automations:write) is enforced at the endpoint; RLS is the tenant boundary.
ALTER TABLE flows.automations ENABLE ROW LEVEL SECURITY;
CREATE POLICY automations_read ON flows.automations FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY automations_write ON flows.automations FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.automations TO authenticated;
GRANT ALL ON flows.automations TO service_role;

-- automation_settings: same posture -- a firm reads and (permission-gated) pauses
-- its own row.
ALTER TABLE flows.automation_settings ENABLE ROW LEVEL SECURITY;
CREATE POLICY automation_settings_read ON flows.automation_settings FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY automation_settings_write ON flows.automation_settings FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.automation_settings TO authenticated;
GRANT ALL ON flows.automation_settings TO service_role;

-- deliveries + cursor: machine state written only by the worker. service_role
-- ONLY, with no `authenticated` grant and no policy at all -- withholding the
-- privilege beats an always-false policy (the aml.operator_secrets / flows.outbox
-- precedent). A firm-facing "why didn't it fire?" surface ships later as a
-- permission-gated endpoint reading on service_role, the way audit.actions does.
ALTER TABLE flows.automation_deliveries ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.automation_deliveries TO service_role;

ALTER TABLE flows.automation_cursor ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON flows.automation_cursor TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA flows TO authenticated, service_role;

-- ============================================================================
-- updated_at triggers, audit attach, FORCE RLS (bind even the migrator owner).
-- ============================================================================
CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.automations
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.automation_settings
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.automation_deliveries
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Audit the CONFIG, not the machine state. An automation that emails clients and
-- the switch that pauses it are compliance-relevant changes ("who armed this, and
-- who turned the safety off?"). Deliveries and the cursor are high-volume
-- consumer bookkeeping -- attaching audit.record() there would write a second
-- audit.log row per event considered, the same reasoning that keeps audit.actions
-- itself off the attach list.
SELECT audit.attach(ARRAY['flows.automations', 'flows.automation_settings']);

ALTER TABLE flows.automations FORCE ROW LEVEL SECURITY;
ALTER TABLE flows.automation_settings FORCE ROW LEVEL SECURITY;
ALTER TABLE flows.automation_deliveries FORCE ROW LEVEL SECURITY;
ALTER TABLE flows.automation_cursor FORCE ROW LEVEL SECURITY;

-- NO cursor row is seeded here, deliberately. The consumer creates its own on
-- first run, at the CURRENT head of audit.actions
-- (app/flows/automation.py::_ensure_cursor) -- the app/events.py pattern, and the
-- only one that works: this table is service_role-only with no policy at all, and
-- FORCE binds the table owner too, so a migrator-role INSERT is refused (it has no
-- BYPASSRLS; service_role does). Seeding at the head rather than 0 is the point of
-- doing it at all: a cursor starting at 0 would replay every historical action
-- event the moment a firm arms its first automation -- months of "a client
-- uploaded a document" firing at once. Automations act on what happens NEXT.
