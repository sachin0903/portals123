-- 0007_document_requests: adviser-requested client uploads.
--
-- An adviser asks a client to upload a document; the client fulfils it by uploading (which creates
-- the document + links both parties). TEMP binding: user_id -> auth.users (the client), to reconcile
-- with crm.contacts later, like the other collab tables. See docs/document-management.md.

CREATE TABLE documents.upload_requests (
    id                    int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid                   text        NOT NULL UNIQUE,
    tenant_id             int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    user_id               uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,  -- TEMP: -> crm.contacts
    requested_by          uuid        NOT NULL REFERENCES auth.users(id),
    fulfilled_document_id uuid        REFERENCES documents.documents(id) ON DELETE SET NULL,
    category              text        NOT NULL,
    description           text,
    due_date              date,
    status                text        NOT NULL DEFAULT 'pending'
                              CHECK (status IN ('pending', 'fulfilled', 'cancelled')),
    fulfilled_at          timestamptz,
    created_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX upload_requests_tenant_idx ON documents.upload_requests(tenant_id);
CREATE INDEX upload_requests_user_idx ON documents.upload_requests(user_id, status);

-- Staff manage requests for their tenant; the target client may READ their own (to see + fulfil).
-- Clients never write requests directly (they fulfil via the service_role endpoint), so writes are
-- staff-only.
ALTER TABLE documents.upload_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents.upload_requests FORCE ROW LEVEL SECURITY;
CREATE POLICY upload_requests_read ON documents.upload_requests FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()) OR user_id = auth.uid());
CREATE POLICY upload_requests_write ON documents.upload_requests FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON documents.upload_requests TO authenticated;
GRANT ALL ON documents.upload_requests TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA documents TO authenticated, service_role;

SELECT audit.attach(ARRAY['documents.upload_requests']);
