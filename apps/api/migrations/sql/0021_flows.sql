-- ============================================================================
-- 0021_flows.sql -- the generic, config-driven FLOW engine. A "flow" is a firm-authored,
-- versioned process definition (ordered steps + declarative milestones); a "case" is a running
-- instance of a published flow for a subject contact. Onboarding is simply the first published
-- flow (docs/... ; seeded on the model tenant) -- there is no onboarding-specific schema.
--
-- The engine derives a case's status from its steps' completion. Each step is realised as a
-- concrete artifact we already have: a documents.request_item (fill_form / accept_terms / upload)
-- or a platform.accounts row (setup_account). flows.case_steps is the join from process -> artifact,
-- which is why documents.requests is left untouched.
--
-- Also widens documents.shares to carry 'flow_case' links, so the ONE tokenised access-link
-- primitive (0017) covers the public, pre-auth entry into a case.
--
-- RLS: flow DEFINITIONS (flows / flow_versions) are staff-authored -> authenticated read+write
-- scoped to the tenant lineage (like documents.forms). CASE state (cases / case_steps) is
-- service_role-write only -- every mutation goes through the engine on a service_role session
-- (firm_session for staff/client, system_transaction for the public path), because instantiating
-- a setup_account step writes platform.accounts/crm.applications (themselves service_role-only).
-- Reads: staff see their tenant; a client sees a case whose subject contact is in their scope.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS flows;
GRANT USAGE ON SCHEMA flows TO anon, authenticated, service_role;

-- ---- flows.flows -- a flow DEFINITION header (tenant-scoped, authorable, versioned) ----
CREATE TABLE flows.flows (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                       -- 'flw_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  code text NOT NULL,                             -- unique per tenant (e.g. 'onboarding')
  name text NOT NULL,
  description text,
  entity text,                                    -- free-form hint (e.g. 'onboarding')
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  current_published_version_id int,               -- FK added after flow_versions exists
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flows_tenant_code_key UNIQUE (tenant_id, code)
);
CREATE INDEX flows_tenant_id_idx ON flows.flows(tenant_id);

-- ---- flows.flow_versions -- the authored definition JSON (steps + milestones) ----
CREATE TABLE flows.flow_versions (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                       -- 'flv_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  flow_id int NOT NULL REFERENCES flows.flows(id) ON DELETE CASCADE,
  version int NOT NULL,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  -- { "steps": [ { id, type, title, required, assignee, visibility, config } ],
  --   "milestones": [ { status, reached_when: [stepId] } ] }
  -- Validated on write by app/flows/definitions.py (strict allowlist; structured, no free code).
  definition jsonb NOT NULL DEFAULT '{"steps": [], "milestones": []}'::jsonb,
  published_at timestamptz,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flow_versions_flow_version_key UNIQUE (flow_id, version)
);
CREATE INDEX flow_versions_flow_id_idx ON flows.flow_versions(flow_id);
CREATE INDEX flow_versions_tenant_id_idx ON flows.flow_versions(tenant_id);

ALTER TABLE flows.flows ADD CONSTRAINT flows_current_version_fkey
  FOREIGN KEY (current_published_version_id) REFERENCES flows.flow_versions(id) ON DELETE SET NULL;

-- ---- flows.cases -- a running INSTANCE of a published flow version ----
CREATE TABLE flows.cases (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,                       -- 'cas_...'
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  flow_id int NOT NULL REFERENCES flows.flows(id) ON DELETE CASCADE,
  flow_version_id int NOT NULL REFERENCES flows.flow_versions(id) ON DELETE RESTRICT,
  subject_contact_id int REFERENCES crm.contacts(id) ON DELETE SET NULL,  -- the client party
  -- Engine-owned free-form status: draft -> in_progress -> submitted -> completed (+ cancelled and
  -- any firm-authored milestone). Not a DB enum -- the vocabulary lives in the flow definition.
  status text NOT NULL DEFAULT 'draft',
  initiation text CHECK (initiation IN ('adviser', 'client')),
  -- Polymorphic domain link: an onboarding case points at a crm.applications row
  -- (resource_type = 'application', resource_id = applications.id). No FK (polymorphic).
  resource_type text,
  resource_id int,
  data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  cancelled_at timestamptz
);
CREATE INDEX cases_tenant_id_idx ON flows.cases(tenant_id);
CREATE INDEX cases_flow_id_idx ON flows.cases(flow_id);
CREATE INDEX cases_subject_contact_idx ON flows.cases(subject_contact_id) WHERE subject_contact_id IS NOT NULL;
CREATE INDEX cases_status_idx ON flows.cases(tenant_id, status);

-- ---- flows.case_steps -- per-instance step state; the join from process to the artifact ----
CREATE TABLE flows.case_steps (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  case_id int NOT NULL REFERENCES flows.cases(id) ON DELETE CASCADE,
  step_id text NOT NULL,                          -- the step id from the flow definition
  step_type text NOT NULL,
  title text,
  assignee text NOT NULL DEFAULT 'client' CHECK (assignee IN ('client', 'staff')),
  required boolean NOT NULL DEFAULT true,
  sort_order int NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'fulfilled', 'skipped', 'cancelled')),
  -- The concrete artifact this step is realised as (by type; at most one set):
  request_item_id int REFERENCES documents.request_items(id) ON DELETE SET NULL,
  account_id int REFERENCES platform.accounts(id) ON DELETE SET NULL,
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT case_steps_case_step_key UNIQUE (case_id, step_id)
);
CREATE INDEX case_steps_case_id_idx ON flows.case_steps(case_id);
CREATE INDEX case_steps_tenant_id_idx ON flows.case_steps(tenant_id);
CREATE INDEX case_steps_request_item_idx ON flows.case_steps(request_item_id) WHERE request_item_id IS NOT NULL;

-- ============================================================================
-- Widen the tokenised access-link primitive (0017) to cover flow cases.
-- ============================================================================
ALTER TABLE documents.shares DROP CONSTRAINT IF EXISTS shares_resource_type_check;
ALTER TABLE documents.shares ADD CONSTRAINT shares_resource_type_check
  CHECK (resource_type IN ('document', 'file', 'flow_case'));

-- ============================================================================
-- ROW LEVEL SECURITY
-- ============================================================================
-- flows / flow_versions: staff-authored, authenticated read+write within the tenant lineage.
ALTER TABLE flows.flows ENABLE ROW LEVEL SECURITY;
CREATE POLICY flows_read ON flows.flows FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY flows_write ON flows.flows FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.flows TO authenticated;
GRANT ALL ON flows.flows TO service_role;

ALTER TABLE flows.flow_versions ENABLE ROW LEVEL SECURITY;
CREATE POLICY flow_versions_read ON flows.flow_versions FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY flow_versions_write ON flows.flow_versions FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.flow_versions TO authenticated;
GRANT ALL ON flows.flow_versions TO service_role;

-- cases / case_steps: READ for staff (tenant lineage) and for the client whose contact is the
-- subject; WRITE is service_role only (the engine runs on service_role sessions).
ALTER TABLE flows.cases ENABLE ROW LEVEL SECURITY;
CREATE POLICY cases_read ON flows.cases FOR SELECT TO authenticated
  USING (
    tenant_id = ANY (auth.tenant_lineage())
    OR subject_contact_id = ANY (auth.contact_scope())
  );
GRANT SELECT ON flows.cases TO authenticated;
GRANT ALL ON flows.cases TO service_role;

ALTER TABLE flows.case_steps ENABLE ROW LEVEL SECURITY;
CREATE POLICY case_steps_read ON flows.case_steps FOR SELECT TO authenticated
  USING (
    tenant_id = ANY (auth.tenant_lineage())
    OR EXISTS (
      SELECT 1 FROM flows.cases c
      WHERE c.id = flows.case_steps.case_id
        AND c.subject_contact_id = ANY (auth.contact_scope())
    )
  );
GRANT SELECT ON flows.case_steps TO authenticated;
GRANT ALL ON flows.case_steps TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA flows TO authenticated, service_role;

-- ============================================================================
-- updated_at + audit triggers, then FORCE RLS (bind even the migrator owner).
-- ============================================================================
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.table_schema, c.table_name
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.column_name = 'updated_at'
      AND t.table_type = 'BASE TABLE'
      AND c.table_schema = 'flows'
  LOOP
    EXECUTE format(
      'CREATE TRIGGER set_updated_at BEFORE UPDATE ON %I.%I '
      'FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()',
      r.table_schema, r.table_name);
  END LOOP;
END $$;

-- Onboarding is regulated: the flow definitions, the case lifecycle and each step's completion
-- are all compliance-relevant, so audit every write.
SELECT audit.attach(ARRAY[
  'flows.flows', 'flows.flow_versions', 'flows.cases', 'flows.case_steps'
]);

DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT schemaname, tablename FROM pg_tables WHERE schemaname = 'flows'
  LOOP
    EXECUTE format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY', r.schemaname, r.tablename);
  END LOOP;
END $$;
