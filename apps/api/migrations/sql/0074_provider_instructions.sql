-- 0074_provider_instructions: the outbound instruction queue (docs/provider-routing.md §6a).
--
-- One row per INTENT -- a thing we mean to happen at a custodian -- against the many rows per
-- ATTEMPT that `audit.api_log` already holds. The two are deliberately separate: folding the log
-- in here would lose the failed attempts (a queue row is mutable and keeps only the last
-- outcome), and folding this into the log would make evidence mutable, which the append-only
-- grant on `audit.api_log` exists to prevent. They join with no new column -- an attempt stamps
-- `api_log.entity_type = 'provider_instruction'` and `entity_id` = this row's id.
--
-- A TABLE QUEUE, not PGMQ, for the reason `0013_render_jobs` already recorded: the same
-- claim / ack / retry / dead-letter contract without a PG18 extension, on the plain postgres:18
-- image. Roughly ten queues in this codebase now share the idiom.

CREATE TABLE platform.provider_instructions (
    id             bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tenant_id      int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

    -- What we mean to happen. `operation` is the vendor's own action name, which is what
    -- `platform_actions` validates the payload against and what the retry class is declared on.
    provider       text        NOT NULL,
    operation      text        NOT NULL,
    payload        jsonb       NOT NULL DEFAULT '{}'::jsonb,

    -- What it is about, loosely, so a human reading the queue can tell one row from another
    -- without parsing the payload. No FK: the subject may live in any schema, and a delivery
    -- record must not fail to write because a row was later removed.
    subject_type   text,
    subject_id     text,

    -- IDEMPOTENCY. Derived from the subject (a contribution uid, a contact id) and never random,
    -- so enqueuing the same intent twice collapses here rather than depending on every caller
    -- remembering to check. This protects against a double ENQUEUE; it cannot protect against an
    -- attempt that reached the vendor and lost the answer coming back -- that is what the
    -- `guarded` retry class re-checks, and it is the exact shape of the duplicate-contact bug.
    idempotency_key text       NOT NULL,

    -- How it may be retried, decided per vendor operation rather than per transport. DEFAULT
    -- 'manual' on purpose: an operation added without thinking about this must not become
    -- auto-retried, because the cost of guessing wrong runs one way only -- Morgan Lloyd has no
    -- delete, and a retried contribution reclaims relief from HMRC twice.
    retry_class    text        NOT NULL DEFAULT 'manual'
                               CHECK (retry_class IN ('safe', 'guarded', 'manual')),

    status         text        NOT NULL DEFAULT 'queued'
                               CHECK (status IN ('queued', 'processing', 'done',
                                                 'failed', 'dead_letter')),
    attempts       int         NOT NULL DEFAULT 0,
    max_attempts   int         NOT NULL DEFAULT 3,
    run_after      timestamptz NOT NULL DEFAULT now(),   -- visibility / retry backoff
    last_error     text,
    claimed_at     timestamptz,

    -- What came back, when the vendor minted something. For a `guarded` operation this is also
    -- the evidence that a retry must not send again.
    external_id    text,

    -- Who asked. Nullable: a flow or a schedule has no acting human, which is the whole reason
    -- those paths need a queue and the console's drawers do not.
    requested_by   uuid        REFERENCES auth.users(id) ON DELETE SET NULL,

    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    completed_at   timestamptz
);

-- The index that actually enforces idempotency. Scoped by tenant because two firms legitimately
-- hold the same subject id at different custodians.
CREATE UNIQUE INDEX provider_instructions_idempotency_idx
    ON platform.provider_instructions (tenant_id, provider, operation, idempotency_key);

-- The worker's hot path: the claimable set, oldest-ready first.
CREATE INDEX provider_instructions_claim_idx
    ON platform.provider_instructions (run_after) WHERE status = 'queued';
-- The operator's: everything parked, per firm.
CREATE INDEX provider_instructions_attention_idx
    ON platform.provider_instructions (tenant_id, created_at DESC)
    WHERE status IN ('failed', 'dead_letter');

COMMENT ON TABLE platform.provider_instructions IS
  'Outbound instruction queue: one row per INTENT to be delivered to a custodian, retried by '
  'class (safe/guarded/manual). audit.api_log holds one row per ATTEMPT and joins by '
  'entity_type=''provider_instruction''. See docs/provider-routing.md section 6a.';
COMMENT ON COLUMN platform.provider_instructions.retry_class IS
  'safe = idempotent by nature; guarded = a create whose landing we can check on platform.links '
  'before resending; manual = one attempt then park for a human. Defaults to manual.';

-- RLS: firm staff read their own tenant's queue (an adviser should be able to see that their
-- instruction is stuck); the worker runs as service_role. Deliberately NO insert or update for
-- `authenticated` -- enqueuing goes through the API, which validates the payload against the
-- vendor contract first, and a hand-written row would bypass that.
ALTER TABLE platform.provider_instructions ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.provider_instructions FORCE ROW LEVEL SECURITY;
CREATE POLICY provider_instructions_read ON platform.provider_instructions
    FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT ON platform.provider_instructions TO authenticated;
GRANT ALL ON platform.provider_instructions TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA platform TO service_role;
