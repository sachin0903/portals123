-- ============================================================================
-- 0038_aml_operator_credentials — AML phase 2: attributable writes, and making
-- unattributable Creditsafe profiles visible to Graphene operations.
--
-- Two changes, both prerequisites for the write paths:
--
-- 1. PER-OPERATOR CREDENTIALS. Reads run on a shared Creditsafe service account, but every
--    WRITE (open a profile, run a screen, decide a hit, change monitoring) must be attributed
--    to the acting Graphene operator, so Creditsafe's OWN audit trail names a real person
--    rather than "Graphene". That means replaying the operator's password to Creditsafe's
--    /authenticate to mint a per-user token — so the password cannot be hashed, only
--    encrypted, and it lives in a table no request-path role can read.
--
-- 2. NULLABLE tenant_id ON THE MIRROR. `aml.profiles.tenant_id` was NOT NULL and the sync
--    deliberately refuses to guess which firm a Creditsafe profile belongs to (a wrong guess
--    files one firm's screening in another firm's book, and RLS would then faithfully serve
--    it). The consequence was that an unmatched profile could not be stored AT ALL, so the
--    console could never show "here are the Creditsafe profiles we cannot tie to a client" —
--    which is the reconciliation gap the console exists to surface. Confirmed against the
--    live sandbox: all 13 profiles there match no contact, so the mirror stayed empty.
--    An unattributed profile now lands with tenant_id IS NULL and is visible to Graphene
--    operations only, until an operator links it to a client.
-- ============================================================================

-- ── 1. Per-operator Creditsafe credentials ─────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS aml.operator_credentials (
  id           int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id      uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  -- Creditsafe's unique per-user LOGIN NAME, which is not necessarily the email: when an email
  -- maps to several Creditsafe users, /authenticate rejects it with "Identity has multiple
  -- users, please specify a userid" and only the unique username works.
  cs_username  text NOT NULL,
  -- Set when the login above still maps to more than one Creditsafe user.
  cs_user_id   text,
  connected_at timestamptz NOT NULL DEFAULT now(),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE aml.operator_credentials ENABLE ROW LEVEL SECURITY;
ALTER TABLE aml.operator_credentials FORCE ROW LEVEL SECURITY;

-- An operator may see whether THEY are connected (the account page reads this); nobody may see
-- anybody else's. Writes go through service_role code so the credentials are verified against
-- Creditsafe before they are stored — a self-service INSERT could store a password that never
-- authenticates, and the failure would only surface mid-screen.
CREATE POLICY operator_credentials_read_own ON aml.operator_credentials
  FOR SELECT TO authenticated
  USING (user_id = auth.uid());

GRANT SELECT ON aml.operator_credentials TO authenticated;
GRANT ALL ON aml.operator_credentials TO service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON aml.operator_credentials
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- The secret half, split from the metadata above so the readable table stays readable.
CREATE TABLE IF NOT EXISTS aml.operator_secrets (
  user_id     uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  -- Fernet ciphertext (app/crypto.py, SECRETS_MASTER_KEY). This is the one credential in the
  -- system that CANNOT be hashed: it must be replayed verbatim to Creditsafe's /authenticate.
  password_ct text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE aml.operator_secrets ENABLE ROW LEVEL SECURITY;
ALTER TABLE aml.operator_secrets FORCE ROW LEVEL SECURITY;

-- Deliberately NO policy and NO grant to authenticated — not even an always-false policy.
-- Withholding the privilege is stronger than writing a policy that evaluates to false: the
-- role cannot so much as attempt the query. Same shape as storage.tenant_secrets (0027).
GRANT ALL ON aml.operator_secrets TO service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON aml.operator_secrets
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

GRANT USAGE ON ALL SEQUENCES IN SCHEMA aml TO authenticated, service_role;

-- ── 2. Unattributed mirror rows ────────────────────────────────────────────────────────────

ALTER TABLE aml.profiles ALTER COLUMN tenant_id DROP NOT NULL;
ALTER TABLE aml.searches ALTER COLUMN tenant_id DROP NOT NULL;
ALTER TABLE aml.hits     ALTER COLUMN tenant_id DROP NOT NULL;

-- Distinguish an operator's manual link from the sync's automatic name+DOB match, so a human
-- decision is auditable as one and a later sync pass never silently re-attributes it.
ALTER TABLE aml.profiles ADD COLUMN IF NOT EXISTS linked_by uuid
  REFERENCES auth.users(id) ON DELETE SET NULL;
ALTER TABLE aml.profiles ADD COLUMN IF NOT EXISTS linked_at timestamptz;

-- The read policies, restated. Two clauses, and the ABSENCE of a third is the point:
--
--   * an attributed row belongs to a firm and follows tenant lineage, exactly as before;
--   * an UNATTRIBUTED row (tenant_id IS NULL) belongs to no firm yet, so only Graphene
--     platform staff may read it. `auth.is_system()` is the `system` PERMISSION alone since
--     0034 — never a token's role name — so a firm cannot reach these by naming a role
--     "admin". The ops console itself reads through service_role + an `aml:read` check
--     (app/routers/aml.py), so this clause governs direct `authenticated` access only.
--
-- `auth.contact_scope()` remains ABSENT, as in 0037. That omission is the tipping-off control:
-- a client must never read their own sanctions/PEP/adverse-media position (POCA 2002 s.333A),
-- and auth.tenant_lineage() returns '{}' for a client-portal principal, so the lineage clause
-- alone locks the client portal out. tests/test_aml_rls.py asserts via pg_policies that no aml
-- policy mentions contact_scope. Do not add it here for symmetry with crm.kyc_checks.

DROP POLICY IF EXISTS profiles_read ON aml.profiles;
CREATE POLICY profiles_read ON aml.profiles FOR SELECT TO authenticated
  USING (
    (tenant_id IS NOT NULL AND tenant_id = ANY (auth.tenant_lineage()))
    OR (tenant_id IS NULL AND auth.is_system())
  );

DROP POLICY IF EXISTS searches_read ON aml.searches;
CREATE POLICY searches_read ON aml.searches FOR SELECT TO authenticated
  USING (
    (tenant_id IS NOT NULL AND tenant_id = ANY (auth.tenant_lineage()))
    OR (tenant_id IS NULL AND auth.is_system())
  );

DROP POLICY IF EXISTS hits_read ON aml.hits;
CREATE POLICY hits_read ON aml.hits FOR SELECT TO authenticated
  USING (
    (tenant_id IS NOT NULL AND tenant_id = ANY (auth.tenant_lineage()))
    OR (tenant_id IS NULL AND auth.is_system())
  );

-- The console's "unmatched" filter is the queue's most-acted-on view, and it is a small slice
-- of a table that grows with the whole book.
CREATE INDEX IF NOT EXISTS aml_profiles_unattributed_idx
  ON aml.profiles(id) WHERE tenant_id IS NULL;

-- ── 3. Keep the new secret out of the audit trail ──────────────────────────────────────────
-- audit.record() is reissued verbatim with one extra redact entry, per the 0027 convention:
-- migrations evolve shared functions and the SQL file is the reviewable artifact.

CREATE OR REPLACE FUNCTION audit.record() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = 'audit', 'auth', 'pg_catalog' AS $fn$
DECLARE
  v_new     jsonb := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
  v_old     jsonb := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
  v_subject jsonb := COALESCE(v_new, v_old);
  -- never copy secrets / opaque pointers into the trail (key_hash is a hash, not the
  -- secret, but it stays out of logs on principle; credentials_ref points at a vault).
  v_redact  text[] := ARRAY['key_hash', 'credentials_ref', 'workos_api_key_ct', 'cookie_password_ct', 'secret_access_key_ct', 'password_ct'];
  v_entity  bigint;
  v_tenant  int;
  v_detail  jsonb;
  k         text;
BEGIN
  -- entity_id only when the PK is integer-shaped; uuid/composite PKs live in detail.
  BEGIN v_entity := (v_subject ->> 'id')::bigint; EXCEPTION WHEN others THEN v_entity := NULL; END;

  -- Stamp the AFFECTED row's tenant (correct for cross-tenant admin writes); fall back
  -- to the actor's tenant for tables that carry no tenant_id (e.g. auth.*), which now also
  -- covers an unattributed aml.* row whose tenant_id is NULL.
  BEGIN
    v_tenant := COALESCE(NULLIF(v_subject ->> 'tenant_id', '')::int, auth.tenant_id());
  EXCEPTION WHEN others THEN v_tenant := auth.tenant_id();
  END;

  v_new := v_new - v_redact;
  v_old := v_old - v_redact;

  IF TG_OP = 'UPDATE' THEN
    v_detail := '{}'::jsonb;   -- only the columns that actually changed (redacted ones excluded)
    FOR k IN SELECT jsonb_object_keys(v_new) LOOP
      IF v_new -> k IS DISTINCT FROM v_old -> k THEN
        v_detail := v_detail || jsonb_build_object(k, jsonb_build_object('old', v_old -> k, 'new', v_new -> k));
      END IF;
    END LOOP;
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'changed', v_detail);
  ELSIF TG_OP = 'INSERT' THEN
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'row', v_new);
  ELSE
    v_detail := jsonb_build_object('id', v_subject -> 'id', 'row', v_old);
  END IF;

  INSERT INTO audit.log (tenant_id, user_id, action, entity_type, entity_id, detail)
  VALUES (
    v_tenant,
    auth.uid(),
    TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME || '.' || lower(TG_OP),
    TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME,
    v_entity,
    v_detail
  );
  RETURN NULL;  -- AFTER trigger: return value is ignored
END;
$fn$;

SELECT audit.attach(ARRAY[
  'aml.operator_credentials',
  'aml.operator_secrets'
]);
