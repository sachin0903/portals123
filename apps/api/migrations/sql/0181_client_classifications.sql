-- ============================================================================
-- 0181_client_classifications — named books of clients, not WorkOS roles.
--
-- A firm's client portal can carry several design sets. Those were assigned by
-- client-portal auth-profile roles, which is the wrong grain: advised vs D2C
-- (read-only vs self-serve money) is a book fact, and both books live in ONE
-- tenant. A classification is a tenant-owned label with optional match rules
-- (service type, AUM, contact type) and a pin on the contact. The branding
-- template binds to the classification slug. Design: docs/client-classifications.md.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE TABLE crm.client_classifications (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  name text NOT NULL
    CHECK (length(btrim(name)) BETWEEN 1 AND 40),
  slug text NOT NULL
    CHECK (slug ~ '^[a-z0-9-]{1,32}$'),
  sort_order int NOT NULL DEFAULT 0,
  is_default boolean NOT NULL DEFAULT false,
  -- Closed vocabulary of match predicates, validated in app/classifications.py.
  -- '{}' matches everyone (only useful as the default, or as a last-resort row).
  match jsonb NOT NULL DEFAULT '{}',
  -- Capability flags the portal and future money doors read. Unknown keys are
  -- dropped at the service layer so this cannot become a second settings dump.
  capabilities jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, slug),
  -- 0035: the contact pin is a COMPOSITE FK. A bare classification_id would
  -- let a row point at another firm's classification.
  UNIQUE (tenant_id, id)
);

CREATE INDEX client_classifications_tenant_idx
  ON crm.client_classifications(tenant_id, sort_order, id);

-- At most one default per tenant. Partial unique, so several non-defaults are fine.
CREATE UNIQUE INDEX client_classifications_one_default
  ON crm.client_classifications(tenant_id)
  WHERE is_default;

ALTER TABLE crm.client_classifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm.client_classifications FORCE ROW LEVEL SECURITY;

-- Helpers wrapped in scalar subqueries so the planner runs them once (gotchas).
-- Clients may READ the catalogue (auth.tenant_id() — 0177/0082): the hook
-- resolves their design set from it. They cannot WRITE. Match rules are
-- filtered out of the client-facing /mine payload in the service, not here.
CREATE POLICY client_classifications_read ON crm.client_classifications
  FOR SELECT TO authenticated
  USING (
    tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[])
    OR tenant_id = (SELECT auth.tenant_id())
  );
CREATE POLICY client_classifications_write ON crm.client_classifications
  FOR ALL TO authenticated
  USING (tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[]))
  WITH CHECK (tenant_id = ANY ((SELECT auth.tenant_lineage())::integer[]));

GRANT SELECT, INSERT, UPDATE, DELETE ON crm.client_classifications TO authenticated;
GRANT ALL ON crm.client_classifications TO service_role;
GRANT USAGE, SELECT ON SEQUENCE crm.client_classifications_id_seq TO authenticated, service_role;

-- Explicit pin. NULL = resolve from match rules / the default. SET NULL on
-- delete so removing a classification rematches rather than 500ing the contact.
ALTER TABLE crm.contacts
  ADD COLUMN classification_id int REFERENCES crm.client_classifications(id)
    ON DELETE SET NULL;

ALTER TABLE crm.contacts
  ADD CONSTRAINT contacts_classification_tenant_fkey
  FOREIGN KEY (tenant_id, classification_id)
  REFERENCES crm.client_classifications (tenant_id, id)
  ON DELETE SET NULL;
