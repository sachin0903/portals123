-- 0039_document_types: a per-tenant document-type tag registry.
--
-- documents.document_type is free text; this table is the tenant's set of KNOWN tags — the
-- suggestions shown in the upload/reclassify pickers and the pool auto-classify picks from. It is
-- open-ended, NOT an allowlist: uploading/reclassifying with a new tag registers it here on the fly
-- (app-side, see app/document_types.py::register_document_type), and a firm admin can rename/archive
-- tags in the manager (gated app-side by documents:admin; archiving hides a tag from suggestions
-- without blocking its use). Seeded with the common adviser doc types for existing + future tenants.
--
-- RLS: any staff in the tenant may READ + WRITE the registry (they classify/register on upload);
-- the write policy just pins the tenant. Clients never classify, so there is no client-scope
-- branch. Slugs are the stable key stored on documents.

CREATE TABLE documents.document_types (
    id          int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tenant_id   int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    slug        text        NOT NULL CHECK (slug ~ '^[a-z0-9_]+$' AND char_length(slug) <= 64),
    label       text        NOT NULL CHECK (char_length(label) BETWEEN 1 AND 128),
    sort_order  int         NOT NULL DEFAULT 0,
    archived    boolean     NOT NULL DEFAULT false,  -- soft-retire a type; keeps existing docs valid
    created_at  timestamptz NOT NULL DEFAULT now(),
    created_by  uuid        REFERENCES auth.users(id),
    CONSTRAINT document_types_tenant_slug_key UNIQUE (tenant_id, slug)
);
CREATE INDEX document_types_tenant_idx ON documents.document_types(tenant_id, sort_order);

ALTER TABLE documents.document_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents.document_types FORCE ROW LEVEL SECURITY;
CREATE POLICY document_types_read ON documents.document_types FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY document_types_write ON documents.document_types FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON documents.document_types TO authenticated;
GRANT ALL ON documents.document_types TO service_role;
-- Re-grant sequence USAGE so `authenticated` can use the new IDENTITY sequence (the 0005 blanket
-- grant only covered sequences that existed then).
GRANT USAGE ON ALL SEQUENCES IN SCHEMA documents TO authenticated, service_role;

-- The default vocabulary — the list the upload dialog hardcoded before this table existed.
-- Seed it for every EXISTING tenant, and (via the trigger below) for every future one, so a firm
-- always starts with a usable taxonomy it can then edit.
--
-- Run the backfill as service_role: migrations execute as `migrator`, which is subject to
-- FORCE ROW LEVEL SECURITY on auth.tenants and is NOT bypassrls (that attribute isn't inherited via
-- service_role membership), so a bare SELECT FROM auth.tenants would return zero rows and silently
-- seed nothing. SET LOCAL ROLE service_role activates its BYPASSRLS for this transaction (migrator
-- is a member), matching the 0023/0024 precedent; RESET ROLE returns to migrator for the DDL below.
SET LOCAL ROLE service_role;
INSERT INTO documents.document_types (tenant_id, slug, label, sort_order)
SELECT t.id, v.slug, v.label, v.sort_order
FROM auth.tenants t
CROSS JOIN (VALUES
    ('report', 'Report', 1),
    ('statement', 'Statement', 2),
    ('agreement', 'Agreement', 3),
    ('identity', 'Identity', 4),
    ('tax', 'Tax', 5),
    ('illustration', 'Illustration', 7),
    ('application', 'Application', 8),
    ('letter', 'Letter', 9)
) AS v(slug, label, sort_order)
ON CONFLICT (tenant_id, slug) DO NOTHING;
RESET ROLE;

-- Seed the same defaults for any tenant created later, so a new firm is never left with an empty
-- vocabulary. Runs as the tenant-creating role (SECURITY INVOKER) — every path that creates a
-- tenant (service_role via admin_session, migrator, the superuser in tests) can insert here; the
-- request role `authenticated` never creates tenants. Schema-qualified, idempotent via ON CONFLICT.
CREATE OR REPLACE FUNCTION documents.seed_default_document_types()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO documents.document_types (tenant_id, slug, label, sort_order)
    VALUES
        (NEW.id, 'report', 'Report', 1),
        (NEW.id, 'statement', 'Statement', 2),
        (NEW.id, 'agreement', 'Agreement', 3),
        (NEW.id, 'identity', 'Identity', 4),
        (NEW.id, 'tax', 'Tax', 5),
        (NEW.id, 'illustration', 'Illustration', 7),
        (NEW.id, 'application', 'Application', 8),
        (NEW.id, 'letter', 'Letter', 9)
    ON CONFLICT (tenant_id, slug) DO NOTHING;
    RETURN NEW;
END;
$$;
CREATE TRIGGER seed_document_types AFTER INSERT ON auth.tenants
    FOR EACH ROW EXECUTE FUNCTION documents.seed_default_document_types();
