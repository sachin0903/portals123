-- 0110_account_fee_packages — an account may carry several equal fee packages.
--
-- platform.accounts.fee_package_id represented one "primary" package. Fees are additive and no
-- package is primary, so the assignment is now a tenant-contained join. sort_order is presentation
-- order only. The old column remains for compatibility with older writers, but is no longer read
-- or written by the account-fee API.

SET LOCAL lock_timeout = '5s';

-- Composite foreign keys make tenant equality a schema invariant even for service_role writers.
-- platform.accounts already has accounts_tenant_id_key from 0035.
ALTER TABLE platform.fee_packages
  ADD CONSTRAINT fee_packages_tenant_id_key UNIQUE (tenant_id, id);

CREATE TABLE platform.account_fee_packages (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  account_id int NOT NULL REFERENCES platform.accounts(id) ON DELETE CASCADE,
  fee_package_id int NOT NULL REFERENCES platform.fee_packages(id) ON DELETE CASCADE,
  sort_order smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT account_fee_packages_unique UNIQUE (account_id, fee_package_id),
  CONSTRAINT account_fee_packages_sort_order_nonnegative CHECK (sort_order >= 0),
  CONSTRAINT account_fee_packages_account_tenant_fkey
    FOREIGN KEY (tenant_id, account_id)
    REFERENCES platform.accounts (tenant_id, id) ON DELETE CASCADE,
  CONSTRAINT account_fee_packages_fee_package_tenant_fkey
    FOREIGN KEY (tenant_id, fee_package_id)
    REFERENCES platform.fee_packages (tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX account_fee_packages_tenant_id_idx
  ON platform.account_fee_packages (tenant_id);
CREATE INDEX account_fee_packages_account_order_idx
  ON platform.account_fee_packages (account_id, sort_order, fee_package_id);
CREATE INDEX account_fee_packages_fee_package_id_idx
  ON platform.account_fee_packages (fee_package_id);

INSERT INTO platform.account_fee_packages (tenant_id, account_id, fee_package_id, sort_order)
SELECT a.tenant_id, a.id, a.fee_package_id, 0
  FROM platform.accounts a
 WHERE a.fee_package_id IS NOT NULL
ON CONFLICT (account_id, fee_package_id) DO NOTHING;

COMMENT ON COLUMN platform.accounts.fee_package_id IS
  'DEPRECATED compatibility column. New reads and writes use platform.account_fee_packages; '
  'there is deliberately no primary fee package.';
COMMENT ON TABLE platform.account_fee_packages IS
  'Equal, additive fee-package assignments for an account; sort_order is presentation only.';

ALTER TABLE platform.account_fee_packages ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.account_fee_packages FORCE ROW LEVEL SECURITY;
CREATE POLICY account_fee_packages_read ON platform.account_fee_packages
  FOR SELECT TO authenticated USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR account_id = ANY (auth.account_scope())
  );

GRANT SELECT ON platform.account_fee_packages TO authenticated;
GRANT ALL ON platform.account_fee_packages TO service_role;
GRANT USAGE, SELECT ON SEQUENCE platform.account_fee_packages_id_seq
  TO authenticated, service_role;
