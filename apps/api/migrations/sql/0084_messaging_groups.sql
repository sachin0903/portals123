-- ============================================================================
-- 0084_messaging_groups -- a staff-only saved shortcut to a set of clients
-- ("Direct messages" vs "Groups" in the platform inbox sidebar), NOT a new
-- kind of conversation.
--
-- Every client still has exactly one real conversation (messaging.conversations,
-- unchanged). Sending "to a group" fans out into each member's own conversation
-- via the existing send path (app/messaging.py::send_staff_message) — a group
-- has no messages, no attachments, and no conversation row of its own. The
-- platform inbox renders a MERGED view of the members' real conversations
-- for the adviser's convenience; each client only ever sees their own thread,
-- exactly as before this migration.
--
-- RLS is deliberately staff-only -- tenant_lineage() with NO contact_scope()
-- branch at all. A client must never see that they've been grouped with
-- other clients, or even that grouping exists — unlike messaging.conversations/
-- messages, which a client legitimately reads their own slice of, there is no
-- client-facing slice of this table to grant at all.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE TABLE messaging.groups (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (btrim(name) <> ''),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX groups_tenant_id_idx ON messaging.groups(tenant_id);

ALTER TABLE messaging.groups ENABLE ROW LEVEL SECURITY;
CREATE POLICY groups_staff_only ON messaging.groups FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON messaging.groups TO authenticated;
GRANT ALL ON messaging.groups TO service_role;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON messaging.groups
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE messaging.group_members (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
  group_id bigint NOT NULL REFERENCES messaging.groups(id) ON DELETE CASCADE,
  -- Composite link per 0035's invariant: a mis-tenanted contact_id would be
  -- readable through a same-tenant group otherwise.
  contact_id int NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
  CONSTRAINT group_members_contact_tenant_fkey
    FOREIGN KEY (tenant_id, contact_id) REFERENCES crm.contacts (tenant_id, id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT group_members_unique UNIQUE (group_id, contact_id)
);
CREATE INDEX group_members_group_id_idx ON messaging.group_members(group_id);
CREATE INDEX group_members_contact_id_idx ON messaging.group_members(contact_id);

ALTER TABLE messaging.group_members ENABLE ROW LEVEL SECURITY;
CREATE POLICY group_members_staff_only ON messaging.group_members FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON messaging.group_members TO authenticated;
GRANT ALL ON messaging.group_members TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA messaging TO authenticated, service_role;

SELECT audit.attach(ARRAY['messaging.groups', 'messaging.group_members']);
ALTER TABLE messaging.groups FORCE ROW LEVEL SECURITY;
ALTER TABLE messaging.group_members FORCE ROW LEVEL SECURITY;
