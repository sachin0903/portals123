-- ============================================================================
-- 0046_case_memory.sql -- CASE MEMORY: the handful of facts a journey carries.
--
-- Flows v3 Phase B makes a flow a graph, and a graph needs somewhere to keep the
-- values its branches test and its copy prints:
--
--   * variables injected when the journey starts (an automation's authored
--     context, an adviser's intake answers);
--   * values promoted out of a completed form by an AUTHORED mapping
--     (`fill_form.config.remember`) -- never the whole answer set: a fact-find
--     has hundreds of fields and memory is for the handful a later branch or
--     message needs;
--   * values written by an action node as a journey runs.
--
-- WHY A TABLE, and not `flows.cases.data -> 'memory'`. Three reasons, in order
-- of how much they hurt when ignored:
--
--   1. LOST UPDATES. Two step events settling on sibling instances of the same
--      case both read-modify-write the case's jsonb; the second one silently
--      discards the first's key. A per-key upsert cannot lose a write. (The
--      execution-wide advisory lock serialises recompute, but memory is also
--      written from `submit_step` before that lock is taken.)
--   2. AUDIT. `audit.attach` gives every write a row in the audit spine with
--      the before-value. "The client's journey branched to enhanced due
--      diligence because `memory.risk_band` said high -- who set that, and
--      when?" is a compliance question, and a jsonb patch on a case answers it
--      with a whole-object diff at best.
--   3. CAPS THAT BIND. A size cap on an opaque jsonb blob is a comment; here it
--      is a CHECK the database enforces on every write, whatever wrote it.
--
-- Values are JSON-safe scalars/containers only -- no code, no references. The
-- Python side (app/flows/memory.py) owns the per-case key count and total-size
-- caps, and this file owns the per-value one.
--
-- Expand-only: nothing reads this table for a legacy flow, and a v3 flow with no
-- authored memory never writes a row.
-- ============================================================================

-- Policy/constraint changes below take short ACCESS EXCLUSIVE locks. Fail fast
-- rather than queue behind a long transaction (the 0024 convention).
SET LOCAL lock_timeout = '5s';

CREATE TABLE flows.case_memory (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  tenant_id int NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,

  -- Memory belongs to a CASE, not an execution. A tiered onboarding fans one
  -- flow into a profile case per participant plus a case per account, and a
  -- branch resolves inside ONE of them -- "this applicant is offshore" is a
  -- fact about that applicant, and hoisting it to the execution would let one
  -- participant's answer decide another's route. Values that really are
  -- journey-wide are seeded into every case at start, which is the same thing
  -- said honestly.
  case_id int NOT NULL REFERENCES flows.cases(id) ON DELETE CASCADE,

  -- The authored name, WITHOUT the `memory.` prefix: a condition reads
  -- `memory.risk_band`, this column holds `risk_band`. Slug-shaped and dotless
  -- on purpose -- a dotted key would be ambiguous against the nested lookup the
  -- condition/interpolation resolvers do (`memory` -> `risk_band`).
  key text NOT NULL CHECK (key ~ '^[a-z0-9](?:[a-z0-9_]*[a-z0-9])?$'),

  -- The value itself as jsonb (a bare scalar is valid jsonb, so a string does
  -- not need a wrapper object). NOT NULL is the column; a JSON `null` value is
  -- allowed and means "the author set this to nothing", which conditions read
  -- as empty.
  value jsonb NOT NULL,

  -- WHERE the value came from. Not decoration: "an operator typed this at
  -- kickoff" and "a form answer was promoted" are different evidential weights
  -- when a firm is asked why a case went the way it did.
  source text NOT NULL DEFAULT 'engine'
    CHECK (source IN ('start', 'answers', 'action', 'engine')),
  -- The graph node that wrote it, when one did (an action node, or the step
  -- whose answers were promoted). NULL for values injected at start.
  node_id text,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  -- One value per name per case: writing `risk_band` twice UPDATES it. Memory
  -- is a variable, not a log -- the log is the audit spine.
  CONSTRAINT case_memory_case_key_key UNIQUE (case_id, key),

  -- The per-value ceiling. 4 KB is generous for the things memory is for (a
  -- band, a date, a reference, a short list) and far below what would make a
  -- branch evaluation or an interpolated email expensive. Enforced here as well
  -- as in Python because the Python cap is a promise and this one is a fact.
  CONSTRAINT case_memory_value_size CHECK (octet_length(value::text) <= 4096),
  CONSTRAINT case_memory_key_length CHECK (length(key) <= 64)
);

-- THE read: "every value this case carries", which is how the condition context
-- and the interpolation context are both built. Covered by the unique index on
-- (case_id, key) already, so no second index is added.

-- ============================================================================
-- ROW LEVEL SECURITY
-- ============================================================================
-- ENGINE state, exactly like flows.timers / flows.case_listeners (0045): written
-- only by the orchestrator and the worker on a service_role session. No
-- `authenticated` grant and no policy at all -- withholding the privilege beats
-- an always-false policy (the flows.outbox / aml.operator_secrets precedent).
--
-- A firm-facing "what does this journey know about my client?" surface ships as
-- a permission-gated endpoint reading on service_role, the way audit.actions is
-- read by GET /admin/audit/actions -- NOT by opening this table to
-- `authenticated`. Memory can hold anything an author promoted out of a
-- fact-find, so the read side deserves a deliberate permission rather than
-- inheriting the case's.
ALTER TABLE flows.case_memory ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON flows.case_memory TO service_role;

GRANT USAGE ON ALL SEQUENCES IN SCHEMA flows TO authenticated, service_role;

-- ============================================================================
-- updated_at trigger, audit attach, FORCE RLS (bind even the migrator owner).
-- ============================================================================
CREATE TRIGGER set_updated_at BEFORE UPDATE ON flows.case_memory
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Attached, for reason (2) in the header: a memory value is frequently the
-- reason a case took the route it did, and the audit spine's before-value is
-- what makes that reconstructible.
SELECT audit.attach(ARRAY['flows.case_memory']);

ALTER TABLE flows.case_memory FORCE ROW LEVEL SECURITY;

-- ============================================================================
-- flows.cases.initiation -- a journey started BY another journey says so.
-- ============================================================================
-- Expand-only CHECK widening, the same move 0043 made for 'automation'. A
-- `start_flow` node is a tail call from one journey into another, and recording
-- it as 'automation' would conflate "a rule started this" with "the client's
-- onboarding handed over to the review journey" -- two different answers to the
-- compliance reader's question. Nothing switches on the value.
ALTER TABLE flows.cases DROP CONSTRAINT IF EXISTS cases_initiation_check;
ALTER TABLE flows.cases ADD CONSTRAINT cases_initiation_check
  CHECK (initiation IN ('adviser', 'client', 'automation', 'flow'));
