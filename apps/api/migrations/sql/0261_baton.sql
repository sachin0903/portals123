-- ============================================================================
-- 0261_baton.sql — the baton durable-action runtime tables (docs/baton.md).
--
-- These coexist with the legacy actions.* engine during the migration: baton
-- owns its runtime tables in its own schema, while firm policy stays in
-- actions.policies / actions.policy_roles (reused, not duplicated). The final
-- cutover — when every door runs on baton — retires actions.runs/steps/
-- http_requests and this is the only runtime store left.
--
-- The CREATE TABLE block below is baton.ddl('baton') verbatim (pkgs/baton);
-- everything after the marker is the host's own RLS, grants, triggers, uid
-- default, FKs and search column, the way 0215 wrapped the old engine.
-- ============================================================================

SET LOCAL lock_timeout = '5s';

CREATE SCHEMA baton;
GRANT USAGE ON SCHEMA baton TO authenticated, service_role;

CREATE TABLE baton.runs (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,
  tenant_id int NOT NULL,
  action_key text NOT NULL,
  idempotency_key text NOT NULL,
  kind text NOT NULL DEFAULT 'action' CHECK (kind IN ('action', 'gate')),
  leaf boolean,                                             -- NULL until the first pass decides
  params jsonb NOT NULL DEFAULT '{}'::jsonb,
  params_hash text,
  result jsonb,
  meta jsonb NOT NULL DEFAULT '{}'::jsonb,
  parent_run_id bigint REFERENCES baton.runs(id) ON DELETE CASCADE,
  root_run_id bigint REFERENCES baton.runs(id) ON DELETE CASCADE,
  depth int NOT NULL DEFAULT 0,
  key text,                                                 -- memo key within the parent
  position int,                                             -- call order within the parent body
  after_keys text[] NOT NULL DEFAULT '{}',                  -- graph predecessors (children only)
  requested_by uuid,
  requested_at timestamptz NOT NULL DEFAULT now(),
  contact_id int,
  subject_kind text,
  subject_uid text,
  state_type text NOT NULL CHECK (state_type IN
    ('scheduled', 'pending', 'running', 'paused', 'completed', 'failed', 'cancelled', 'crashed')),
  state_name text NOT NULL,
  state_message text,
  state_at timestamptz NOT NULL DEFAULT now(),
  scheduled_at timestamptz,
  lease_token uuid,
  lease_owner text,
  lease_until timestamptz,
  timeout_at timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  passes int NOT NULL DEFAULT 0,
  attempt_count int NOT NULL DEFAULT 0,
  wait_started_at timestamptz,
  error text,
  case_no int,
  justification text,
  approver_role_ids int[] NOT NULL DEFAULT '{}',
  gate_roles int[],
  gate_message text,
  decision text CHECK (decision IN ('approved', 'rejected')),
  decided_by uuid,
  decided_at timestamptz,
  decision_note text,
  on_failure text,                                          -- how THIS run's parent treats its failure
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, idempotency_key),
  UNIQUE (parent_run_id, key),
  UNIQUE (parent_run_id, position),
  CHECK ((parent_run_id IS NULL) = (key IS NULL)),
  CHECK ((parent_run_id IS NULL) = (root_run_id IS NULL)),
  CHECK (kind <> 'gate' OR gate_roles IS NOT NULL),
  CHECK (state_type <> 'scheduled' OR scheduled_at IS NOT NULL),
  CHECK (state_type <> 'running' OR (lease_token IS NOT NULL AND lease_until IS NOT NULL))
);

CREATE INDEX runs_claim_idx ON baton.runs (scheduled_at, id) WHERE state_type = 'scheduled';
CREATE INDEX runs_lease_idx ON baton.runs (lease_until) WHERE state_type = 'running';
CREATE INDEX runs_timeout_idx ON baton.runs (timeout_at)
  WHERE timeout_at IS NOT NULL AND state_type IN ('scheduled', 'running', 'paused');
CREATE INDEX runs_tenant_action_idx ON baton.runs (tenant_id, action_key, id DESC)
  WHERE parent_run_id IS NULL;
CREATE INDEX runs_tenant_state_idx ON baton.runs (tenant_id, state_type, state_name)
  WHERE parent_run_id IS NULL;
CREATE INDEX runs_parent_idx ON baton.runs (parent_run_id, position) WHERE parent_run_id IS NOT NULL;
CREATE INDEX runs_root_idx ON baton.runs (root_run_id) WHERE root_run_id IS NOT NULL;
CREATE INDEX runs_open_children_idx ON baton.runs (parent_run_id)
  WHERE parent_run_id IS NOT NULL AND state_type NOT IN ('completed', 'failed', 'cancelled');
CREATE INDEX runs_contact_idx ON baton.runs (contact_id) WHERE contact_id IS NOT NULL;
CREATE INDEX runs_subject_idx ON baton.runs (tenant_id, subject_kind, subject_uid)
  WHERE subject_uid IS NOT NULL;
CREATE UNIQUE INDEX runs_case_no_idx ON baton.runs (tenant_id, case_no) WHERE case_no IS NOT NULL;
CREATE INDEX runs_inbox_idx ON baton.runs USING gin (approver_role_ids)
  WHERE state_type = 'paused' AND parent_run_id IS NULL;
CREATE INDEX runs_open_gate_idx ON baton.runs (parent_run_id)
  WHERE kind = 'gate' AND state_type = 'paused';
CREATE INDEX runs_attention_idx ON baton.runs (tenant_id, root_run_id)
  WHERE state_type = 'failed' AND state_name = 'NeedsAttention';

CREATE TABLE baton.attempts (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  run_id bigint NOT NULL REFERENCES baton.runs(id) ON DELETE CASCADE,
  root_run_id bigint NOT NULL,
  tenant_id int NOT NULL,
  attempt_no int NOT NULL,
  worker text,
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  duration_ms int,
  outcome text NOT NULL CHECK (outcome IN
    ('ok', 'skipped', 'wait', 'retry', 'failed', 'timed_out', 'crashed')),
  error text,
  error_type text,
  method text,
  url text,
  status_code int,
  request jsonb,
  response jsonb,
  UNIQUE (run_id, attempt_no)
);

CREATE INDEX attempts_run_idx ON baton.attempts (run_id, id);
CREATE INDEX attempts_root_idx ON baton.attempts (root_run_id, id);
CREATE INDEX attempts_tenant_idx ON baton.attempts (tenant_id, started_at DESC);

CREATE TABLE baton.events (
  id bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  tenant_id int NOT NULL,
  run_id bigint NOT NULL REFERENCES baton.runs(id) ON DELETE CASCADE,
  root_run_id bigint NOT NULL,
  event_type text NOT NULL,
  actor_id uuid,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX events_root_idx ON baton.events (root_run_id, id);
CREATE INDEX events_tenant_idx ON baton.events (tenant_id, id);

CREATE TABLE baton.subjects (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  run_id bigint NOT NULL REFERENCES baton.runs(id) ON DELETE CASCADE,
  tenant_id int NOT NULL,
  action_key text NOT NULL,
  kind text NOT NULL,
  uid text NOT NULL,
  entity_id bigint,
  blocking boolean NOT NULL DEFAULT false,
  UNIQUE (run_id, kind, uid)
);

CREATE INDEX subjects_run_idx ON baton.subjects (run_id);
CREATE INDEX subjects_lookup_idx ON baton.subjects (tenant_id, kind, uid);
CREATE UNIQUE INDEX subjects_one_open_idx ON baton.subjects (tenant_id, action_key, kind, uid)
  WHERE blocking;


-- ======== host additions (not shipped by the package) =======================

-- Public ids and timestamps, the platform conventions.
ALTER TABLE baton.runs ALTER COLUMN uid SET DEFAULT public.nanoid(12);

CREATE TRIGGER set_updated_at_baton_runs BEFORE UPDATE ON baton.runs
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Foreign keys into the app's own schemas (the package stays schema-agnostic).
ALTER TABLE baton.runs
  ADD CONSTRAINT runs_tenant_fk FOREIGN KEY (tenant_id) REFERENCES auth.tenants(id) ON DELETE CASCADE,
  ADD CONSTRAINT runs_requested_by_fk FOREIGN KEY (requested_by) REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD CONSTRAINT runs_decided_by_fk FOREIGN KEY (decided_by) REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD CONSTRAINT runs_contact_fk FOREIGN KEY (contact_id) REFERENCES crm.contacts(id) ON DELETE SET NULL;

-- Search text for the runs listing (uid, case number, action, subject). Generated, as 0249.
ALTER TABLE baton.runs
  ADD COLUMN _search text GENERATED ALWAYS AS (
    search.normalise(uid, case_no::text, action_key, subject_kind, subject_uid)
  ) STORED;
CREATE INDEX baton_runs_search_trgm ON baton.runs USING gin (_search gin_trgm_ops);

