ALTER TABLE baton.runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE baton.attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE baton.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE baton.subjects ENABLE ROW LEVEL SECURITY;

-- A run is readable by Graphene operators across the lineage, by its requester, and by anyone
-- whose contact scope covers its subject. Same shape as actions.runs (0215).
CREATE POLICY baton_runs_read ON baton.runs FOR SELECT TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR (
      tenant_id = ANY (auth.tenant_lineage())
      AND (
        requested_by = NULLIF(auth.jwt() ->> 'user_uuid', '')::uuid
        OR contact_id IS NULL
        OR contact_id = ANY (auth.contact_scope())
      )
    )
  );
CREATE POLICY baton_runs_write ON baton.runs FOR ALL TO authenticated
  USING (
    (auth.can_read_all() AND tenant_id = ANY (auth.tenant_lineage()))
    OR (
      tenant_id = ANY (auth.tenant_lineage())
      AND (
        requested_by = NULLIF(auth.jwt() ->> 'user_uuid', '')::uuid
        OR contact_id IS NULL
        OR contact_id = ANY (auth.contact_scope())
      )
    )
  )
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

CREATE POLICY baton_subjects_all ON baton.subjects FOR ALL TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()))
  WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));

-- Attempts and events are evidence: tenant-scoped to read, append-only and never blocked on write
-- (the same rule as audit.api_log — a caller with no claims must still be able to record one).
CREATE POLICY baton_attempts_read ON baton.attempts FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR (tenant_id IS NULL AND auth.is_system()));
CREATE POLICY baton_attempts_append ON baton.attempts FOR INSERT TO authenticated
  WITH CHECK (true);

CREATE POLICY baton_events_read ON baton.events FOR SELECT TO authenticated
  USING (tenant_id = ANY (auth.tenant_lineage()) OR (tenant_id IS NULL AND auth.is_system()));
CREATE POLICY baton_events_append ON baton.events FOR INSERT TO authenticated
  WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE ON baton.runs TO authenticated;
GRANT SELECT, INSERT, UPDATE ON baton.subjects TO authenticated;
GRANT SELECT, INSERT ON baton.attempts TO authenticated;
GRANT SELECT, INSERT ON baton.events TO authenticated;

GRANT ALL ON baton.runs TO service_role;
GRANT ALL ON baton.attempts TO service_role;
GRANT ALL ON baton.events TO service_role;
GRANT ALL ON baton.subjects TO service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA baton TO authenticated, service_role;

ALTER TABLE baton.runs FORCE ROW LEVEL SECURITY;
ALTER TABLE baton.attempts FORCE ROW LEVEL SECURITY;
ALTER TABLE baton.events FORCE ROW LEVEL SECURITY;
ALTER TABLE baton.subjects FORCE ROW LEVEL SECURITY;
