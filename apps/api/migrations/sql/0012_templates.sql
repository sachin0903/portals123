-- 0012_templates: the template + dataset authoring tables (generation's authoring half).
--
-- Lands the persistence for the platform template editor + datasets (docs/document-generation.md
-- §9/§17), previously frontend/mock only. These four tables FK only auth.* (+ each other + the
-- existing documents.files/documents), so they land BEFORE 0002_platform_crm — exactly as the spec
-- notes. The async render pipeline (PGMQ worker, WeasyPrint, POST /documents generate) is a SEPARATE
-- later slice; nothing here renders.
--
-- Divergences from the spec DDL, on purpose, to match the portal's shipped editor:
--   * template_versions.schema holds the portal's TemplateContent (pages→blocks) the Svelte editor
--     produces — not the prototype's GrapesJS {html,css,components}. It's opaque jsonb either way.
--   * documents.templates carries linked_datasets (text[] of dataset codes) + input_form_code
--     (a documents.forms code) at the TEMPLATE level, matching the portal's Template type and the
--     detail page's "Inputs & data" area (the spec kept dataset links in the version schema).
--
-- STAFF-ONLY RLS (tenant lineage) — templates/datasets are firm assets; clients never author them.

CREATE TYPE documents.template_status AS ENUM ('draft', 'published', 'archived');
CREATE TYPE documents.renderer        AS ENUM ('weasy', 'chromium');
CREATE TYPE documents.dataset_source  AS ENUM ('csv', 'sql', 'static', 'questionnaire');
CREATE TYPE documents.dataset_scope   AS ENUM ('subject', 'collection', 'global');

-- ── templates ────────────────────────────────────────────────────────────────
CREATE TABLE documents.templates (
    id                           int         PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid                          text        NOT NULL UNIQUE,
    tenant_id                    int         NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    code                         text        NOT NULL,
    name                         text        NOT NULL,
    document_type                text        NOT NULL,
    description                  text,
    current_published_version_id int,        -- deferred FK added below
    linked_datasets              text[]      NOT NULL DEFAULT '{}',  -- dataset codes (portal shape)
    input_form_code              text,       -- a documents.forms code (the §9.1 form link)
    created_by                   uuid        NOT NULL REFERENCES auth.users(id),
    archived_at                  timestamptz,
    created_at                   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, code)
);
CREATE INDEX templates_tenant_type_idx ON documents.templates(tenant_id, document_type);

-- ── template_versions ─────────────────────────────────────────────────────────
-- Immutable once status = 'published'. `schema` is the editor's TemplateContent (opaque jsonb).
CREATE TABLE documents.template_versions (
    id             int                       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid            text                      NOT NULL UNIQUE,
    tenant_id      int                       NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    template_id    int                       NOT NULL REFERENCES documents.templates(id) ON DELETE CASCADE,
    version_number integer                   NOT NULL,
    status         documents.template_status NOT NULL DEFAULT 'draft',
    renderer       documents.renderer        NOT NULL DEFAULT 'weasy',
    schema         jsonb                     NOT NULL DEFAULT '{}'::jsonb,
    input_schema   jsonb,                    -- derived on publish (generation slice)
    fixtures       jsonb,                    -- derived on publish (generation slice)
    metadata       jsonb,
    created_by     uuid                      NOT NULL REFERENCES auth.users(id),
    published_by   uuid                      REFERENCES auth.users(id),
    published_at   timestamptz,
    created_at     timestamptz               NOT NULL DEFAULT now(),
    UNIQUE (template_id, version_number)
);
CREATE INDEX template_versions_template_idx ON documents.template_versions(template_id);

-- Deferred FK templates → template_versions (circular; both rows insert in one txn on first publish).
ALTER TABLE documents.templates
    ADD CONSTRAINT fk_current_published_version
    FOREIGN KEY (current_published_version_id)
    REFERENCES documents.template_versions(id)
    DEFERRABLE INITIALLY DEFERRED;

-- FK documents.documents.template_version_id → template_versions (column shipped as a plain int in
-- 0002; the constraint lands here now the target exists).
ALTER TABLE documents.documents
    ADD CONSTRAINT fk_template_version
    FOREIGN KEY (template_version_id) REFERENCES documents.template_versions(id);

-- ── datasets ────────────────────────────────────────────────────────────────
CREATE TABLE documents.datasets (
    id            int                      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid           text                     NOT NULL UNIQUE,
    tenant_id     int                      NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    code          text                     NOT NULL,
    name          text                     NOT NULL,
    description   text,
    source_type   documents.dataset_source NOT NULL,
    scope         documents.dataset_scope  NOT NULL,
    output_schema jsonb,
    parameters    jsonb,
    enabled       boolean                  NOT NULL DEFAULT true,
    created_by    uuid                     NOT NULL REFERENCES auth.users(id),
    created_at    timestamptz              NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, code)
);
CREATE INDEX datasets_tenant_idx ON documents.datasets(tenant_id);

-- ── dataset_versions ──────────────────────────────────────────────────────────
-- source_type denormalised so the exactly-one-source CHECK needs no join. Reuses template_status.
CREATE TABLE documents.dataset_versions (
    id                int                       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uid               text                      NOT NULL UNIQUE,
    tenant_id         int                       NOT NULL REFERENCES auth.tenants(id) ON DELETE CASCADE,
    dataset_id        int                       NOT NULL REFERENCES documents.datasets(id) ON DELETE CASCADE,
    version_number    integer                   NOT NULL,
    status            documents.template_status NOT NULL DEFAULT 'draft',
    source_type       documents.dataset_source  NOT NULL,
    csv_file_id       uuid                      REFERENCES documents.files(id),
    sql_query         text,
    static_data       jsonb,
    questionnaire_uid text,
    created_by        uuid                      NOT NULL REFERENCES auth.users(id),
    published_at      timestamptz,
    created_at        timestamptz               NOT NULL DEFAULT now(),
    UNIQUE (dataset_id, version_number),
    CHECK (
        (source_type = 'csv'           AND csv_file_id       IS NOT NULL AND sql_query IS NULL AND static_data IS NULL AND questionnaire_uid IS NULL) OR
        (source_type = 'sql'           AND sql_query         IS NOT NULL AND csv_file_id IS NULL AND static_data IS NULL AND questionnaire_uid IS NULL) OR
        (source_type = 'static'        AND static_data       IS NOT NULL AND csv_file_id IS NULL AND sql_query IS NULL AND questionnaire_uid IS NULL) OR
        (source_type = 'questionnaire' AND questionnaire_uid IS NOT NULL AND csv_file_id IS NULL AND sql_query IS NULL AND static_data IS NULL)
    )
);
CREATE INDEX dataset_versions_dataset_idx ON documents.dataset_versions(dataset_id);

-- ── RLS + grants (claim-driven, per 0001) ─────────────────────────────────────
-- Staff-scoped; no client branch (clients don't author templates/datasets).
ALTER TABLE documents.templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents.templates FORCE ROW LEVEL SECURITY;
CREATE POLICY templates_read ON documents.templates FOR SELECT TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()));
CREATE POLICY templates_write ON documents.templates FOR ALL TO authenticated
    USING (tenant_id = ANY (auth.tenant_lineage()))
    WITH CHECK (tenant_id = ANY (auth.tenant_lineage()));
GRANT SELECT, INSERT, UPDATE, DELETE ON documents.templates TO authenticated;
GRANT ALL ON documents.templates TO service_role;

