"""Regenerate ``models/raw_reports.py`` — one model per SEI report.

    uv run python scripts/generate_raw_models.py
    uv run python scripts/generate_raw_models.py --check   # CI: fail if out of date

The raw layer is 47 near-identical models, so it is generated rather than
hand-written: the shape lives in the template here and the output is checked in and
reviewed as a diff. Run this after editing the template, after
``scripts/profile_schema.py`` changes a declared type, or after SEI adds a report to
``KNOWN_REPORTS``.

**Why each model's SQL is written out in full rather than shared.** interlace
fingerprints a Python model from ``inspect.getsource(fn)`` — the decorated function
and nothing it calls. A single generic extractor therefore fingerprints *identically*
for all 47 reports, and edits to the read logic behind it are invisible: ``plan``
reports no change, and ``run`` merges into the existing physical table, silently
keeping the old column types. Declared types could not land at all that way. Writing
the SQL inline puts every semantic choice inside the fingerprinted source, so
changing a column's type changes that model's fingerprint and rebuilds its table.

(SQL models would fingerprint correctly too, but interlace only interpolates
``${VAR}`` in ``interlace.yaml`` — not in ``.sql`` files — and these models need the
bucket and SEI environment from settings at run time.)
"""

from __future__ import annotations

import argparse
import logging
import subprocess
import sys
from pathlib import Path

from sei_sync.columns import replace_clauses
from sei_sync.reports import DELIMITER, KNOWN_REPORTS, table_name

logger = logging.getLogger("sei_sync.generate")

_MODULE = Path(__file__).resolve().parent.parent / "models" / "raw_reports.py"

# Reports SEI sends as same-day deltas rather than a full daily snapshot. Both are
# append-only here; the distinction matters to the consumption layer, which applies
# *_Upd rows over the base header/detail tables.
DELTA_REPORTS = frozenset({"EODChangedPositions", "TransactionDetailUpd", "TransactionHeaderUpd"})

# Reference carries the dimensions (firms, subfirms, DSR teams, currencies…) that
# everything downstream joins to, so it is declared first and so builds first.
_EARLY = ("Reference",)

_HEADER = '''"""Raw layer: one model per SEI report — GENERATED, do not edit.

Regenerate with ``uv run python scripts/generate_raw_models.py``; the template and
the reasoning live there. ``raw.files`` — the model every one of these depends on —
lands each drop as ``sei/staged/{{table}}/dt={{YYYY-MM-DD}}/{{name}}.out``,
pipe-delimited with a header row, and these models read those into the DuckLake
warehouse.

Four decisions worth knowing:

**The pull is upstream, not a separate cron.** ``depends_on=("raw.files",)`` puts the
SFTP fetch and PGP decrypt in the same dependency graph as the reads, so a run cannot
read a drop it has not fetched. It is a dependency for *ordering* only — these models
read object storage directly rather than taking the ledger as a parameter, because they
glob whole partitions and never need to know which individual files are new.

**Read as text, materialise as types.** SEI ships untyped text, and letting DuckDB
sniff would drift the schema between drops — a column that is blank on Monday sniffs
as VARCHAR and as BIGINT on Tuesday. So the read is ``all_varchar`` and each model
converts the columns we have declared a type for (``sei_sync.schema``, generated by
profiling the corpus), leaving identifiers and numeric code enumerations as text.
The raw tables therefore carry real DATE / DECIMAL / BOOLEAN / TIMESTAMP columns and
the consumption layer filters and joins them directly instead of casting.

Dates in particular have to be *parsed*: SEI writes ``20260327``, and
``try_cast('20260327' AS DATE)`` is NULL, so casting downstream produced silently
empty date columns.

**The key is (source file, row number), not a business key.** Every staged object is
immutable, so that pair is a stable row identity, which makes re-reading a date
idempotent without knowing the natural key of all {count} reports — SEI documents them
inconsistently and several have none. Business keys are applied downstream, where
they are understood.

**Reads are incremental on ``dt``.** interlace injects the max ``dt`` from the previous
materialisation, so a nightly run touches only the new partitions rather than
re-reading the whole history (~30MB/day, growing without bound).

**The read assumes UTF-8, and the PULL is what makes that safe.** DuckDB's ``read_csv``
refuses a file that is not the encoding it was told — ``Invalid unicode (byte sequence
mismatch)`` — which fails the whole model, and a failed model reads as "this firm has no
data". SEI's corpus is genuinely mixed: ``Clients``/``ContactDetails`` have arrived as
Latin-1, while ``CostsCharges``/``RoleDetail`` are valid UTF-8 carrying bytes in
``0x80``-``0x9F`` that strict ISO-8859-1 rejects. DuckDB offers utf-8, utf-16 and latin-1
and nothing else, so no setting here covers both, and a per-report setting does not
either — ``Clients`` was Latin-1 one day and clean ASCII the next.

So ``sei_sync.reports.to_utf8`` normalises at the staging boundary instead (UTF-8 first so
a clean file passes through byte-identical, then CP1252), and the byte-exact evidence stays
in the ``sftp/`` archive. That reasoning lives there; these models just read UTF-8.
"""

from __future__ import annotations

from typing import Any

import pyarrow as pa
from interlace import model

from sei_sync.raw_read import read_report
'''

_MODEL = '''

@model(
    name="raw.{table}",
    strategy="merge",
    key=("_source_file", "_row"),
    cursor="dt",
    depends_on=("raw.files",),
    schedule={{"cron": "30 5 * * 2-6"}},
    tags=("sei", "raw", "{tag}"),
    description="SEI {report} report ({kind})",
)
async def raw_{table}(cursor: Any) -> pa.Table:
    return await read_report(
        "{table}",
        cursor,
        # The shape of the empty table when SEI has never delivered this report. Stated HERE, in
        # the model, because interlace fingerprints a model from its own source and nothing it
        # calls — a shape declared only in the helper cannot rebuild the table it got wrong.
        empty_columns=("_source_file", "_row", "dt"),
        sql="""
        SELECT
            * EXCLUDE (filename){replace}
            filename AS _source_file,
            row_number() OVER (PARTITION BY filename) AS _row
        FROM read_csv(
            's3://{{bucket}}/sei/staged/{table}/dt=*/*.out',
            delim = '{delimiter}',
            header = true,
            all_varchar = true,
            filename = true,
            hive_partitioning = true,
            union_by_name = true,
            quote = '',
            escape = '',
            null_padding = true,
            max_line_size = 16000000
        )
        """,
    )
'''


_INDENT = " " * 16
_LINE_LIMIT = 100


def _format_clause(clause: str) -> str:
    """Indent one REPLACE clause, wrapping before ``AS`` if the line would be too long.

    The clauses sit inside a Python string, so the repo's line-length limit still counts
    them; SEI's widest column name is 39 characters and a BOOLEAN decode of it does not
    fit. Wrapping at ``AS`` keeps the expression on one readable line either way.
    """
    # The join appends a comma, so a clause has one character less to play with.
    budget = _LINE_LIMIT - 1
    if len(_INDENT + clause) <= budget or " AS " not in clause:
        return _INDENT + clause

    expression, _, alias = clause.rpartition(" AS ")
    lines = [f"{_INDENT}{expression}", f"{_INDENT}    AS {alias}"]
    if len(lines[0]) > budget and " WHEN " in expression:
        # A BOOLEAN decode of the widest column names is still too long on its own.
        head, _, rest = expression.partition(" WHEN ")
        lines[:1] = [f"{_INDENT}{head}", f"{_INDENT}    WHEN {rest}"]
    return "\n".join(lines)


def render_model(report: str) -> str:
    """One model's source. The SQL is inline so it is part of the fingerprint."""
    table = table_name(report)
    clauses = replace_clauses(table)
    if clauses:
        body = ",\n".join(_format_clause(clause) for clause in clauses)
        replace = f" REPLACE (\n{body}\n            ),"
    else:
        replace = ","  # nothing declared for this report
    return _MODEL.format(
        report=report,
        table=table,
        delimiter=DELIMITER,
        tag="delta" if report in DELTA_REPORTS else "snapshot",
        kind="daily delta" if report in DELTA_REPORTS else "daily snapshot",
        replace=replace,
    )


def render() -> str:
    """The module source, already `ruff format`-clean.

    Formatting is applied here rather than left to the caller so that the generated file,
    the `--check` comparison and `ruff format --check .` all agree on one byte sequence.
    Without it the writer emitted one form, the formatter rewrote it, and the staleness
    test then reported a file it had just regenerated as stale.
    """
    ordered = sorted(KNOWN_REPORTS, key=lambda r: (r not in _EARLY, r))
    source = _HEADER.format(count=len(KNOWN_REPORTS)) + "".join(
        render_model(report) for report in ordered
    )
    formatted = subprocess.run(  # noqa: S603
        ["ruff", "format", "--stdin-filename", str(_MODULE), "-"],  # noqa: S607
        input=source,
        capture_output=True,
        text=True,
        check=False,
    )
    return formatted.stdout if formatted.returncode == 0 else source


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the module is stale")
    args = parser.parse_args(argv)

    source = render()
    typed = sum(len(replace_clauses(table_name(r))) for r in KNOWN_REPORTS)

    if args.check:
        current = _MODULE.read_text(encoding="utf-8") if _MODULE.exists() else ""
        if current != source:
            logger.error(
                "%s is out of date — run `uv run python scripts/generate_raw_models.py`",
                _MODULE.name,
            )
            return 1
        logger.info("%s is up to date", _MODULE.name)
        return 0

    _MODULE.write_text(source, encoding="utf-8")
    logger.info(
        "wrote %d models to %s (%d typed columns converted)",
        len(KNOWN_REPORTS),
        _MODULE.name,
        typed,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
