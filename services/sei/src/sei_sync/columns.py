"""Turning SEI's untyped text into the raw layer's declared types.

SEI ships every column of every report as text: dates as ``20260327``, money as
``123.4500``, booleans as ``Y``/``N``. The raw models read that as VARCHAR — no
sniffing, because a column that is blank on Monday and populated on Tuesday would
otherwise change type mid-week — and then convert the columns we have declared a
type for, so ``raw.*`` materialises real DATE, DECIMAL, BOOLEAN and TIMESTAMP.

The types live in :mod:`sei_sync.schema`, generated by profiling the staged corpus
and reviewed as a diff. Anything not declared there stays VARCHAR; see that module
for why identifiers and numeric code enumerations deliberately do.

Two things this module is careful about:

**Dates need parsing, not casting.** ``try_cast('20260327' AS DATE)`` is NULL in
DuckDB — the format has no separators — so every date goes through ``strptime``
with an explicit format. Casting is what silently produced all-NULL date columns.

**Only the typed columns are named.** The conversions are emitted as a DuckDB
``* REPLACE (…)`` list, so a 152-column report contributes the handful of lines it
actually needs rather than a full restatement of its schema. Empty fields are
already NULL by the time they get here (DuckDB's CSV reader does that), so
untyped columns need no expression at all.
"""

from __future__ import annotations

from sei_sync.schema import COLUMN_TYPES, DATE_FORMAT

# Money and quantity. 28 integer digits before the 10 decimal places — SEI's widest
# value is nowhere near it, and one scale everywhere means no rescaling when facts
# are joined.
DECIMAL_TYPE = "DECIMAL(38, 10)"

# SEI writes its two timestamp columns with an offset and, in one case, on a
# 12-hour clock — `2024-10-16 02:00:07 PM +01:00` vs `2025-07-30 19:11:34 +00:00`.
# Both are real instants, so both land as TIMESTAMP WITH TIME ZONE; only the source
# format differs, and neither can be reached by CAST.
TIMESTAMPTZ_FORMATS = {
    "TIMESTAMPTZ": "%Y-%m-%d %H:%M:%S %z",
    "TIMESTAMPTZ_12H": "%Y-%m-%d %I:%M:%S %p %z",
}

DECLARED_TYPES = frozenset({"DATE", "DECIMAL", "BOOLEAN", *TIMESTAMPTZ_FORMATS})


def _quote(column: str) -> str:
    """Quote an identifier. SEI's headers are SHOUTY_SNAKE and would otherwise fold."""
    return '"' + column.replace('"', '""') + '"'


def cast_expression(column: str, declared: str) -> str:
    """The SQL converting one raw text column to its declared type.

    Every branch is lenient (``try_*``): one malformed value in a nightly drop must
    not fail the whole report. That is only safe because the conversion is audited —
    see :func:`loss_audit`.
    """
    quoted = _quote(column)
    if declared == "DATE":
        return f"try_strptime({quoted}, '{DATE_FORMAT}')::DATE"
    if declared in TIMESTAMPTZ_FORMATS:
        return f"try_strptime({quoted}, '{TIMESTAMPTZ_FORMATS[declared]}')"
    if declared == "DECIMAL":
        return f"try_cast({quoted} AS {DECIMAL_TYPE})"
    if declared == "BOOLEAN":
        # Not `= 'Y'`: that maps both 'N' and an absent value to false, claiming SEI
        # answered a flag it never sent.
        return f"CASE {quoted} WHEN 'Y' THEN true WHEN 'N' THEN false END"
    raise ValueError(f"no conversion for declared type {declared!r} on column {column!r}")


def typed_columns(table: str) -> dict[str, str]:
    """The declared non-VARCHAR columns of one report, in a stable order."""
    return dict(sorted(COLUMN_TYPES.get(table, {}).items()))


def replace_clauses(table: str) -> list[str]:
    """``* REPLACE`` entries converting this report's declared columns.

    Empty when the report has nothing typed, in which case the model selects the
    source unchanged.
    """
    return [
        f"{cast_expression(column, declared)} AS {_quote(column)}"
        for column, declared in typed_columns(table).items()
    ]


def loss_audit(table: str) -> str | None:
    """Query counting values that failed to convert, per typed column.

    ``{source}`` is substituted with the relation to audit. Returns one row with one
    BIGINT column per typed column, named after it; None when nothing is typed.

    This is the guard that turns a lenient conversion into an honest one: an
    all-NULL date column shows up here as a loss equal to the row count, on the
    first night, instead of in a review months later.
    """
    typed = typed_columns(table)
    if not typed:
        return None
    counts = [
        f"count(*) FILTER (WHERE {_quote(column)} IS NOT NULL "
        f"AND ({cast_expression(column, declared)}) IS NULL) AS {_quote(column)}"
        for column, declared in typed.items()
    ]
    # Column names come from the generated schema and the expressions from this module;
    # `{source}` is filled by the caller with a relation it built. No caller input.
    return "SELECT " + ", ".join(counts) + " FROM {source}"  # noqa: S608
