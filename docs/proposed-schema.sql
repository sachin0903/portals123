-- ---- updated_at triggers on every table that has the column ----
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.table_schema, c.table_name FROM information_schema.columns c
    JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.column_name = 'updated_at' AND t.table_type = 'BASE TABLE'
      AND c.table_schema IN ('auth','platform','crm','compliance','forms','workflow','documents','integrations','events')
  LOOP
    EXECUTE format('CREATE TRIGGER set_updated_at BEFORE UPDATE ON %I.%I '
                   'FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', r.table_schema, r.table_name);
  END LOOP;
END $$;

-- ---- FORCE RLS so even the owner (migrator) is bound ----
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT schemaname, tablename FROM pg_tables
    WHERE schemaname IN ('auth','platform','crm','compliance','forms','workflow','documents','integrations','events','audit')
  LOOP
    EXECUTE format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY', r.schemaname, r.tablename);
  END LOOP;
END $$;

