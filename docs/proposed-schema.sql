-- NORTH-STAR SCHEMA (REFERENCE) -- Graphene Platform
-- Loads clean on PostgreSQL 18. This is the validated reference the forward
-- migrations are sliced from (see docs/data-architecture.md section 8); it is NOT
-- applied directly. Reconciled to the ACCEPTED decisions and the implemented
-- 0001_auth_core:
--   * auth.users is pure identity (no irn/title -- those live on platform.advisers);
--     auth.uid() reads the 'user_uuid' claim; auth.users READ is scoped to
--     same-tenant + self (not USING(true)); auth.tenants stays USING(true).
--   * lineage trigger has a cycle guard + descendant recompute on re-parent.
--   * the login<->party bridge is crm.contact_users (crm.contacts.user_id is gone);
--     staff assignment is crm.client_advisers; advised/exec-only is crm.contacts.service_type.
--   * platform.transactions (the realised-transaction fact) + model_platforms; advisers.
--   * audit.log is append-only + the generic audit.record()/attach() DML trigger.
--   * claim-driven RLS helpers incl. can_read_all/contact_scope/account_scope and the
--     SECURITY DEFINER auth.resolve_claims() request-claim minter (full version here,
--     filling contact_ids/account_ids); cross-RLS definer helpers are owned by the
--     BYPASSRLS service_role.
-- Schemas: auth, platform, crm, compliance, forms, workflow, documents, integrations, events, audit.
-- NOTE (Decision 7): the SIPP *domain* tables shown below under integrations.* are
-- relocated to a `pensions.*` schema in 0003 (the money ledger stays in platform.*);
-- they are kept here under integrations for continuity with the original reference.
-- ============================================================================

