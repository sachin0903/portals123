-- baton's own tables. {{s}} is the schema the host renders into (portals: `actions`).
--
-- This file is generic: no RLS, no grants, no uid defaults, no FKs into app schemas, no
-- updated_at trigger. The host migration adds those around it (see README, "DDL contract").
-- CREATE TABLE is deliberately NOT `IF NOT EXISTS`: a clash with pre-existing tables of the
-- same name must fail loudly, so the host renames them out of the way first.

CREATE TABLE {{s}}.runs (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL UNIQUE,
  tenant_id int NOT NULL,
  action_key text NOT NULL,
  idempotency_key text NOT NULL,
  kind text NOT NULL DEFAULT 'action' CHECK (kind IN ('action', 'gate')),
  leaf boolean,                                             -- NULL until the first pass decides
  params jsonb NOT NULL DEFAULT '{}'::jsonb,
  params_hash text,
  result jsonb,
  meta jsonb NOT NULL DEFAULT '{}'::jsonb,
  parent_run_id bigint REFERENCES {{s}}.runs(id) ON DELETE CASCADE,
  root_run_id bigint REFERENCES {{s}}.runs(id) ON DELETE CASCADE,
  depth int NOT NULL DEFAULT 0,
  key text,                                                 -- memo key within the parent
  position int,                                             -- call order within the parent body
  after_keys text[] NOT NULL DEFAULT '{}',                  -- graph predecessors (children only)
  requested_by uuid,
  requested_at timestamptz NOT NULL DEFAULT now(),
  contact_id int,
  subject_kind text,
  subject_uid text,
  state_type text NOT NULL CHECK (state_type IN
    ('scheduled', 'pending', 'running', 'paused', 'completed', 'failed', 'cancelled', 'crashed')),
  state_name text NOT NULL,
  state_message text,
  state_at timestamptz NOT NULL DEFAULT now(),
  scheduled_at timestamptz,
  lease_token uuid,
  lease_owner text,
  lease_until timestamptz,
  timeout_at timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  passes int NOT NULL DEFAULT 0,
  attempt_count int NOT NULL DEFAULT 0,
  wait_started_at timestamptz,
  error text,
  case_no int,
  justification text,
  approver_role_ids int[] NOT NULL DEFAULT '{}',
  gate_roles int[],
  gate_message text,
  decision text CHECK (decision IN ('approved', 'rejected')),
  decided_by uuid,
  decided_at timestamptz,
  decision_note text,
  on_failure text,                                          -- how THIS run's parent treats its failure
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, idempotency_key),
  UNIQUE (parent_run_id, key),
  UNIQUE (parent_run_id, position),
  CHECK ((parent_run_id IS NULL) = (key IS NULL)),
  CHECK ((parent_run_id IS NULL) = (root_run_id IS NULL)),
  CHECK (kind <> 'gate' OR gate_roles IS NOT NULL),
  CHECK (state_type <> 'scheduled' OR scheduled_at IS NOT NULL),
  CHECK (state_type <> 'running' OR (lease_token IS NOT NULL AND lease_until IS NOT NULL))
);

CREATE INDEX runs_claim_idx ON {{s}}.runs (scheduled_at, id) WHERE state_type = 'scheduled';
CREATE INDEX runs_lease_idx ON {{s}}.runs (lease_until) WHERE state_type = 'running';
CREATE INDEX runs_timeout_idx ON {{s}}.runs (timeout_at)
  WHERE timeout_at IS NOT NULL AND state_type IN ('scheduled', 'running', 'paused');
CREATE INDEX runs_tenant_action_idx ON {{s}}.runs (tenant_id, action_key, id DESC)
  WHERE parent_run_id IS NULL;
CREATE INDEX runs_tenant_state_idx ON {{s}}.runs (tenant_id, state_type, state_name)
  WHERE parent_run_id IS NULL;
CREATE INDEX runs_parent_idx ON {{s}}.runs (parent_run_id, position) WHERE parent_run_id IS NOT NULL;
CREATE INDEX runs_root_idx ON {{s}}.runs (root_run_id) WHERE root_run_id IS NOT NULL;
CREATE INDEX runs_open_children_idx ON {{s}}.runs (parent_run_id)
  WHERE parent_run_id IS NOT NULL AND state_type NOT IN ('completed', 'failed', 'cancelled');
CREATE INDEX runs_contact_idx ON {{s}}.runs (contact_id) WHERE contact_id IS NOT NULL;
CREATE INDEX runs_subject_idx ON {{s}}.runs (tenant_id, subject_kind, subject_uid)
  WHERE subject_uid IS NOT NULL;
CREATE UNIQUE INDEX runs_case_no_idx ON {{s}}.runs (tenant_id, case_no) WHERE case_no IS NOT NULL;
CREATE INDEX runs_inbox_idx ON {{s}}.runs USING gin (approver_role_ids)
  WHERE state_type = 'paused' AND parent_run_id IS NULL;
CREATE INDEX runs_open_gate_idx ON {{s}}.runs (parent_run_id)
  WHERE kind = 'gate' AND state_type = 'paused';
CREATE INDEX runs_attention_idx ON {{s}}.runs (tenant_id, root_run_id)
  WHERE state_type = 'failed' AND state_name = 'NeedsAttention';

CREATE TABLE {{s}}.attempts (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  run_id bigint NOT NULL REFERENCES {{s}}.runs(id) ON DELETE CASCADE,
  root_run_id bigint NOT NULL,
  tenant_id int NOT NULL,
  attempt_no int NOT NULL,
  worker text,
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  duration_ms int,
  outcome text NOT NULL CHECK (outcome IN
    ('ok', 'skipped', 'wait', 'retry', 'failed', 'timed_out', 'crashed')),
  error text,
  error_type text,
  method text,
  url text,
  status_code int,
  request jsonb,
  response jsonb,
  UNIQUE (run_id, attempt_no)
);

CREATE INDEX attempts_run_idx ON {{s}}.attempts (run_id, id);
CREATE INDEX attempts_root_idx ON {{s}}.attempts (root_run_id, id);
CREATE INDEX attempts_tenant_idx ON {{s}}.attempts (tenant_id, started_at DESC);

CREATE TABLE {{s}}.events (
  id bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  tenant_id int NOT NULL,
  run_id bigint NOT NULL REFERENCES {{s}}.runs(id) ON DELETE CASCADE,
  root_run_id bigint NOT NULL,
  event_type text NOT NULL,
  actor_id uuid,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX events_root_idx ON {{s}}.events (root_run_id, id);
CREATE INDEX events_tenant_idx ON {{s}}.events (tenant_id, id);

CREATE TABLE {{s}}.subjects (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  run_id bigint NOT NULL REFERENCES {{s}}.runs(id) ON DELETE CASCADE,
  tenant_id int NOT NULL,
  action_key text NOT NULL,
  kind text NOT NULL,
  uid text NOT NULL,
  entity_id bigint,
  blocking boolean NOT NULL DEFAULT false,
  UNIQUE (run_id, kind, uid)
);

CREATE INDEX subjects_run_idx ON {{s}}.subjects (run_id);
CREATE INDEX subjects_lookup_idx ON {{s}}.subjects (tenant_id, kind, uid);
CREATE UNIQUE INDEX subjects_one_open_idx ON {{s}}.subjects (tenant_id, action_key, kind, uid)
  WHERE blocking;
