/** The reference-table symbol for an ISO code, or `undefined` when the seed does not list it. */
export function currencySymbol(code: string | null | undefined): string | undefined {
	const key = (code ?? '').trim().toUpperCase();
	return key ? CURRENCY_SYMBOLS[key] : undefined;
}
